import {
  completeProjectConfig,
  describe,
  expect,
  fs,
  generateMasterConfigs,
  it,
  os,
  path,
  repoRoot,
  verifyMasterConfigs,
} from "./test-support.js";

describe("regenerate and an edited root .tiltignore", () => {
  const setup = async () => {
    const projectRoot = fs.mkdtempSync(path.join(os.tmpdir(), "flisk-regen-tiltignore-"));
    fs.mkdirSync(path.join(projectRoot, ".flisk"), { recursive: true });
    fs.writeFileSync(
      path.join(projectRoot, ".flisk", "project.json"),
      JSON.stringify(completeProjectConfig("regen-tiltignore")),
    );
    return projectRoot;
  };
  const withEnv = async (fn: () => Promise<void>) => {
    const old = process.env.FLISK_EXTENSION_SOURCE;
    process.env.FLISK_EXTENSION_SOURCE = repoRoot;
    try {
      await fn();
    } finally {
      if (old === undefined) delete process.env.FLISK_EXTENSION_SOURCE;
      else process.env.FLISK_EXTENSION_SOURCE = old;
    }
  };

  const writeUnsafeApiManifest = (projectRoot: string, relativeDir: string): string => {
    const manifest = path.join(projectRoot, relativeDir, "service.json");
    fs.mkdirSync(path.dirname(manifest), { recursive: true });
    fs.writeFileSync(
      manifest,
      JSON.stringify({
        schemaVersion: 1,
        appName: "api",
        appType: "backend",
        stack: "shop",
        port: 4000,
        healthCheckPath: "/health\n    privileged: true",
      }),
    );
    return `${relativeDir.split(path.sep).join("/")}/service.json`;
  };

  it("refuses to generate when a service.json value would add keys to the compose file (GHSA-phgf-pww4-7jxc)", async () => {
    const projectRoot = await setup();
    try {
      const manifest = writeUnsafeApiManifest(projectRoot, "services/shop/api");

      await withEnv(async () => {
        await expect(generateMasterConfigs(projectRoot)).rejects.toThrow(
          `Refusing to generate config from unsafe service.json values:\n  ${manifest}.healthCheckPath`,
        );
      });
      expect(fs.existsSync(path.join(projectRoot, ".flisk", ".flisk-out"))).toBe(false);
    } finally {
      fs.rmSync(projectRoot, { recursive: true, force: true });
    }
  });

  it("does not validate a service.json under a skipped build folder (#3817)", async () => {
    const projectRoot = await setup();
    try {
      writeUnsafeApiManifest(projectRoot, "services/shop/api/target/debug");

      await withEnv(async () => {
        await generateMasterConfigs(projectRoot);
      });

      const tiltfile = fs.readFileSync(
        path.join(projectRoot, ".flisk", ".flisk-out", "Tiltfile"),
        "utf-8",
      );
      expect(tiltfile).toContain("regen-tiltignore");
      expect(tiltfile).not.toContain("target/debug");
    } finally {
      fs.rmSync(projectRoot, { recursive: true, force: true });
    }
  });

  it("validates a skipped folder when discovery.paths names it literally (#3817)", async () => {
    const projectRoot = await setup();
    try {
      const configPath = path.join(projectRoot, ".flisk", "project.json");
      const config = JSON.parse(fs.readFileSync(configPath, "utf-8"));
      config.discovery.paths = ["services/shop/api/target/*"];
      fs.writeFileSync(configPath, JSON.stringify(config));

      const manifest = writeUnsafeApiManifest(projectRoot, "services/shop/api/target/debug");

      await withEnv(async () => {
        await expect(generateMasterConfigs(projectRoot)).rejects.toThrow(
          `Refusing to generate config from unsafe service.json values:\n  ${manifest}.healthCheckPath`,
        );
      });
    } finally {
      fs.rmSync(projectRoot, { recursive: true, force: true });
    }
  });

  it("restores an edited Flisk-generated root .tiltignore only when discarding hand edits", async () => {
    const projectRoot = await setup();
    try {
      await withEnv(async () => {
        await generateMasterConfigs(projectRoot);
        const target = path.join(projectRoot, ".tiltignore");
        const generated = fs.readFileSync(target, "utf-8");
        expect(generated).toContain("SYSTEM-GENERATED BY Flisk CLI");

        fs.writeFileSync(target, `${generated}my-extra-dir/\n`);
        expect(verifyMasterConfigs(projectRoot).errors.join("\n")).toContain(
          "Out of sync: .tiltignore",
        );

        // Plain generation (what `flisk project --yes` does) does not clobber the edit.
        await generateMasterConfigs(projectRoot);
        expect(fs.readFileSync(target, "utf-8")).toBe(`${generated}my-extra-dir/\n`);

        // `flisk config regenerate` discards it.
        await generateMasterConfigs(projectRoot, { discardHandEdits: true });
        expect(fs.readFileSync(target, "utf-8")).toBe(generated);
        const result = verifyMasterConfigs(projectRoot);
        expect(result.errors).toEqual([]);
        expect(result.warnings).not.toContain(".tiltignore: not generated by Flisk, left as is");
      });
    } finally {
      fs.rmSync(projectRoot, { recursive: true, force: true });
    }
  }, 15000);

  it("never overwrites a header-less (team-owned) root .tiltignore, even when discarding hand edits", async () => {
    const projectRoot = await setup();
    try {
      await withEnv(async () => {
        const own = "dist/\n";
        const target = path.join(projectRoot, ".tiltignore");
        fs.writeFileSync(target, own);
        await generateMasterConfigs(projectRoot, { discardHandEdits: true });
        expect(fs.readFileSync(target, "utf-8")).toBe(own);
        const result = verifyMasterConfigs(projectRoot);
        expect(result.errors).toEqual([]);
        expect(result.warnings).toContain(".tiltignore: not generated by Flisk, left as is");
      });
    } finally {
      fs.rmSync(projectRoot, { recursive: true, force: true });
    }
  }, 15000);
});
