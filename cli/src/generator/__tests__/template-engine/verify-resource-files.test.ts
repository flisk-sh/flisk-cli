import {
  describe,
  expect,
  fs,
  generateMasterConfigs,
  it,
  os,
  path,
  projectConfig,
  repoRoot,
  staleServiceOutputs,
  verifyMasterConfigs,
  writeProjectJson,
} from "./test-support.js";

describe("verifyMasterConfigs generated resource files", () => {
  it("checks generated files against their snapshots and skips service.yaml and .flisk-contract", () => {
    const projectRoot = fs.mkdtempSync(path.join(os.tmpdir(), "flisk-generated-resource-"));
    try {
      writeProjectJson(projectRoot, projectConfig());
      const resourceDir = path.join(projectRoot, "services", "shop", "api");
      const generatedDir = path.join(resourceDir, ".autogenerated");
      const contractDir = path.join(generatedDir, ".flisk-contract");
      const serviceJson = `${JSON.stringify({ appName: "api", appType: "backend" }, null, 2)}\n`;
      const serviceJsonPath = path.join(resourceDir, "service.json");
      fs.mkdirSync(resourceDir, { recursive: true });
      fs.writeFileSync(serviceJsonPath, serviceJson);
      const generatedErrors = () =>
        verifyMasterConfigs(projectRoot).errors.filter((error) => error.includes(".autogenerated"));

      // No generated directory at all: nothing to verify.
      expect(generatedErrors()).toEqual([]);

      fs.mkdirSync(contractDir, { recursive: true });
      fs.writeFileSync(path.join(contractDir, "service.json.source"), serviceJson);
      expect(generatedErrors()).toEqual([]);

      // service.yaml is a runtime discovery shadow and has no snapshot to compare against.
      fs.writeFileSync(path.join(generatedDir, "service.yaml"), "kind: Service\n");
      expect(generatedErrors()).toEqual([]);

      fs.writeFileSync(path.join(generatedDir, "Dockerfile"), "FROM oven/bun:1.2\n");
      expect(generatedErrors().join("\n")).toContain(
        "Dockerfile: generated-file snapshot is missing (run flisk up to regenerate)",
      );

      // The image build step's copies of the Dockerfile are written while Tilt runs and have no snapshot.
      fs.writeFileSync(path.join(generatedDir, "Dockerfile.prebuild"), "FROM oven/bun:1.2\n");
      fs.writeFileSync(
        path.join(generatedDir, "Dockerfile.prebuild.dockerignore"),
        "node_modules\n",
      );
      // The marker the build step leaves once the image is built.
      fs.writeFileSync(path.join(generatedDir, "Dockerfile.prebuild.built"), "1\n");
      expect(generatedErrors().join("\n")).not.toContain("prebuild");

      // Nested files are collected recursively and compared to their nested snapshot.
      const nestedSource = path.join(generatedDir, "docker", "entrypoint.sh");
      const nestedSnapshot = path.join(contractDir, "docker", "entrypoint.sh");
      fs.mkdirSync(path.dirname(nestedSource), { recursive: true });
      fs.mkdirSync(path.dirname(nestedSnapshot), { recursive: true });
      fs.writeFileSync(nestedSource, "#!/bin/sh\n");
      fs.writeFileSync(nestedSnapshot, "#!/bin/sh\n");
      fs.writeFileSync(
        path.join(contractDir, "Dockerfile"),
        fs.readFileSync(path.join(generatedDir, "Dockerfile"), "utf-8"),
      );
      const matching = verifyMasterConfigs(projectRoot);
      expect(matching.errors.filter((error) => error.includes(".autogenerated"))).toEqual([]);
      expect(matching.handEdited).toEqual([]);

      fs.writeFileSync(nestedSource, "#!/bin/sh\necho edited\n");
      const edited = verifyMasterConfigs(projectRoot);
      expect(edited.handEdited).toEqual(["services/shop/api/.autogenerated/docker/entrypoint.sh"]);
      expect(edited.errors.join("\n")).toContain(
        "generated file differs from its Flisk snapshot (run flisk up to regenerate)",
      );

      fs.rmSync(path.join(contractDir, "service.json.source"));
      expect(generatedErrors().join("\n")).toContain(
        "generated-file contract snapshot is missing (run flisk up to regenerate)",
      );

      // A manifest edited after its outputs were written makes those outputs stale.
      fs.writeFileSync(path.join(contractDir, "service.json.source"), serviceJson);
      fs.writeFileSync(serviceJsonPath, serviceJson.replace('"backend"', '"frontend"'));
      expect(verifyMasterConfigs(projectRoot).errors.join("\n")).toContain(
        "service.json changed since generated outputs were written",
      );

      // Callers that already have the manifest list can skip re-discovery.
      const skipped = verifyMasterConfigs(projectRoot, { manifestPaths: [] });
      expect(skipped.errors.join("\n")).not.toContain(".autogenerated");
    } finally {
      fs.rmSync(projectRoot, { recursive: true, force: true });
    }
  });

  it("detects hand edits to stack-level generated files without flagging unsnapshotted files (#3846)", async () => {
    const projectRoot = fs.mkdtempSync(path.join(os.tmpdir(), "flisk-stack-contract-"));
    const oldExtensionSource = process.env.FLISK_EXTENSION_SOURCE;
    process.env.FLISK_EXTENSION_SOURCE = repoRoot;
    try {
      writeProjectJson(projectRoot, projectConfig());
      const resourceDir = path.join(projectRoot, "services", "shop", "api");
      const serviceJson = `${JSON.stringify(
        {
          schemaVersion: 1,
          appName: "api",
          appType: "backend",
          stack: "shop",
          port: 4000,
        },
        null,
        2,
      )}\n`;
      fs.mkdirSync(resourceDir, { recursive: true });
      fs.writeFileSync(path.join(resourceDir, "service.json"), serviceJson);

      const serviceGenerated = path.join(resourceDir, ".autogenerated");
      const serviceContract = path.join(serviceGenerated, ".flisk-contract");
      fs.mkdirSync(serviceContract, { recursive: true });
      fs.writeFileSync(path.join(serviceContract, "service.json.source"), serviceJson);
      const dockerfile = "FROM oven/bun:1.2\n";
      fs.writeFileSync(path.join(serviceGenerated, "Dockerfile.app.autogenerated"), dockerfile);
      fs.writeFileSync(path.join(serviceContract, "Dockerfile.app.autogenerated"), dockerfile);

      const stackDir = path.join(projectRoot, "services", "shop");
      const stackGenerated = path.join(stackDir, ".autogenerated");
      const stackContract = path.join(stackGenerated, ".flisk-contract");
      const composeRel = ".autogenerated/docker-compose.app.autogenerated.yml";
      const composePath = path.join(stackGenerated, "docker-compose.app.autogenerated.yml");
      const compose = "services:\n  api:\n    networks:\n      - mg1_backend\n";
      fs.mkdirSync(stackGenerated, { recursive: true });
      fs.writeFileSync(composePath, compose);
      await generateMasterConfigs(projectRoot);

      // A stack folder from an older project has no contract directory: leave it alone.
      const noContract = verifyMasterConfigs(projectRoot);
      expect(noContract.errors).toEqual([]);
      expect(noContract.handEdited).toEqual([]);

      fs.mkdirSync(stackContract, { recursive: true });
      fs.writeFileSync(path.join(stackContract, "docker-compose.app.autogenerated.yml"), compose);
      // Discovery shadows and image-build copies have no snapshots by design.
      fs.writeFileSync(path.join(stackGenerated, "service.yaml"), "kind: Service\n");
      fs.writeFileSync(path.join(stackGenerated, "Dockerfile.prebuild"), dockerfile);
      const clean = verifyMasterConfigs(projectRoot);
      expect(clean.errors).toEqual([]);
      expect(clean.handEdited).toEqual([]);

      fs.writeFileSync(composePath, compose.replace("mg1_backend", "mg1_backendX"));
      const edited = verifyMasterConfigs(projectRoot);
      expect(edited.valid).toBe(false);
      expect(edited.handEdited).toEqual([`services/shop/${composeRel}`]);
      expect(edited.errors).toContain(
        `services/shop/${composeRel}: generated file differs from its Flisk snapshot (run flisk up to regenerate)`,
      );

      fs.writeFileSync(composePath, compose);
      expect(verifyMasterConfigs(projectRoot).valid).toBe(true);
    } finally {
      if (oldExtensionSource === undefined) delete process.env.FLISK_EXTENSION_SOURCE;
      else process.env.FLISK_EXTENSION_SOURCE = oldExtensionSource;
      fs.rmSync(projectRoot, { recursive: true, force: true });
    }
  }, 15000);

  it("accepts a database resource whose .autogenerated holds only the discovery service.yaml (#2863)", () => {
    const projectRoot = fs.mkdtempSync(path.join(os.tmpdir(), "flisk-generated-database-"));
    try {
      writeProjectJson(projectRoot, projectConfig());
      const resourceDir = path.join(projectRoot, "services", "shop", "shop-db");
      const generatedDir = path.join(resourceDir, ".autogenerated");
      fs.mkdirSync(generatedDir, { recursive: true });
      fs.writeFileSync(
        path.join(resourceDir, "service.json"),
        `${JSON.stringify({ appName: "shop-db", appType: "database", framework: "postgres", stack: "shop" }, null, 2)}\n`,
      );
      // flisk up writes no outputs for a database resource, so there is no contract snapshot, only the shadow.
      fs.writeFileSync(path.join(generatedDir, "service.yaml"), "appName: shop-db\n");

      const errors = verifyMasterConfigs(projectRoot).errors.filter((error) =>
        error.includes(".autogenerated"),
      );
      expect(errors).toEqual([]);
      expect(staleServiceOutputs(projectRoot)).toEqual([]);
    } finally {
      fs.rmSync(projectRoot, { recursive: true, force: true });
    }
  });
});
