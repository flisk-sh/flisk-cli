/**
 * Resource types `flisk resource --type` accepts; `byo` is an alias of `bring-your-own`, and `inference` is a preset of it.
 * `database`, `queue` and `storage` stay themselves: their `--framework` decides whether Flisk's Postgres or a bring-your-own
 * container is created. The preset types of 1.4.24 (redis, qdrant, rabbitmq, minio, mlflow) are frameworks now.
 */
export function parseResourceType(type: string): CreatableResourceType | InfraResourceType | "sdk" {
  const replacement = replacementForRemovedType(type);
  if (replacement) {
    throw new FliskError(`${type} is a framework: use ${replacement}.`, [
      `Run: flisk resource <name> ${replacement}`,
    ]);
  }
  const normalized = type === "byo" || type === INFERENCE_TYPE ? BRING_YOUR_OWN_TYPE : type;
  if (normalized === "migrator") {
    throw new FliskError("A migrator cannot be created with --type migrator.", [
      "Create one together with a new API: flisk resource <api> --type backend --feature prisma",
      "For another migration tool: flisk resource <name> --type bring-your-own --dockerfile ./Dockerfile --restart no",
      "Put the Dockerfile that runs the migration in the resource directory (or pass its directory with --path)",
    ]);
  }
  const validTypes: readonly string[] = [...RESOURCE_CREATE_TYPE_VALUES, "sdk"];
  if (!validTypes.includes(normalized)) {
    const closest = suggestClosest(normalized, validTypes);
    throw new FliskError(
      `Unknown resource type "${type}". Supported types: ${validTypes.join(", ")}.`,
      [
        ...(closest ? [`Did you mean "${closest}"?`] : []),
        `Use one of: ${validTypes.join(", ")}`,
        "Omit --type to create a backend",
      ],
    );
  }
  return normalized as CreatableResourceType | InfraResourceType | "sdk";
}

