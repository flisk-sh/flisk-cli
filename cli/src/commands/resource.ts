// `--port` is an override for every port-assigned type, validated against that type's range.
// Without it the next free port in the type's range is used. The range errors hint at assignedPort — a port that
// is free in this project — never at the first port of the range, which may already be taken (#5063), and the flag
// is always spelled `--port`: "BYO --port" is not a flag anyone can type.
export function resolveResourcePort(
  resourceType: PortAssignableResourceType,
  value: string | undefined,
  assignedPort: number,
  resources: Array<{ name?: string; config?: { port?: number } }>,
): number {
  if (!value) return assignedPort;
  const { min, max } = PORT_RANGES[resourceType];
  const subject =
    resourceType === BRING_YOUR_OWN_TYPE ? "--port for a bring-your-own resource" : "--port";
  const rangeError = () =>
    new FliskError(`${subject} must be an integer from ${min} through ${max}.`, [
      `Pass a port in range, for example --port ${assignedPort}`,
      "Or leave the flag out and Flisk assigns a free port",
    ]);
  if (!/^\d+$/.test(value)) {
    throw rangeError();
  }

  const port = Number(value);
  if (!Number.isInteger(port) || port < min || port > max) {
    throw rangeError();
  }
  const owner = resources.find((resource) => resource.config?.port === port);
  if (owner) {
    throw new FliskError(
      `Port ${port} is already assigned to ${owner.name ?? "another resource"}.`,
      [
        "See the ports in use with: flisk resources",
        `Pick another port, for example --port ${assignedPort}, or leave the flag out and Flisk assigns a free one`,
      ],
    );
  }
  return port;
}

/**
 * The probe route of a server framework (Next.js): its health route lives under the same prefix the engine serves the
 * frontend on, which is `basePath` or, without one, the service name (get_frontend_base_path).
 */
export function serverFrameworkHealthPath(name: string, basePath?: string): string {
  const prefix = basePath ? trimEndChars(basePath, "/") : `/${name}`;
  return `${prefix}/health`;
}

/**
 * After registering an existing server-framework frontend under a new base path (or name), the new probe route when the
 * manifest still carries a generated default, else undefined. A `healthCheckPath` the user set is never rewritten.
 */
export function retargetServerHealthPath(
  existing: { appName?: string; basePath?: unknown; healthCheckPath?: unknown },
  newName: string,
  newBasePath: string | undefined,
): string | undefined {
  const current = existing.healthCheckPath;
  if (typeof current !== "string") return undefined;
  const oldBase = typeof existing.basePath === "string" ? existing.basePath : undefined;
  const generated = new Set([
    serverFrameworkHealthPath(newName, oldBase),
    ...(existing.appName ? [serverFrameworkHealthPath(existing.appName, oldBase)] : []),
  ]);
  if (!generated.has(current)) return undefined;
  const next = serverFrameworkHealthPath(newName, newBasePath);
  return next === current ? undefined : next;
}

export function createServiceJson(
  name: string,
  type: CreatableResourceType,
  stack: string,
  port: number,
  extraFeatures: string[] = [],
  frameworkId?: string,
  languageId?: string,
  agent?: AgentConfig,
  basePath?: string,
) {
  const framework = resolveFrontendFramework(type, frameworkId);
  // Only an explicit selection is persisted: a missing `language` has always meant Bun.
  const language = languageId === undefined ? undefined : resolveBackendLanguage(type, languageId);
  // Likewise a missing backend `framework` has always meant Hono.
  const backendFramework = resolveBackendFramework(type, frameworkId, language);
  const typeSpecific = TYPE_SPECIFIC[type];

  const base = JSON.parse(JSON.stringify(BASE_TEMPLATE));
  for (const [key, value] of Object.entries(typeSpecific)) {
    if (typeof value === "object" && value !== null && !Array.isArray(value)) {
      base[key] = { ...base[key], ...value };
    } else {
      base[key] = value;
    }
  }

  if (language?.devCommand) {
    base.dev = {
      command: language.devCommand,
      watch: language.watch ?? base.dev.watch,
    };
    // The engine generates the image (.autogenerated/Dockerfile.app.autogenerated); a build
    // block would point at a Dockerfile that does not exist.
    delete base.build;
  }

  return {
    ...base,
    $schema: SERVICE_MANIFEST_SCHEMA_URL,
    schemaVersion: SERVICE_MANIFEST_SCHEMA_VERSION,
    appName: name,
    appType: type as ResourceType,
    featuresEnabled: [
      ...getDefaultFeaturesForResourceType(type as ResourceType).filter(
        // Prisma wiring is Bun-only; the Python provider owns their data layer.
        (feature) => !(language?.createFiles && feature === "prisma"),
      ),
      ...extraFeatures,
    ],
    name,
    type,
    stack,
    port,
    ...(framework ? { framework: framework.id } : {}),
    // A server framework (Next.js) is served under /<name>/ with a base path, so the engine's default /health probe finds
    // nothing there. Probe the framework's own health route under the same prefix.
    ...(framework?.kind === "server"
      ? { healthCheckPath: serverFrameworkHealthPath(name, basePath) }
      : {}),
    ...(backendFramework && type !== "mcp" && type !== "agent"
      ? { framework: backendFramework.id }
      : {}),
    ...(language ? { language: language.id } : {}),
    ...(type === "agent" && agent ? { agent } : {}),
    ...(type === "frontend" && basePath ? { basePath } : {}),
  };
}

