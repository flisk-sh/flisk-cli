/**
 * The parts of the `flisk resource` command the user already typed, so a no-input
 * error can repeat them in its "For example" hint instead of the fixed
 * `api --type backend` example (#5059).
 */
interface ResourceNoInputTyped {
  name?: string;
  type?: string;
  isTypeExplicit?: boolean;
  framework?: string;
  language?: string;
  local?: boolean;
}

/**
 * Builds the "For example" command from the parts the user typed, plus
 * `--stack main --yes` to skip the prompt that could not read input. Only the
 * flags the user actually gave are repeated: --type only when it was typed
 * explicitly, since it defaults to backend.
 */
function resourceNoInputExample(typed: ResourceNoInputTyped): string {
  const parts = ["flisk", "resource", typed.name as string];
  if (typed.isTypeExplicit && typed.type) parts.push("--type", typed.type);
  if (typed.framework) parts.push("--framework", typed.framework);
  if (typed.language) parts.push("--language", typed.language);
  if (typed.local) parts.push("--local");
  parts.push("--stack", DEFAULT_STACK_NAME, "--yes");
  return parts.join(" ");
}

/**
 * Turns a prompt that could not read input into an error that names the flags which avoid the
 * stack prompt. The suggestions travel with both the printed error and the `--json` envelope.
 * When the user typed a resource name, the "For example" hint repeats the command they typed
 * (#5059); with no name given it keeps the fixed `api --type backend` example.
 */
export function resourceNoInputError(
  cause: unknown,
  typed?: ResourceNoInputTyped,
  prompt: "stack" | "type" = "stack",
): FliskError {
  const detail = getErrorMessage(cause);
  if (prompt === "type") {
    // --stack does not skip the type question, so this failure names --type and --yes instead.
    const parts = ["flisk", "resource", typed?.name ?? "api"];
    if (typed?.framework) parts.push("--framework", typed.framework);
    if (typed?.language) parts.push("--language", typed.language);
    if (typed?.local) parts.push("--local");
    parts.push("--type", "backend", "--yes");
    return new FliskError(`${detail} Pass --type <type> or --yes to skip this prompt.`, [
      "Pass --type <type> to choose the resource type, or --yes to accept the default type (backend).",
      `For example: ${parts.join(" ")}.`,
    ]);
  }
  const example = typed?.name
    ? resourceNoInputExample(typed)
    : "flisk resource api --type backend --stack main --yes";
  return new FliskError(`${detail} Pass --stack <name> or --yes to skip this prompt.`, [
    "Pass --stack <name> to skip the stack prompt, or --yes to accept the default stack.",
    `For example: ${example}.`,
  ]);
}

