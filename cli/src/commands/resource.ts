/**
 * Parse an existing `service.json` manifest.
 *
 * Wraps JSON syntax errors in a `FliskError` that names the offending file, so a malformed manifest
 * is reported as a CLI error instead of an unhandled `SyntaxError`. Only the JSON syntax is
 * checked here: the manifest fields themselves are not validated, and a syntactically valid file
 * is returned as-is, including unknown or missing fields.
 *
 * @param content - The raw contents of the `service.json` file.
 * @param configPath - Path to the manifest, used in the error message.
 * @returns The parsed manifest.
 * @throws FliskError When the content is not valid JSON.
 */
export function parseExistingServiceJson(
  content: string,
  configPath: string,
): ExistingServiceConfig {
  try {
    return JSON.parse(content) as ExistingServiceConfig;
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    throw new FliskError(`Could not parse service.json at ${configPath}: ${reason}`, [
      "Fix the JSON syntax in that file",
      "Check every service.json with: flisk config verify",
    ]);
  }
}

/**
 * Prints the framework inventory for the requested resource type.
 *
 * The default is backend, matching the resource type default. Explicit types keep their
 * own column formats, and the backend listing shows each framework's compatible language.
 */
function printFrameworkInventory(
  options: { type?: string; language?: string },
  isTypeExplicit: boolean,
): void {
  const listing = frameworkListing(options);
  if (!isTypeExplicit && listing.type === "backend") {
    console.error(
      "Listing backend frameworks (the default). Other types: --type frontend|database|queue|storage|mail|payment.",
    );
  }
  if (listing.type === "frontend") {
    printFrontendFrameworks();
    return;
  }
  if (isInfraResourceType(listing.type)) {
    for (const f of infraFrameworkListing(listing.type)) {
      console.log(
        `${f.id}\t${f.label}\t${f.image ?? "-"}\t${f.default ? "default" : "-"}\t${f.command}`,
      );
    }
    return;
  }
  if (listing.type !== "backend") return;

  const frameworks = listBackendFrameworks(options.language);
  for (const f of frameworks) {
    // The compatibility cell names the language it is judged against, so it is never a bare
    // "compatible" that could be read against a different language.
    const compatibility = f.compatible
      ? `compatible with ${listing.language}`
      : `incompatible with --language ${listing.language}`;
    console.log(`${f.id}\t${f.label}\t${f.languages.join(", ")}\t${compatibility}\t${f.command}`);
  }
  if (
    listing.language &&
    frameworks.length > 0 &&
    !frameworks.some((framework) => framework.compatible)
  ) {
    console.error(
      `No listed backend framework is compatible with --language ${listing.language}; scaffold it without --framework.`,
    );
  }
}

/**
 * The frameworks `--type database` and the preset types (`queue`, `storage`) accept, in the order the help lists them. The
 * database default is the shared Flisk Postgres (no container of its own, so no image); every other one is a pinned image,
 * and a preset type without `--framework` runs its default (NATS, MinIO).
 */
export function infraFrameworkListing(type: InfraResourceType): {
  id: string;
  label: string;
  image: string | null;
  default: boolean;
  command: string;
}[] {
  const rows = frameworksOfType(type).map((id) => {
    const preset = INFRA_PRESETS[id as InfraFramework];
    return {
      id,
      label: preset.description,
      image: preset.image,
      default: id === defaultFrameworkOfType(type),
      command: `flisk resource <name> --type ${type} --framework ${id}`,
    };
  });
  if (isPresetResourceType(type)) return rows;
  return [
    {
      id: DATABASE_FRAMEWORK,
      label: "Shared Flisk Postgres, one database per stack",
      image: null,
      default: true,
      command: `flisk resource <name> --type ${type} --framework ${DATABASE_FRAMEWORK}`,
    },
    ...rows,
  ];
}

/** Which framework inventory `--frameworks` lists, and for a backend the language it is judged against. */
function frameworkListing(options: {
  type?: string;
  language?: string;
}):
  | { type: "frontend" }
  | { type: "backend"; language: string | undefined }
  | { type: InfraResourceType } {
  const resourceType = parseResourceType(options.type ?? "backend");
  if (isInfraResourceType(resourceType)) {
    return { type: resourceType };
  }
  if (resourceType !== "frontend" && resourceType !== "backend") {
    throw new FliskError(`No frameworks are registered for --type ${resourceType}.`, [
      `Use --type ${["frontend", "backend", "database", ...Object.keys(PRESET_RESOURCE_TYPES)].join(", ").replace(/, ([^,]+)$/, " or $1")} to list frameworks`,
      "Omit --type to list the frontend frameworks",
    ]);
  }

  // `--language` belongs to backends only, so the resource command rejects it for every other type.
  const language = resolveBackendLanguage(resourceType, options.language);
  return resourceType === "frontend"
    ? { type: "frontend" }
    : { type: "backend", language: language?.id };
}

/** What `flisk resource --frameworks --json` reports: the same inventory the text listing prints. */
