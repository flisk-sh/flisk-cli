/** The Bash completion script. */
import type { CompletionCandidates } from "./completion-candidates.js";
import {
  buildCompletionTable,
  type CommandEntry,
  commandWords,
  flagList,
  JSON_RESOURCES,
  JSON_STACKS,
  shellTypeCondition,
  TYPE_VARIABLE,
  type TypeValueArm,
} from "./completion-core.js";

/** The `--type` of the current command line, in bash. */
const BASH_TYPE = `    ${TYPE_VARIABLE}=""
    local i
    for (( i=1; i < COMP_CWORD; i++ )); do
        if [[ "\${COMP_WORDS[i]}" = "--type" ]]; then
            ${TYPE_VARIABLE}="\${COMP_WORDS[i+1]}"
        elif [[ "\${COMP_WORDS[i]}" = "--type="* ]]; then
            ${TYPE_VARIABLE}="\${COMP_WORDS[i]#--type=}"
        fi
    done`;

/** The values of a flag that depend on the `--type`, in bash. */
function bashTypeValues(arms: TypeValueArm[]): string {
  const lines = [`            local ${TYPE_VARIABLE}_values=""`];
  arms.forEach((arm, index) => {
    lines.push(
      `            ${index === 0 ? "if" : "elif"} [[ ${shellTypeCondition(arm.types)} ]]; then`,
    );
    lines.push(`                ${TYPE_VARIABLE}_values="${arm.values.join(" ")}"`);
  });
  lines.push("            fi");
  lines.push(`            COMPREPLY=( $(compgen -W "\${${TYPE_VARIABLE}_values}" -- \${cur}) )`);
  return lines.join("\n");
}

/** The `words` value of the positional argument of a command, in bash. */
function bashPositionalWords(entry: CommandEntry): string | undefined {
  switch (entry.positional) {
    case "stacks":
      return `\${stacks}`;
    case "resources":
      return `\${resources}`;
    case "stacks-and-resources":
      return `\${stacks} \${resources}`;
    case "commands":
      return `\${commands}`;
    case "hosts":
      return (entry.positionalValues ?? []).join(" ");
    default:
      return undefined;
  }
}

export function renderBash(candidates: CompletionCandidates): string {
  const table = buildCompletionTable(candidates);
  const globalFlags = flagList(candidates.globalOptions);

  const aliasCases = table.aliasRows
    .map(({ alias, entry }) => `        ${alias}) cmd="${entry.name}" ;;`)
    .join("\n");

  const commandCases = table.topOptionEntries
    .map((entry) => `            ${entry.name}) options="${flagList(entry.options)}" ;;`)
    .join("\n");

  const subCommandOptionCases = table.subOptionEntries
    .map((entry) => `                "${entry.path}") options="${flagList(entry.options)}" ;;`)
    .join("\n");

  // The values of the flags of the current command, when the command accepts its own set.
  const commandValueCases = table.commandValueRows
    .map(
      ({ key, values }) =>
        `        "${key}")\n            COMPREPLY=( $(compgen -W "${values.join(" ")}" -- \${cur}) )\n            return 0\n            ;;`,
    )
    .join("\n");

  const valueCases = table.valueRows
    .map(
      ({ flag, values }) =>
        `        ${flag})\n            COMPREPLY=( $(compgen -W "${values.join(" ")}" -- \${cur}) )\n            return 0\n            ;;`,
    )
    .join("\n");

  // The values of the flags that depend on the `--type` of the command line.
  const typeValueCases = table.typeValueRows
    .map(
      ({ flag, arms }) =>
        `        ${flag})\n${bashTypeValues(arms)}\n            return 0\n            ;;`,
    )
    .join("\n");

  const subCommandCases = table.withSubcommands
    .map(
      (entry) => `        ${entry.name}) words="${commandWords(entry.subcommands).join(" ")}" ;;`,
    )
    .join("\n");

  const positionalCase = (entry: CommandEntry, pattern: string): string => {
    const words = bashPositionalWords(entry);
    return words === undefined ? "" : `${pattern}) words="${words}" ;;`;
  };

  const positionalCases = table.topPositionalEntries
    .map((entry) => positionalCase(entry, `        ${entry.name}`))
    .join("\n");

  // The positional argument of a sub-command, for example the resource of `flisk agent sessions`.
  const subCommandPositionalCases = table.subPositionalEntries
    .map((entry) => positionalCase(entry, `            "${entry.path}"`))
    .join("\n");

  // The path of the command the cursor is in, for example "config verify".
  const subCommandPathCases = table.subEntries
    .map((entry) => `            "${entry.path}") path="${entry.path}" ;;`)
    .join("\n");

  return `# Flisk CLI Bash Completion
# Generated by "flisk completion bash". The command and flag lists come from the CLI itself.
_flisk_completions() {
    local cur prev cmd sub options words commands stacks resources path ${TYPE_VARIABLE} ${TYPE_VARIABLE}_values
    COMPREPLY=()
    cur="\${COMP_WORDS[COMP_CWORD]}"
    prev="\${COMP_WORDS[COMP_CWORD-1]}"
    cmd="\${COMP_WORDS[1]}"
    sub="\${COMP_WORDS[2]}"

    # The path of the command the cursor is in, for example "config verify".
    path="\${cmd}"
    case "\${cmd} \${sub}" in
${subCommandPathCases}
    esac

    commands="${table.words.join(" ")}"

    # The stacks and the resources of the current project.
    stacks="$(${JSON_STACKS})"
    resources="$(${JSON_RESOURCES})"

${BASH_TYPE}

    # The values of the flags of the current command, when the command accepts its own set.
    case "\${path} \${prev}" in
${commandValueCases}
    esac

    # The values of the flags that take a fixed list.
    case "\${prev}" in
${valueCases}
${typeValueCases}
        --stack)
            COMPREPLY=( $(compgen -W "\${stacks}" -- \${cur}) )
            return 0
            ;;
        --only)
            COMPREPLY=( $(compgen -W "\${resources}" -- \${cur}) )
            return 0
            ;;
    esac

    # The aliases are the same commands under a different name.
    case "\${cmd}" in
${aliasCases}
    esac

    # The flags of the current command.
    if [[ \${cur} == -* ]]; then
        options="${globalFlags}"
        case "\${cmd}" in
${commandCases}
        esac
        if [[ -n "\${sub}" ]]; then
            case "\${cmd} \${sub}" in
${subCommandOptionCases}
            esac
        fi
        COMPREPLY=( $(compgen -W "\${options}" -- \${cur}) )
        return 0
    fi

    # Inside a sub-command the flags and the positional argument of the sub-command are left.
    if [[ -n "\${sub}" ]]; then
        words=""
        case "\${cmd} \${sub}" in
${subCommandPositionalCases}
        esac
        if [[ -n "\${words}" ]]; then
            COMPREPLY=( $(compgen -W "\${words}" -- \${cur}) )
        fi
        return 0
    fi

    # Only a bare \`flisk <TAB>\` completes the top-level commands. Inside a command, the case below
    # supplies the words of its sub-commands or positional argument; everything else gets nothing.
    words=""
    if [[ -z "\${cmd}" ]]; then
        words="\${commands}"
    fi
    case "\${cmd}" in
${subCommandCases}
${positionalCases}
    esac

    COMPREPLY=( $(compgen -W "\${words}" -- \${cur}) )
    return 0
}

complete -F _flisk_completions flisk
`;
}
