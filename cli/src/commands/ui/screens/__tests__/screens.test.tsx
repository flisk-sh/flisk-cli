// A props object where every dep field carries a value that reaches the screen's richer path:
// selections made, events loaded, services discovered. The registry tests pick from this.
const fullProps: TuiScreenProps = {
  items: [
    { label: "shop (1 resource)", value: "shop" },
    { label: "edge (0 resources)", value: "edge" },
  ],
  onSelect: () => {},
  highlightedIndex: 0,
  isActive: true,
  pageSize: 10,
  width: 100,
  onLayout: () => {},
  services: [service],
  message: "",
  selectedFile: null,
  selectedStackData: { stack, metadata: stackMeta },
  selectedServiceData: { service, metadata: resourceMeta },
  terminalWidth: 120,
  showSidebar: true,
  eventLoadState: "ready",
  eventLoadError: null,
  eventSnapshot: snapshot,
};

const renderScreen = (screen: TuiScreen, props: Partial<TuiScreenProps> = {}): string =>
  renderToString(
    createElement(
      TUIThemeContext.Provider,
      { value: theme },
      createElement(screen.Component, { ...fullProps, ...props }),
    ),
    { columns: 120 },
  );

// Renders a screen with only the props its registry `deps` declares; a screen that silently
// reads an undeclared prop gets undefined and loses the marker this way.
const renderScreenFromDeps = (screen: TuiScreen): string =>
  renderToString(
    createElement(
      TUIThemeContext.Provider,
      { value: theme },
      createElement(
        screen.Component,
        Object.fromEntries(
          screen.deps.map((dep) => [dep, fullProps[dep]]),
        ) as unknown as TuiScreenProps,
      ),
    ),
    { columns: 120 },
  );

describe("TUI screen registry", () => {
  it("registers one screen module per tab", () => {
    for (const tab of TABS) {
      expect(TUI_SCREENS[tab.id], `no screen registered for ${tab.id}`).toBeDefined();
      expect(TUI_SCREENS[tab.id].name).toBe(tab.id);
    }
    expect(Object.keys(TUI_SCREENS).sort()).toEqual(TABS.map((tab) => tab.id).sort());
  });

  it.each(TABS.map((tab) => tab.id))("declares a non-empty unique dep list for %s", (tab) => {
    const { deps } = TUI_SCREENS[tab];
    expect(deps.length).toBeGreaterThan(0);
    expect(new Set(deps).size).toBe(deps.length);
  });
});

describe("screen bodies", () => {
  it.each<{
    name: string;
    tab: TabId;
    props: Partial<TuiScreenProps>;
    want: string[];
  }>([
    {
      name: "lists the stacks when services exist",
      tab: "overview",
      props: {},
      want: ["Stacks", "shop (1 resource)"],
    },
    {
      name: "renders the empty state when no services exist",
      tab: "overview",
      props: { services: [] },
      want: ["No Services Found", "No service.json files found"],
    },
    {
      name: "asks for a stack when nothing is selected",
      tab: "resources",
      props: { selectedStackData: null },
      want: ["Select a stack to view resources", "shop (1 resource)"],
    },
    {
      name: "renders the stack resource table for a selection",
      tab: "resources",
      props: {},
      want: ["Stack: shop", "orders-api"],
    },
    {
      name: "asks for a service when nothing is selected",
      tab: "files",
      props: { selectedServiceData: null },
      want: ["Select a service to view files", "shop (1 resource)"],
    },
    {
      name: "renders the service file tree for a selection",
      tab: "files",
      props: {},
      want: ["Service: orders-api", "Autogenerated Files"],
    },
    {
      name: "shows a loading line while events arrive",
      tab: "events",
      props: { eventLoadState: "loading", eventSnapshot: null },
      want: ["Loading Tilt events..."],
    },
    {
      name: "shows the friendly unavailable state when Tilt is offline",
      tab: "events",
      props: { eventLoadState: "unavailable", eventSnapshot: null },
      want: ["Tilt is not running or its UI is unreachable.", "press [r] to retry."],
    },
    {
      name: "shows the load error when Tilt answers with a bad response",
      tab: "events",
      props: {
        eventLoadState: "error",
        eventSnapshot: null,
        eventLoadError: "Tilt returned invalid UIResource JSON",
      },
      want: ["Could not load Tilt events.", "Tilt returned invalid UIResource JSON"],
    },
    {
      name: "renders the resource states and event rows for a ready snapshot",
      tab: "events",
      props: {},
      want: ["Event Timeline", "orders-api", "Runtime ok", "Build completed"],
    },
    {
      name: "asks for a service when nothing is selected",
      tab: "config",
      props: { selectedServiceData: null },
      want: ["Select a service to view configuration", "shop (1 resource)"],
    },
    {
      name: "renders the selected service manifest",
      tab: "config",
      props: {},
      want: ["services/shop/orders-api/service.json", '"appType": "backend"'],
    },
  ])("$tab: $name", ({ tab, props, want }) => {
    const output = renderScreen(TUI_SCREENS[tab], props);
    for (const text of want) expect(output).toContain(text);
  });

  it.each<[TabId, string]>([
    ["overview", "shop (1 resource)"],
    ["resources", "orders-api"],
    ["files", "Service: orders-api"],
    ["events", "Build completed"],
    ["config", "service.json"],
  ])("the %s screen needs only its declared deps", (tab, text) => {
    expect(renderScreenFromDeps(TUI_SCREENS[tab])).toContain(text);
  });
});

describe("screen pickers", () => {
  const pickableTabs: TabId[] = ["overview", "resources", "files", "config"];

  it.each(pickableTabs)(
    "the %s screen's picker reports a selection with the highlighted item",
    async (tab) => {
      const onSelect = vi.fn();
      const io = ttyStreams();
      const app = render(
        createElement(
          TUIThemeContext.Provider,
          { value: theme },
          createElement(TUI_SCREENS[tab].Component, {
            ...fullProps,
            onSelect,
            selectedStackData: null,
            selectedServiceData: null,
          }),
        ),
        {
          stdin: io.stdin,
          stdout: io.stdout,
          stderr: io.stderr,
          interactive: true,
          exitOnCtrlC: false,
          patchConsole: false,
        },
      );
      try {
        await new Promise((resolve) => setTimeout(resolve, 50));
        await app.waitUntilRenderFlush();

        io.stdin.write("j");
        await new Promise((resolve) => setTimeout(resolve, 30));
        io.stdin.write("\r");
        await new Promise((resolve) => setTimeout(resolve, 30));
        await app.waitUntilRenderFlush();

        expect(onSelect).toHaveBeenCalledWith({ label: "edge (0 resources)", value: "edge" });
      } finally {
        app.unmount();
        io.stdin.destroy();
        io.stdout.destroy();
        io.stderr.destroy();
      }
    },
  );
});
