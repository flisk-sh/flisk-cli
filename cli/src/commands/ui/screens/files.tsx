import { Box, Text } from "ink";
import type React from "react";
import { useMemo } from "react";
import { FileTree } from "../../../components/index.js";
import { sectionTitle, useTUITheme } from "../../../components/ui-theme.js";
import type { DiscoveredResource, FileNode } from "../../../types/index.js";
import { ScreenSelectList } from "./select-list.js";
import type { TuiScreen, TuiScreenProps } from "./types.js";

const FilesScreen: React.FC<TuiScreenProps> = ({
  selectedServiceData,
  selectedFile,
  services,
  ...listProps
}) => {
  const theme = useTUITheme();
  const fileTreeNodes: FileNode[] = useMemo(() => {
    if (selectedServiceData) {
      return [
        {
          name: selectedServiceData.service.name,
          path: selectedServiceData.service.path,
          type: "directory",
          children: selectedServiceData.metadata.autogeneratedFiles.map((f) => ({
            name: f.name,
            path: f.path,
            type: "file" as const,
            fileType: f.type,
            size: f.size,
            lastModified: f.lastModified,
          })),
        },
      ];
    }
    return services.map((s: DiscoveredResource) => ({
      name: s.name,
      path: s.path,
      type: "directory" as const,
      children: [],
    }));
  }, [selectedServiceData, services]);

  return (
    <>
      <Box marginBottom={1}>
        <Text bold color={theme.muted}>
          {sectionTitle(theme, "Autogenerated Files")}
        </Text>
      </Box>
      {selectedServiceData ? (
        <>
          <Text color={theme.muted}>Service: {selectedServiceData.service.name}</Text>
          <Box marginTop={1}>
            <FileTree nodes={fileTreeNodes} selectedPath={selectedFile || undefined} />
          </Box>
        </>
      ) : (
        <ScreenSelectList prompt="Select a service to view files" {...listProps} />
      )}
    </>
  );
};

export const filesScreen: TuiScreen = {
  name: "files",
  deps: [
    "selectedServiceData",
    "selectedFile",
    "services",
    "items",
    "onSelect",
    "highlightedIndex",
    "isActive",
    "pageSize",
    "width",
    "onLayout",
  ],
  Component: FilesScreen,
};
