import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { expect, it } from "vitest";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
// The rules moved to live_update.star and their docker_build call site to single_resource.star
// (#4959); both are pinned here just as the one file was before the split.
const liveUpdate = readFileSync(
  join(
    repoRoot,
    "runtime",
    "engine",
    "topologies",
    "tilt",
    "resources",
    "orchestrator",
    "live_update.star",
  ),
  "utf-8",
);
const singleResource = readFileSync(
  join(
    repoRoot,
    "runtime",
    "engine",
    "topologies",
    "tilt",
    "resources",
    "orchestrator",
    "single_resource.star",
  ),
  "utf-8",
);

// Tilt resolves sync() local paths against the Tiltfile directory (.flisk/.flisk-out), not the
// docker_build context. A project-relative path never matches the changed files, so every
// edit fell back to a full rebuild ("Found file(s) not matching any sync").
it("anchors live-update sync sources at the project root", () => {
  expect(liveUpdate).toContain(
    "def _live_update_sync_source(project_root, full_res_path, sync_path)",
  );
  expect(liveUpdate).toContain("return project_root.rstrip('/') + '/' + relative_path");
  expect(liveUpdate).toContain(
    "full_sync_path = _live_update_sync_source(project_root, full_res_path, sync_path)",
  );
});

it("passes the project root and language to the live-update rules by keyword", () => {
  expect(liveUpdate).toContain(
    "def build_live_update_rules(res_path, full_res_path, syncs, project_root='', language='bun', go_live_reload=False, node_frontend=False, bun_backend_entry=None)",
  );
  expect(singleResource).toContain("project_root=config.get('project_root', ''),");
  expect(singleResource).toContain("language=config.get('manifest', {}).get('language', 'bun'),");
  expect(singleResource).toContain(
    "node_frontend=Docker.is_next_frontend(config.get('manifest', {})),",
  );
  expect(singleResource).toContain("bun_backend_entry=_bun_backend_entry(config),");
});

it("gives Rust, and Go without dev.liveReload, no live-update rules, so Tilt rebuilds the image on change", () => {
  expect(liveUpdate).toContain(
    "if language == 'rust' or (language == 'go' and not go_live_reload):\n        return []",
  );
  // The early return must come before any sync() step is built: Tilt rejects sync steps that are created but unused.
  expect(
    liveUpdate.indexOf("if language == 'rust' or (language == 'go' and not go_live_reload):"),
  ).toBeLessThan(liveUpdate.indexOf("live_update_rules.append(sync(full_sync_path, dest))"));
});

it("keeps the container destination under /app, independent of the host project root", () => {
  expect(liveUpdate).toContain("dest = '/app/' + full_res_path + '/' + sync_path");
});

it("does not sync the Bun/npm registry config for Python backends", () => {
  expect(liveUpdate).toContain("if language == 'python' and (");
  expect(liveUpdate).toContain("sync_path.endswith('.npmrc.docker.autogenerated')");
  expect(liveUpdate).toContain("sync_path.endswith('bunfig.docker.autogenerated.toml')");
});

it("does not sync the Bun/npm registry config for Node backends", () => {
  expect(liveUpdate).toContain("if language == 'node' and (");
  expect(liveUpdate).toContain(
    "sync_path.endswith('.npmrc.docker.autogenerated') or sync_path.endswith('bunfig.docker.autogenerated.toml')",
  );
});

it("skips bun install step for Python, Node backends and Next.js frontends (a Node image)", () => {
  expect(liveUpdate).toContain(
    "if language == 'python' or language == 'node' or node_frontend:\n        return live_update_rules",
  );
});

it("configures Go live reload with fall_back_on for go.mod, go.sum, and autogenerated folder", () => {
  expect(liveUpdate).toContain("if go_live_reload:");
  expect(liveUpdate).toContain(
    "source_dir = _live_update_sync_source(project_root, full_res_path, '')",
  );
  expect(liveUpdate).toContain("fall_back_on([");
  expect(liveUpdate).toContain("source_dir + 'go.mod',");
  expect(liveUpdate).toContain("source_dir + 'go.sum',");
  expect(liveUpdate).toContain("source_dir + OUTPUT.AUTOGENERATED_FOLDER,");
  expect(liveUpdate).toContain("sync(source_dir.rstrip('/'), '/app/' + full_res_path)");
});

it("rebuilds the image when a dependency file changes, matched by local path", () => {
  // A run() trigger under /app/ is a container path that Tilt never matches, so `bun install` never ran.
  expect(liveUpdate).toContain(
    "live_update_rules = [fall_back_on([source_dir + name for name in _DEPENDENCY_FILES])]",
  );
  expect(liveUpdate).toContain("'package.json', 'bun.lock', 'bun.lockb', 'package-lock.json'");
  expect(liveUpdate).not.toContain("&& bun install'");
});

it("handles empty or populated project root cleanly in _live_update_sync_source", () => {
  expect(liveUpdate).toContain("relative_path = full_res_path + '/' + sync_path");
  expect(liveUpdate).toContain("if project_root:");
  expect(liveUpdate).toContain("return project_root.rstrip('/') + '/' + relative_path");
  expect(liveUpdate).toContain("return relative_path");
});
