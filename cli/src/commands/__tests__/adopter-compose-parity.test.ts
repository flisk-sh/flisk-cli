import { spawnSync } from "node:child_process";
import { cpSync, existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { composeConfigAvailable, composeConfigParity } from "../../test-support/compose-config.js";
import { cleanEnv, createTempDir } from "../../test-support/index.js";
import { findOnPath } from "../../utils/which.js";
import { exportInvocation } from "../export.js";
import { importInvocation } from "../import/invocation.js";

/**
 * Exporter parity for the adopter fixtures: import a real adopter's Compose file with the pinned importer,
 * regenerate a standalone file with the pinned exporter, then compare `docker compose config` of both, per the
 * Lychee spec's check (LycheeOrg/Lychee#4936). Only the differences the importer and exporter document may show
 * up; everything else is a regression the spec's CI would fail.
 */

const FIXTURES = join(dirname(fileURLToPath(import.meta.url)), "fixtures", "adopter-parity");

/**
 * `supabase` is a trimmed real adopter file (Apache-2.0, one of docs/project/ADOPTER-COVERAGE.md's tested
 * adopters): network aliases, container_name, entrypoint, command, SELinux volume flags, three healthcheck
 * spellings and a variable host port. `synthetic` is hand-written to cover the rest of the documented list:
 * kebab renames with aliases, env_file, deploy reservations, expose and custom networks.
 */
const ADOPTER_FIXTURES = ["supabase", "synthetic"] as const;

/** The pipeline needs a package runner for the pinned packages and Docker for `docker compose config`. */
const runnerFound = findOnPath("npx") !== null || findOnPath("bunx") !== null;

/** A cold npx fetch plus the import or export run, and the Compose parse, in milliseconds. */
const STEP_TIMEOUT_MS = 180_000;

function runPackage(
  invocation: ReturnType<typeof importInvocation>,
  cwd: string,
): { status: number | null; output: string } {
  // nosemgrep: javascript.lang.security.audit.spawn-shell-true.spawn-shell-true -- fixed test command; the shell is only for Windows .cmd shims
  const run = spawnSync(invocation.command, invocation.args, {
    cwd,
    encoding: "utf-8",
    env: cleanEnv({ NO_COLOR: "1" }),
    shell: invocation.shell,
    windowsVerbatimArguments: invocation.windowsVerbatimArguments,
    timeout: STEP_TIMEOUT_MS,
  });
  return { status: run.status, output: `${run.stdout ?? ""}\n${run.stderr ?? ""}` };
}

describe.skipIf(!runnerFound)("adopter compose parity", () => {
  for (const fixture of ADOPTER_FIXTURES) {
    it.skipIf(!composeConfigAvailable())(
      `regenerated ${fixture} compose matches the original, modulo documented differences`,
      () => {
        const fixtureDir = join(FIXTURES, fixture);
        const parent = createTempDir("flisk-adopter-parity-");
        const projectDir = join(parent, fixture);
        cpSync(fixtureDir, projectDir, { recursive: true });
        // env_file entries resolve against this file; an empty one keeps the run deterministic.
        writeFileSync(join(projectDir, ".env"), "");

        const imported = runPackage(importInvocation([".", "--yes"]), projectDir);
        expect(imported.status, `importer output:\n${imported.output}`).toBe(0);
        const exported = runPackage(exportInvocation(["compose", ".", "--force"]), projectDir);
        expect(exported.status, `exporter output:\n${exported.output}`).toBe(0);

        const generatedFile = join(projectDir, ".autogenerated", "docker-compose.yml");
        expect(
          existsSync(generatedFile),
          "the exporter wrote .autogenerated/docker-compose.yml",
        ).toBe(true);

        const report = composeConfigParity(join(projectDir, "docker-compose.yml"), generatedFile);
        const undocumented = report.differences.map((finding) => finding.message);
        const allowed = report.documented.map((finding) => `${finding.kind}: ${finding.message}`);
        expect(undocumented, `documented only:\n${allowed.join("\n")}`).toEqual([]);
      },
      STEP_TIMEOUT_MS * 3,
    );
  }
});
