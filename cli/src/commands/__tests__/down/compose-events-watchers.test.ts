import {
  createJsonEmitterMock,
  describe,
  downCommand,
  downTestContext,
  expect,
  findComposeWatchersMock,
  it,
  probeProjectIdleMock,
  projectComposeProjectsMock,
  realpathSync,
  rmSync,
  runTiltMock,
  setupTestProject,
  stopComposeWatchersMock,
  vi,
} from "../../test-support/down.js";

describe("flisk down", () => {
  downTestContext();

  describe("compose events watchers (#4854)", () => {
    const watchers = [
      {
        pid: 41,
        command:
          "docker compose --project-name test-project-app-autogenerated --project-directory /x events --json",
        projectName: "test-project-app-autogenerated",
        projectDir: "/x",
      },
      {
        pid: 42,
        command:
          "docker-compose compose --project-name test-project-traefik --project-directory /x events --json",
        projectName: "test-project-traefik",
        projectDir: "/x",
      },
    ];

    it("stops the leftover watchers after tilt down and reports them", async () => {
      const tempDir = setupTestProject();
      findComposeWatchersMock.mockReturnValue(watchers);
      stopComposeWatchersMock.mockReturnValue([41, 42]);
      const emitMock = vi.fn();
      createJsonEmitterMock.mockReturnValue(emitMock);
      vi.spyOn(console, "log").mockImplementation(() => {});
      await downCommand.parseAsync(["node", "flisk", "--json"], { from: "node" });
      expect(findComposeWatchersMock).toHaveBeenCalledWith(realpathSync(tempDir), "test-project");
      expect(stopComposeWatchersMock).toHaveBeenCalledWith(watchers);
      expect(emitMock).toHaveBeenCalledWith(
        expect.objectContaining({ ok: true, stoppedEventWatchers: [41, 42] }),
      );
    });

    it("stops leftover watchers even when the stack is already idle", async () => {
      setupTestProject();
      projectComposeProjectsMock.mockReturnValue([]);
      probeProjectIdleMock.mockResolvedValue({ idle: true });
      findComposeWatchersMock.mockReturnValue(watchers);
      stopComposeWatchersMock.mockReturnValue([41]);
      const log = vi.spyOn(console, "log").mockImplementation(() => {});
      await downCommand.parseAsync(["node", "flisk"], { from: "node" });
      expect(runTiltMock).not.toHaveBeenCalled();
      expect(stopComposeWatchersMock).toHaveBeenCalledWith(watchers);
      const output = log.mock.calls.map((call) => call.join(" ")).join("\n");
      expect(output).toContain('Stopped 1 "docker compose events" watcher process(es) (pid 41)');
    });

    it("lists but does not stop watchers on --dry-run", async () => {
      setupTestProject();
      findComposeWatchersMock.mockReturnValue(watchers);
      const emitMock = vi.fn();
      createJsonEmitterMock.mockReturnValue(emitMock);
      vi.spyOn(console, "log").mockImplementation(() => {});
      await downCommand.parseAsync(["node", "flisk", "--dry-run", "--json"], { from: "node" });
      expect(stopComposeWatchersMock).not.toHaveBeenCalled();
      expect(runTiltMock).not.toHaveBeenCalled();
      expect(emitMock).toHaveBeenCalledWith(
        expect.objectContaining({ ok: true, dryRun: true, wouldStopComposeWatchers: [41, 42] }),
      );
    });

    it("only signals pids still proven watchers after tilt down: a stale pid may have been reused", async () => {
      setupTestProject();
      // The pid list is read before `tilt down`; pid 41's watcher exits during it, and a fresh scan no
      // longer proves it is a compose events stream, so it is never signaled.
      findComposeWatchersMock.mockReturnValueOnce(watchers).mockReturnValue(watchers.slice(1));
      stopComposeWatchersMock.mockReturnValue([42]);
      vi.spyOn(console, "log").mockImplementation(() => {});
      await downCommand.parseAsync(["node", "flisk"], { from: "node" });
      expect(stopComposeWatchersMock).toHaveBeenCalledWith(watchers.slice(1));
    });
  });
});
