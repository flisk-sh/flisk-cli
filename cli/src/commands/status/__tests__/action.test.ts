import { describe, expect, it } from "vitest";

import { formatServiceUsage, usageTargets } from "../action.js";

describe("formatServiceUsage", () => {
  it("reports null on Windows even when a sample exists", () => {
    expect(formatServiceUsage({ cpuPercent: 5, rssBytes: 1024, processes: 1 }, "win32")).toBe(
      "usage: null (not available on Windows)",
    );
    expect(formatServiceUsage(null, "win32")).toBe("usage: null (not available on Windows)");
  });

  it("reports not running when there is no sample", () => {
    expect(formatServiceUsage(null, "darwin")).toBe("usage: null (not running)");
    expect(formatServiceUsage(null, "linux")).toBe("usage: null (not running)");
  });

  it("formats CPU, RSS and a plural process count", () => {
    expect(
      formatServiceUsage({ cpuPercent: 12.34, rssBytes: 1048576, processes: 3 }, "darwin"),
    ).toBe("usage: 12.3% CPU, 1.0 MB RSS, 3 processes");
  });

  it("uses the singular for one process", () => {
    expect(formatServiceUsage({ cpuPercent: 0.04, rssBytes: 512, processes: 1 }, "linux")).toBe(
      "usage: 0.0% CPU, 512 B RSS, 1 process",
    );
  });

  it("says so when the source reports no process count", () => {
    expect(
      formatServiceUsage({ cpuPercent: 25, rssBytes: 2097152, processes: null }, "darwin"),
    ).toBe("usage: 25.0% CPU, 2.0 MB RSS, process count not reported");
  });
});

describe("usageTargets", () => {
  it("prefers a recorded container over a recorded pid", () => {
    expect(
      usageTargets(
        [{ name: "api", stack: "main" }],
        { api: { status: "ready" } },
        { api: { pid: 4321, container: "proj-api-1" } },
        "proj",
      ),
    ).toEqual([{ name: "api", container: "proj-api-1" }]);
  });

  it("samples the recorded pid as its own process group for a live local service", () => {
    expect(
      usageTargets([{ name: "api" }], { api: { status: "ready" } }, { api: { pid: 4321 } }, null),
    ).toEqual([{ name: "api", pid: 4321, pgid: 4321 }]);
  });

  it("does not sample a recorded pid while the run reports the service unknown", () => {
    expect(
      usageTargets([{ name: "api" }], { api: { status: "unknown" } }, { api: { pid: 4321 } }, null),
    ).toEqual([{ name: "api" }]);
  });

  it("does not sample a pid that was never recorded for a local service", () => {
    expect(usageTargets([{ name: "api" }], { api: { status: "ready" } }, null, null)).toEqual([
      { name: "api" },
    ]);
    expect(usageTargets([{ name: "api" }], { api: { status: "ready" } }, {}, null)).toEqual([
      { name: "api" },
    ]);
  });

  it("targets the compose service of a Docker project, scoped to the stack's compose project", () => {
    expect(usageTargets([{ name: "api", stack: "Main" }], null, null, "MyProj")).toEqual([
      {
        name: "api",
        docker: true,
        service: "api",
        composeProject: "myproj-main-autogenerated",
      },
    ]);
  });

  it("targets the compose service without a compose project when stack or name is missing", () => {
    expect(usageTargets([{ name: "api" }], null, null, "proj")).toEqual([
      { name: "api", docker: true, service: "api" },
    ]);
    expect(usageTargets([{ name: "api", stack: "main" }], null, null, null)).toEqual([
      { name: "api", docker: true, service: "api" },
    ]);
  });

  it("still prefers a recorded container for a Docker project's mixed run", () => {
    expect(
      usageTargets([{ name: "api", stack: "main" }], null, { api: { container: "c1" } }, "proj"),
    ).toEqual([{ name: "api", container: "c1" }]);
  });
});
