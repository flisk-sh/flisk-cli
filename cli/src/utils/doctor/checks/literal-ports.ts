import type { CheckResult, DiscoveredResource } from "../../../types/index.js";
import { formatCount } from "../../formatting.js";
import { findProjectRoot } from "../../paths.js";
import { discoverResourcesFromRoot } from "../../services.js";

export interface LiteralPortFinding {
  service: string;
  field: string;
  port: number;
  owner: string;
  replacement: string;
}

const LITERAL_PORT_PATTERNS: readonly RegExp[] = [
  /(?:^|[^A-Za-z0-9.-])(?:localhost|127\.0\.0\.1|0\.0\.0\.0):(\d{1,5})(?!\d)/g,
  /(?:^|\s)--port(?:=|\s+)(\d{1,5})(?!\d)/g,
  /(?:^|[^A-Za-z0-9_])PORT=(\d{1,5})(?!\d)/g,
];

function isValidPortNumber(value: unknown): value is number {
  return typeof value === "number" && Number.isInteger(value) && value >= 1 && value <= 65535;
}

function portVariableForService(serviceName: string): string {
  const upper =
    serviceName
      .toUpperCase()
      .split(/[^A-Z0-9]+/)
      .filter(Boolean)
      .join("_") || "SERVICE";
  return `\${${upper}_PORT}`;
}

function collectDeclaredPorts(
  resources: readonly DiscoveredResource[],
): Map<number, Array<{ service: string; isPrimary: boolean }>> {
  const declared = new Map<number, Array<{ service: string; isPrimary: boolean }>>();
  const add = (port: number, service: string, isPrimary: boolean): void => {
    const owners = declared.get(port) ?? [];
    if (!owners.some((entry) => entry.service === service && entry.isPrimary === isPrimary)) {
      owners.push({ service, isPrimary });
    }
    declared.set(port, owners);
  };
  for (const resource of resources) {
    const config = resource.config;
    if (!config) continue;
    if (isValidPortNumber(config.port)) {
      add(config.port, resource.name, true);
    }
    const extraPorts = (config as Record<string, unknown>).extraPorts;
    if (Array.isArray(extraPorts)) {
      for (const entry of extraPorts) {
        if (!entry || typeof entry !== "object") continue;
        const record = entry as Record<string, unknown>;
        if (isValidPortNumber(record.port)) {
          add(record.port, resource.name, false);
        }
        if (isValidPortNumber(record.hostPort)) {
          add(record.hostPort, resource.name, false);
        }
      }
    }
  }
  return declared;
}

function extractLiteralPorts(text: string): number[] {
  const ports: number[] = [];
  for (const pattern of LITERAL_PORT_PATTERNS) {
    for (const match of text.matchAll(pattern)) {
      const port = Number(match[1]);
      if (isValidPortNumber(port)) ports.push(port);
    }
  }
  return ports;
}

function replacementForPort(
  serviceName: string,
  owners: ReadonlyArray<{ service: string; isPrimary: boolean }>,
): { owner: string; replacement: string } {
  const ownPrimary = owners.find((entry) => entry.service === serviceName && entry.isPrimary);
  if (ownPrimary) return { owner: serviceName, replacement: `\${PORT}` };
  const ownAny = owners.find((entry) => entry.service === serviceName);
  if (ownAny) return { owner: serviceName, replacement: portVariableForService(serviceName) };
  const first = owners[0];
  if (!first) return { owner: serviceName, replacement: `\${PORT}` };
  return { owner: first.service, replacement: portVariableForService(first.service) };
}

/**
 * Scans each service's `service.json` fields (`command`, `env`, and `healthCheck` strings) for
 * hardcoded port numbers that match any declared `port` or `extraPorts` entry in the project.
 * Never reads generated files such as `.autogenerated/Dockerfile.app.autogenerated`.
 */
export function findLiteralPorts(resources: readonly DiscoveredResource[]): LiteralPortFinding[] {
  const declared = collectDeclaredPorts(resources);
  if (declared.size === 0) return [];

  const findings: LiteralPortFinding[] = [];
  const seen = new Set<string>();

  const scanText = (service: string, field: string, text: string): void => {
    for (const port of extractLiteralPorts(text)) {
      const owners = declared.get(port);
      if (!owners) continue;
      const key = `${service}\0${field}\0${port}`;
      if (seen.has(key)) continue;
      seen.add(key);
      const { owner, replacement } = replacementForPort(service, owners);
      findings.push({ service, field, port, owner, replacement });
    }
  };

  for (const resource of resources) {
    const config = resource.config;
    if (!config) continue;

    if (typeof config.command === "string") {
      scanText(resource.name, "command", config.command);
    }

    if (config.env && typeof config.env === "object" && !Array.isArray(config.env)) {
      for (const [envKey, rawValue] of Object.entries(config.env)) {
        if (typeof rawValue !== "string") continue;
        const field = `env.${envKey}`;
        if (envKey === "PORT" && /^\d{1,5}$/.test(rawValue.trim())) {
          scanText(resource.name, field, `PORT=${rawValue.trim()}`);
        } else {
          scanText(resource.name, field, rawValue);
        }
      }
    }

    const hc = config.healthCheck as unknown;
    if (typeof hc === "string") {
      scanText(resource.name, "healthCheck", hc);
    } else if (hc && typeof hc === "object" && !Array.isArray(hc)) {
      const hcObj = hc as Record<string, unknown>;
      if (typeof hcObj.path === "string") {
        scanText(resource.name, "healthCheck.path", hcObj.path);
      }
      if (Array.isArray(hcObj.command)) {
        const parts = hcObj.command.filter((part): part is string => typeof part === "string");
        if (parts.length > 0) {
          scanText(resource.name, "healthCheck.command", parts.join(" "));
        }
      } else if (typeof hcObj.command === "string") {
        scanText(resource.name, "healthCheck.command", hcObj.command);
      }
    }
  }

  return findings;
}

/**
 * Warns when a service's `command`, `env`, or `healthCheck` hardcodes a port declared by any
 * service in the project (`port` or `extraPorts`), which parallel checkouts and automatic ports
 * cannot remap.
 */
export function checkLiteralPorts(
  projectRoot = findProjectRoot() ?? process.cwd(),
  resources?: DiscoveredResource[],
): CheckResult {
  let resolvedResources: DiscoveredResource[];
  if (resources !== undefined) {
    resolvedResources = resources;
  } else {
    try {
      resolvedResources = discoverResourcesFromRoot(projectRoot);
    } catch {
      resolvedResources = [];
    }
  }
  const findings = findLiteralPorts(resolvedResources);
  if (findings.length === 0) {
    return {
      name: "Literal ports",
      didPass: true,
      message: "No service hardcodes a declared port in command, env, or healthCheck",
    };
  }
  const lines = findings.map(
    (finding) =>
      `${finding.service} (${finding.field}): literal port ${finding.port} (use ${finding.replacement} instead)`,
  );
  return {
    name: "Literal ports",
    didPass: false,
    isWarning: true,
    message: `${formatCount(findings.length, "literal port")} in service.json that parallel checkouts and automatic ports cannot remap:\n    ${lines.join("\n    ")}`,
    fix: `Replace hardcoded ports in service.json command, env, or healthCheck with \${PORT} for the service's own port or \${<NAME>_PORT} for another service's port`,
  };
}
