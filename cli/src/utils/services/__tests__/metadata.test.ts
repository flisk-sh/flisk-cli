import { join } from "node:path";
import { beforeEach, describe, expect, it } from "vitest";
import { createTempProject } from "../../../test-support/index.js";
import type { DiscoveredResource, DiscoveredStack, ResourceType } from "../../../types/index.js";
import { clearMetadataCache, getResourceMetadata, getStackMetadata } from "../metadata.js";

const fixture = (dir: string, fields: Partial<DiscoveredResource> = {}): DiscoveredResource => ({
  name: "orders-api",
  path: dir,
  configPath: join(dir, "service.json"),
  config: { appName: "orders-api", appType: "backend" },
  ...fields,
});

const serviceDir = (root: string, name = "svc") => join(root, "services", name);

beforeEach(() => {
  clearMetadataCache();
});

describe("getResourceMetadata", () => {
  it.each<[ResourceType | undefined, string, ResourceType]>([
    ["backend", "web-frontend-api", "backend"],
    ["frontend", "store-api", "frontend"],
    [undefined, "shop-frontend", "frontend"],
    [undefined, "shared-sdk", "library"],
    [undefined, "common-lib", "library"],
    [undefined, "platform-infra", "library"],
    [undefined, "orders-api", "backend"],
  ])("appType %s on %s resolves to %s", (appType, name, expectedType) => {
    const root = createTempProject({ resources: { svc: "{}" } });
    const resource: DiscoveredResource = {
      name,
      path: serviceDir(root),
      configPath: join(serviceDir(root), "service.json"),
      ...(appType === undefined ? {} : { config: { appName: name, appType } }),
    };

    expect(getResourceMetadata(resource).type).toBe(expectedType);
  });

  it("reports the tooling files that sit next to the manifest", () => {
    const root = createTempProject({
      resources: { svc: "{}" },
      files: {
        "services/svc/Dockerfile": "FROM scratch\n",
        "services/svc/Tiltfile": "docker_build('x', '.')\n",
        "services/svc/docker-compose.yml": "services: {}\n",
        "services/svc/tsconfig.json": "{}\n",
      },
    });

    const metadata = getResourceMetadata(fixture(serviceDir(root)));

    expect(metadata.hasDockerfile).toBe(true);
    expect(metadata.hasTiltfile).toBe(true);
    expect(metadata.hasDockerCompose).toBe(true);
    expect(metadata.autogeneratedFiles.map((f) => [f.name, f.type])).toEqual([
      ["docker-compose.yml", "docker"],
      ["Dockerfile", "docker"],
      ["Tiltfile", "tilt"],
      ["tsconfig.json", "config"],
    ]);
  });

  it("detects docker-compose.yaml and prisma files", () => {
    const root = createTempProject({
      resources: { svc: "{}" },
      files: {
        "services/svc/docker-compose.yaml": "services: {}\n",
        "services/svc/prisma/schema.prisma": "model A {}\n",
        "services/svc/prisma/20260101_init_migration.sql": "SELECT 1;\n",
      },
    });

    const metadata = getResourceMetadata(fixture(serviceDir(root)));

    expect(metadata.hasDockerCompose).toBe(true);
    expect(metadata.autogeneratedFiles.map((f) => [f.name, f.type])).toEqual([
      ["docker-compose.yaml", "docker"],
      ["prisma/20260101_init_migration.sql", "prisma"],
      ["prisma/schema.prisma", "prisma"],
    ]);
  });

  it("marks a generated file whose first lines carry the generated banner", () => {
    const root = createTempProject({
      resources: { svc: "{}" },
      files: { "services/svc/tsconfig.build.json": "// GENERATED BY Flisk\n{}\n" },
    });

    expect(getResourceMetadata(fixture(serviceDir(root))).autogeneratedFiles).toEqual([
      expect.objectContaining({ name: "tsconfig.build.json", type: "generated" }),
    ]);
  });

  it("serves the cached object inside the TTL and recomputes after clearMetadataCache", () => {
    const root = createTempProject({ resources: { svc: "{}" } });
    const resource = fixture(serviceDir(root));

    const first = getResourceMetadata(resource);
    expect(getResourceMetadata(resource)).toBe(first);

    clearMetadataCache();
    const second = getResourceMetadata(resource);
    expect(second).not.toBe(first);
    expect(second).toEqual(first);
  });

  it("carries name, stack, port, dependencies and an unknown status", () => {
    const root = createTempProject({ resources: { svc: "{}" } });
    const resource = fixture(serviceDir(root), {
      stack: "shop",
      config: {
        appName: "orders-api",
        appType: "backend",
        port: 4317,
        dependsOn: ["db"],
      },
    });

    const metadata = getResourceMetadata(resource);

    expect(metadata).toEqual(
      expect.objectContaining({
        name: "orders-api",
        stack: "shop",
        type: "backend",
        port: 4317,
        dependencies: ["db"],
        status: "unknown",
      }),
    );
    expect(Date.parse(metadata.createdAt)).not.toBeNaN();
    expect(metadata.lastModified).toBe(metadata.createdAt);
  });
});

describe("getStackMetadata", () => {
  const stackOf = (resources: DiscoveredResource[]): DiscoveredStack => ({
    name: "core",
    resources,
    resourceCount: resources.length,
  });

  it("aggregates resource metadata with earliest and latest timestamps", () => {
    const root = createTempProject({ resources: { a: "{}", b: "{}" } });
    const stack = stackOf([
      fixture(serviceDir(root, "a"), { name: "api-a", stack: "core" }),
      fixture(serviceDir(root, "b"), { name: "api-b", stack: "core" }),
    ]);

    const metadata = getStackMetadata(stack);

    expect(metadata.name).toBe("core");
    expect(metadata.resourceCount).toBe(2);
    expect(metadata.resources).toHaveLength(2);
    expect(metadata.overallStatus).toBe("unknown");
    expect(Date.parse(metadata.createdAt)).not.toBeNaN();
    expect(Date.parse(metadata.lastModified)).not.toBeNaN();
    expect(metadata.createdAt <= metadata.lastModified).toBe(true);
  });

  it("serves the cached object inside the TTL and recomputes after clearMetadataCache", () => {
    const root = createTempProject({ resources: { a: "{}" } });
    const stack = stackOf([fixture(serviceDir(root, "a"))]);

    const first = getStackMetadata(stack);
    expect(getStackMetadata(stack)).toBe(first);

    clearMetadataCache();
    expect(getStackMetadata(stack)).not.toBe(first);
  });
});
