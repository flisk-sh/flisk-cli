const viteSpaFrameworks = Object.values(FRONTEND_FRAMEWORKS).filter(
  (provider) => (provider.kind ?? "vite-spa") === "vite-spa",
);

describe("every Vite frontend in the registry can run on the host", () => {
  it("declares its Vite setup, so no framework needs the engine for its config", () => {
    expect(viteSpaFrameworks.length).toBeGreaterThanOrEqual(9);
    for (const provider of viteSpaFrameworks) {
      expect(provider.vite, `${provider.id} has no vite setup`).toBeDefined();
    }
  });

  it.each(viteSpaFrameworks.map((provider) => [provider.id, provider] as const))(
    "%s: the plugin it imports is one of its own dependencies",
    (_id, provider) => {
      for (const statement of provider.vite?.imports ?? []) {
        const module = /from '([^']+)'/.exec(statement)?.[1] ?? "";
        const declared = { ...provider.dependencies, ...provider.devDependencies };
        const root = module.startsWith("@")
          ? module.split("/").slice(0, 2).join("/")
          : module.split("/")[0];
        expect(Object.keys(declared), `${provider.id} imports ${module}`).toContain(root);
      }
    },
  );

  it("writes a plain config: the framework plugin, one port, and no engine files", () => {
    const config = renderLocalViteConfig(FRONTEND_FRAMEWORKS.react as never, { port: 3456 });
    expect(config).toContain("import react from '@vitejs/plugin-react';");
    expect(config).toContain("plugins: [react()]");
    expect(config).toContain("process.env.PORT ?? 3456");
    // Flisk watches this exact port, so Vite must not quietly move to the next free one.
    expect(config).toContain("strictPort: true");
    expect(config).not.toMatch(/autogenerated|resolve\(__dirname/);
    expect(config).not.toContain("proxy");
  });

  it("writes imports in Biome's sorted order so a fresh scaffold passes its own lint", () => {
    for (const provider of viteSpaFrameworks) {
      const config = renderLocalViteConfig(provider as never, { port: 3456 });
      const modules = config
        .split("\n")
        .filter((line) => line.startsWith("import "))
        .map((line) => /from '([^']+)'/.exec(line)?.[1] ?? "");
      expect(modules, `${provider.id} has unsorted imports`).toEqual([...modules].sort());
    }
  });

  it("sorts a double-quoted import by its module too, so it never lands before vite", () => {
    const provider = {
      id: "x",
      label: "X",
      vite: { imports: ['import solid from "vite-plugin-solid";'], plugins: ["solid()"] },
    };
    const lines = renderLocalViteConfig(provider as never, { port: 3000 })
      .split("\n")
      .filter((line) => line.startsWith("import "));
    expect(lines).toEqual([
      "import { defineConfig } from 'vite';",
      'import solid from "vite-plugin-solid";',
    ]);
  });

  it("proxies the backend when there is one", () => {
    const config = renderLocalViteConfig(FRONTEND_FRAMEWORKS.vue as never, {
      port: 3000,
      proxyTarget: "http://localhost:4001",
    });
    expect(config).toContain("'/health': { target: 'http://localhost:4001'");
  });

  it("refuses a framework without a Vite setup instead of writing a broken config", () => {
    expect(() => renderLocalViteConfig({ id: "x", label: "X" } as never, { port: 3000 })).toThrow(
      /no Vite setup/,
    );
  });
});

const contentOf = (tasks: FileGenerationTask[], filename: string) =>
  (tasks.find((task) => task.filename === filename)?.content ?? {}) as Record<string, unknown>;

describe("applyLocalScaffold", () => {
  const scaffold = (): FileGenerationTask[] => [
    {
      type: "json",
      filename: "service.json",
      content: {
        build: { dockerfile: "Dockerfile" },
        dev: { command: "bun run dev" },
        healthCheckPath: "/health",
      },
      description: "",
      emoji: "",
    },
    {
      type: "json",
      filename: "package.json",
      content: {
        scripts: {
          predev: "x",
          prebuild: "y",
          dev: "vite --config .autogenerated/a.ts",
          build: "b",
        },
      },
      description: "",
      emoji: "",
    },
    { type: "text", filename: "Dockerfile", content: "FROM bun", description: "", emoji: "" },
  ];

  it("drops the Dockerfile, writes a vite config, and points service.json at an npm script", () => {
    const tasks = scaffold();
    const command = applyLocalScaffold({
      resourceName: "web",
      resourceType: "frontend",
      port: 3000,
      tasks,
      frontendFramework: FRONTEND_FRAMEWORKS.react,
      onPath: () => true,
    });
    expect(command).toBe("npm run dev");
    expect(tasks.map((task) => task.filename)).toEqual([
      "service.json",
      "package.json",
      "vite.config.ts",
    ]);
    const service = contentOf(tasks, "service.json");
    expect(service.command).toBe("npm run dev");
    expect(service).not.toHaveProperty("build");
    expect(service).not.toHaveProperty("dev");
    const scripts = contentOf(tasks, "package.json").scripts as Record<string, string>;
    expect(scripts.dev).toBe("vite");
    expect(scripts).not.toHaveProperty("predev");
    expect(scripts).not.toHaveProperty("prebuild");
  });

  it("a server framework keeps its own dev script and probes the root on the host", () => {
    const tasks = scaffold();
    contentOf(tasks, "service.json").healthCheckPath = "/web/health";
    applyLocalScaffold({
      resourceName: "web",
      resourceType: "frontend",
      port: 3000,
      tasks,
      frontendFramework: FRONTEND_FRAMEWORKS.next,
    });
    expect(tasks.some((task) => task.filename === "vite.config.ts")).toBe(false);
    expect(contentOf(tasks, "service.json").healthCheckPath).toBe("/");
  });

  it("a language that owns its runtime runs its own dev command", () => {
    const tasks = scaffold().filter((task) => task.filename !== "package.json");
    const command = applyLocalScaffold({
      resourceName: "api",
      resourceType: "backend",
      port: 4000,
      tasks,
      backendLanguage: {
        id: "go",
        label: "Go",
        devCommand: "go run .",
        gitignore: [],
        installHint: "",
      },
    });
    expect(command).toBe("go run .");
  });

  it("a worker declares no port: its readiness is the process staying alive", () => {
    const tasks = scaffold();
    contentOf(tasks, "service.json").port = 6000;
    const command = applyLocalScaffold({
      resourceName: "jobs",
      resourceType: "worker",
      port: 0,
      tasks,
    });
    expect(command).toBe("npm run dev");
    const service = contentOf(tasks, "service.json");
    expect(service.command).toBe("npm run dev");
    // A port would have `flisk up` wait on a listener that never comes; the worker scaffold serves no route.
    expect(service).not.toHaveProperty("port");
  });

  it.each(["mcp", "agent"] as const)(
    "a %s scaffold binds localhost for its HTTP server and keeps its port and health path",
    (resourceType) => {
      const tasks = [
        ...scaffold(),
        {
          type: "text" as const,
          filename: "src/index.ts",
          content: "server.listen(port, '0.0.0.0', onReady)",
          description: "",
          emoji: "",
        },
      ];
      applyLocalScaffold({ resourceName: "svc", resourceType, port: 4100, tasks });
      const service = contentOf(tasks, "service.json");
      expect(service.command).toBe("npm run dev");
      expect(service.port).toBe(4100);
      expect(service.healthCheckPath).toBe("/health");
      const index = tasks.find((task) => task.filename === "src/index.ts");
      expect(index?.content).toBe("server.listen(port, 'localhost', onReady)");
    },
  );

  it("an agent with files durability gets a .gitignore for the checkpoint store it writes locally", () => {
    const tasks = scaffold();
    contentOf(tasks, "service.json").agent = { runtime: "custom", durability: "files" };
    applyLocalScaffold({ resourceName: "bot", resourceType: "agent", port: 4100, tasks });
    const gitignore = tasks.find((task) => task.filename === ".gitignore");
    expect(gitignore?.content).toContain(".agent-state/");
  });

  it("an agent on postgres keeps no host checkpoint folder, so no .gitignore", () => {
    const tasks = scaffold();
    contentOf(tasks, "service.json").agent = { runtime: "custom", durability: "postgres" };
    applyLocalScaffold({ resourceName: "bot", resourceType: "agent", port: 4100, tasks });
    expect(tasks.some((task) => task.filename === ".gitignore")).toBe(false);
  });

  // The manager is the first of npm, bun, pnpm, yarn on the machine; npm stays the pick when it is
  // installed, so a Bun-only computer gets `bun run dev` instead of a command it cannot run (#3609).
  it.each([
    [["npm", "bun"], "npm run dev"],
    [["bun"], "bun run dev"],
    [["bun", "pnpm"], "bun run dev"],
    [["pnpm"], "pnpm run dev"],
    [["yarn"], "yarn run dev"],
    [[], "npm run dev"],
  ])("writes the run command through the first package manager on PATH %s", (present, expected) => {
    const tasks = scaffold();
    const command = applyLocalScaffold({
      resourceName: "web",
      resourceType: "frontend",
      port: 3000,
      tasks,
      frontendFramework: FRONTEND_FRAMEWORKS.react,
      onPath: (program) => present.includes(program),
    });
    expect(command).toBe(expected);
    expect(contentOf(tasks, "service.json").command).toBe(expected);
  });

  it("picks the machine's package manager for a backend package.json too", () => {
    const tasks = scaffold();
    const command = applyLocalScaffold({
      resourceName: "api",
      resourceType: "backend",
      port: 4000,
      tasks,
      onPath: (program) => program === "bun",
    });
    expect(command).toBe("bun run dev");
    expect(contentOf(tasks, "service.json").command).toBe("bun run dev");
  });

  it("keeps a Bun dev script on Bun even when npm is installed (#5403)", () => {
    const tasks = scaffold();
    contentOf(tasks, "package.json").scripts = {
      dev: "bun run --watch src/index.ts",
    };
    const command = applyLocalScaffold({
      resourceName: "api",
      resourceType: "backend",
      port: 4000,
      tasks,
      onPath: (program) => program === "npm" || program === "bun",
    });
    expect(command).toBe("bun run dev");
    expect(contentOf(tasks, "service.json").command).toBe("bun run dev");
  });

  it("lists in featuresEnabled only what the host run generated (#5122)", () => {
    const tasks = scaffold();
    contentOf(tasks, "service.json").featuresEnabled = [
      "api-client",
      "env-config",
      "api-index",
      "drizzle",
    ];
    applyLocalScaffold({ resourceName: "api", resourceType: "backend", port: 4000, tasks });
    // The three engine generators produce nothing for a local process; drizzle's files came from the CLI.
    expect(contentOf(tasks, "service.json").featuresEnabled).toEqual(["drizzle"]);
  });
});

