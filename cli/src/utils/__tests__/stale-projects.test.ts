function listingKind(args: string[]): string {
  if (args[0] === "ps" && !args.some((arg) => arg.startsWith("ancestor="))) return "containers";
  if (args[0] === "volume") return "volumes";
  if (args[0] === "network") return "networks";
  if (args[0] === "images") return "images";
  return "other";
}

describe("parseSizeToBytes", () => {
  it("parses plain byte and unit sizes", () => {
    expect(parseSizeToBytes("500B")).toBe(500);
    expect(parseSizeToBytes("10KB")).toBe(10 * 1024);
    expect(parseSizeToBytes("15.5MB")).toBe(15.5 * 1024 * 1024);
    expect(parseSizeToBytes("2GB")).toBe(2 * 1024 * 1024 * 1024);
    expect(parseSizeToBytes("0B")).toBe(0);
    expect(parseSizeToBytes("")).toBe(0);
  });

  it("prefers virtual container sizes when present", () => {
    expect(parseSizeToBytes("12MB (virtual 1.5GB)")).toBe(1.5 * 1024 * 1024 * 1024);
    expect(parseSizeToBytes("0B (virtual 500MB)")).toBe(500 * 1024 * 1024);
  });
});

describe("extractProjectRootFromWorkingDir", () => {
  it("extracts root from .flisk/.flisk-out directories", () => {
    expect(
      extractProjectRootFromWorkingDir("/Users/sunny/worktrees/agent-1/.flisk/.flisk-out"),
    ).toBe("/Users/sunny/worktrees/agent-1");
  });

  it("extracts root from service autogenerated directories", () => {
    expect(
      extractProjectRootFromWorkingDir(
        "/Users/sunny/worktrees/agent-1/services/web/.autogenerated",
      ),
    ).toBe("/Users/sunny/worktrees/agent-1");
  });

  it("returns plain path when not in an autogenerated subdirectory", () => {
    expect(extractProjectRootFromWorkingDir("/Users/sunny/projects/my-app")).toBe(
      "/Users/sunny/projects/my-app",
    );
  });
});

describe("isPathStale", () => {
  it("returns true when neither path nor project root exists", () => {
    const existing = new Set(["/existing/project"]);
    const checker = (p: string) => existing.has(p);

    expect(isPathStale("/deleted/project/.flisk/.flisk-out", checker)).toBe(true);
    expect(isPathStale("/existing/project/.flisk/.flisk-out", checker)).toBe(false);
  });
});

describe("findStaleProjects", () => {
  it("discovers stale projects whose directory is missing and groups resources", async () => {
    const existingDirs = new Set(["/live/project"]);
    const pathChecker = (p: string) => existingDirs.has(p);

    const fakeDocker = (_command: string, args: string[]) => {
      if (args[0] === "ps") {
        return [
          // Stale project container
          "c1\tstale-web-1\t10MB (virtual 100MB)\tstale-proj\t/deleted/worktree-1/.flisk/.flisk-out\t\t",
          // Live project container (should be ignored)
          "c2\tlive-web-1\t5MB (virtual 50MB)\tlive-proj\t/live/project/.flisk/.flisk-out\t\t",
          // Stale project second container
          "c3\tstale-worker-1\t5MB (virtual 50MB)\tstale-proj\t/deleted/worktree-1/.flisk/.flisk-out\t\t",
        ].join("\n");
      }
      if (args[0] === "volume") {
        return [
          "stale-proj_data\tstale-proj\t/deleted/worktree-1/.flisk/.flisk-out\t\t",
          "live-proj_data\tlive-proj\t/live/project/.flisk/.flisk-out\t\t",
        ].join("\n");
      }
      if (args[0] === "network") {
        return [
          "stale-proj_default\tstale-proj\t/deleted/worktree-1/.flisk/.flisk-out\t\t",
          "live-proj_default\tlive-proj\t/live/project/.flisk/.flisk-out\t\t",
        ].join("\n");
      }
      return "";
    };

    const report = await findStaleProjects({
      records: [],
      commandRunner: fakeDocker,
      pathChecker,
    });

    expect(report.totalProjects).toBe(1);
    expect(report.staleProjects).toHaveLength(1);

    const proj = report.staleProjects[0];
    expect(proj.name).toBe("stale-proj");
    expect(proj.recordedPath).toBe("/deleted/worktree-1");
    expect(proj.containers).toEqual(["stale-web-1", "stale-worker-1"]);
    expect(proj.volumes).toEqual(["stale-proj_data"]);
    expect(proj.networks).toEqual(["stale-proj_default"]);
    expect(proj.containerCount).toBe(2);
    expect(proj.volumeCount).toBe(1);
    expect(proj.networkCount).toBe(1);
    expect(proj.estimatedSizeBytes).toBe(150 * 1024 * 1024);
    expect(proj.recorded).toBe(false);
    expect(proj.cleanupCommand).toBe(`docker compose -p ${proj.name} down`);
  });

  it("returns an empty report when all projects are active", async () => {
    const existingDirs = new Set(["/live/project"]);
    const fakeDocker = (_command: string, args: string[]) => {
      if (args[0] === "ps") {
        return "c1\tlive-web-1\t10MB\tlive-proj\t/live/project/.flisk/.flisk-out\t\t";
      }
      return "";
    };

    const report = await findStaleProjects({
      records: [],
      commandRunner: fakeDocker,
      pathChecker: (p) => existingDirs.has(p),
    });

    expect(report.totalProjects).toBe(0);
    expect(report.staleProjects).toEqual([]);
    expect(report.totalContainers).toBe(0);
  });

  it("handles docker errors gracefully without crashing", async () => {
    const failingDocker = () => {
      throw new Error("Cannot connect to the Docker daemon");
    };

    const report = await findStaleProjects({
      records: [],
      commandRunner: failingDocker,
    });

    expect(report.totalProjects).toBe(0);
    expect(report.staleProjects).toEqual([]);
  });

  it("lists containers, volumes, networks and images once each for a recorded stale project", async () => {
    const name = "staleshop";
    const calls: string[] = [];
    const runner = (_command: string, args: string[]) => {
      const kind = listingKind(args);
      calls.push(kind);
      const isWide = args.some((arg) => arg.includes("working_dir"));
      if (kind === "containers") {
        return isWide
          ? `c1\t${name}-main-autogenerated-api-1\t1MB\t${name}-main-autogenerated\t/gone/${name}/.flisk/.flisk-out\t\t\t`
          : `${name}-main-autogenerated-api-1\t${name}-main-autogenerated`;
      }
      if (kind === "volumes") {
        return isWide
          ? `${name}-main-autogenerated_uploads\t${name}-main-autogenerated\t/gone/${name}/.flisk/.flisk-out\t\t`
          : `${name}-main-autogenerated_uploads\t${name}-main-autogenerated`;
      }
      if (kind === "networks") return isWide ? `${name}_backend\t\t\t\t` : `${name}_backend`;
      if (kind === "images") return `${name}-l1:latest`;
      return "";
    };

    const report = await findStaleProjects({
      records: [{ name, roots: [`/gone/${name}`], stacks: ["main"], updatedAt: "" }],
      commandRunner: runner,
      pathChecker: () => false,
      holds: () => false,
    });

    expect(report.staleProjects.map((project) => project.name)).toEqual([name]);
    const counts = calls.reduce<Record<string, number>>((acc, kind) => {
      acc[kind] = (acc[kind] ?? 0) + 1;
      return acc;
    }, {});
    expect(counts).toEqual({ containers: 1, volumes: 1, networks: 1, images: 1 });
  });

  it("starts the four independent listings together", async () => {
    const started: string[] = [];
    const finish: Array<() => void> = [];
    const reportPromise = findStaleProjects({
      records: [],
      pathChecker: () => false,
      commandRunner: (_command, args) => {
        started.push(listingKind(args));
        return new Promise<string>((resolve) => {
          finish.push(() => resolve(""));
        });
      },
    });

    await Promise.resolve();
    expect(started.slice().sort()).toEqual(["containers", "images", "networks", "volumes"]);
    for (const resolve of finish) resolve();
    await expect(reportPromise).resolves.toMatchObject({ totalProjects: 0 });
  });
});

describe("findStaleProjects with the projects flisk up recorded", () => {
  // After `flisk down` a deleted project has no containers left, and a volume records no folder: only the record of
  // where the project lived tells its database volume apart from a stopped project's (the 31 unused volumes of #3360).
  const runner = (_command: string, args: string[]): string => {
    if (args[0] === "ps") return "";
    if (args[0] === "volume") {
      return [
        "hpc52513-database-management_hpc52513_postgres_data\thpc52513-database-management\t\t\t",
        "shop-database-management_shop_postgres_data\tshop-database-management\t\t\t",
      ].join("\n");
    }
    if (args[0] === "network") {
      return args.includes("{{.Name}}")
        ? "hpc52513_backend\nshop_backend"
        : "hpc52513_backend\t\t\t\t\nshop_backend\t\t\t\t";
    }
    if (args[0] === "images") return "hpc52513-l1:latest\nhpc52513_main_api:dev\nshop-l1:latest";
    return "";
  };
  const records = [
    { name: "hpc52513", roots: ["/tmp/hpc52513"], stacks: ["main"], updatedAt: "" },
    { name: "shop", roots: ["/work/shop"], stacks: ["main"], updatedAt: "" },
  ];
  const holds = (root: string) => root === "/work/shop";

  it("reuses Docker listings across five stale recorded projects", async () => {
    const manyRecords = Array.from({ length: 5 }, (_, index) => {
      const name = `stale-${index}`;
      return { name, roots: [`/tmp/${name}`], stacks: ["main"], updatedAt: "" };
    });
    const listingArgs = [CONTAINER_LIST_ARGS, VOLUME_LIST_ARGS, NETWORK_LIST_ARGS, IMAGE_LIST_ARGS];
    const calls = new Map<string, number>();
    const report = await findStaleProjects({
      commandRunner: (_command, args) => {
        const key = JSON.stringify(args);
        calls.set(key, (calls.get(key) ?? 0) + 1);
        if (args[0] !== "ps") return "";
        return manyRecords
          .map(
            ({ name }) =>
              `c1\t${name}-main-autogenerated-api-1\t1MB\t${name}-main-autogenerated\t/tmp/${name}/.flisk/.flisk-out\t\t`,
          )
          .join("\n");
      },
      pathChecker: () => false,
      records: manyRecords,
      holds: () => false,
    });

    expect(
      report.staleProjects.map(({ name, recordedPath, containers }) => ({
        name,
        recordedPath,
        containers,
      })),
    ).toEqual(
      manyRecords.map(({ name, roots }) => ({
        name,
        recordedPath: roots[0],
        containers: [`${name}-main-autogenerated-api-1`],
      })),
    );
    expect(report.totalContainers).toBe(5);
    expect(listingArgs.map((args) => calls.get(JSON.stringify([...args])))).toEqual([1, 1, 1, 1]);
  });

  it("skips the ancestor queries when no recorded project is stale", async () => {
    const ancestorCalls: string[][] = [];
    const runner = (_command: string, args: string[]): string => {
      if (args.some((arg) => arg.startsWith("ancestor="))) {
        ancestorCalls.push(args);
        return "";
      }
      if (args[0] === "images") return "flisk-wake-gateway:latest";
      return "";
    };
    await findStaleProjects({ commandRunner: runner, records: [], pathChecker: () => true });
    await findStaleProjects({
      commandRunner: runner,
      records: [{ name: "live", roots: ["/live"], stacks: ["main"], updatedAt: "" }],
      holds: () => true,
      pathChecker: () => true,
    });
    expect(ancestorCalls).toEqual([]);
  });

  it("keeps the ancestor query for a stale recorded project", async () => {
    const ancestorCalls: string[][] = [];
    await findStaleProjects({
      commandRunner: (_command, args) => {
        if (args.some((arg) => arg.startsWith("ancestor="))) ancestorCalls.push(args);
        if (args[0] === "images") return "flisk-wake-gateway:latest";
        return "";
      },
      records: [{ name: "gone", roots: ["/gone"], stacks: ["main"], updatedAt: "" }],
      holds: () => false,
      pathChecker: () => false,
    });
    expect(ancestorCalls).toHaveLength(1);
  });

  it("turns a synchronous throw from the ancestor query into an empty answer", async () => {
    const report = await findStaleProjects({
      commandRunner: (_command, args) => {
        if (args.some((arg) => arg.startsWith("ancestor="))) throw new Error("boom");
        if (args[0] === "images") return "flisk-wake-gateway:latest";
        return "";
      },
      records: [{ name: "gone", roots: ["/gone"], stacks: ["main"], updatedAt: "" }],
      holds: () => false,
      pathChecker: () => false,
    });
    expect(report.staleProjects).toBeDefined();
  });

  it("reports the volumes, networks and images of a recorded project whose folder is gone", async () => {
    const report = await findStaleProjects({
      commandRunner: runner,
      pathChecker: () => false,
      records,
      holds,
    });

    expect(report.staleProjects.map((project) => project.name)).toEqual(["hpc52513"]);
    const [stale] = report.staleProjects;
    expect(stale?.volumes).toEqual(["hpc52513-database-management_hpc52513_postgres_data"]);
    expect(stale?.networks).toEqual(["hpc52513_backend"]);
    expect(stale?.images).toEqual(["hpc52513-l1:latest", "hpc52513_main_api:dev"]);
    expect(stale?.recordedPath).toBe("/tmp/hpc52513");
    expect(stale?.recorded).toBe(true);
    expect(stale?.cleanupCommand).toBe("flisk projects --stale --prune");
    expect(report.totalVolumes).toBe(1);
    expect(report.totalImages).toBe(2);
  });

  it("keeps a foreign Compose project out of a recorded project of the same name", async () => {
    const labelled = (_command: string, args: string[]): string => {
      if (args[0] === "ps" && args.join(" ").includes("working_dir")) {
        return "abc\tforeign-1\t1MB\thpc52513\t/gone/foreign\t\t";
      }
      return runner(_command, args);
    };

    const report = await findStaleProjects({
      commandRunner: labelled,
      pathChecker: () => false,
      records,
      holds,
    });

    const flisk = report.staleProjects.find((project) => project.recorded);
    expect(flisk?.containers).toEqual([]);
    const other = report.staleProjects.find((project) => !project.recorded);
    expect(other?.containers).toEqual(["foreign-1"]);
  });

  it("leaves a project that still exists alone, even when it is stopped", async () => {
    const report = await findStaleProjects({
      commandRunner: runner,
      pathChecker: () => false,
      records,
      holds: () => true,
    });

    expect(report.staleProjects).toEqual([]);
  });

  it("surfaces a stale recorded project with zero Docker resources (e.g. command-only or already downed)", async () => {
    const emptyRunner = (): string => "";
    const commandOnlyRecord = {
      name: "cmd-only",
      roots: ["/tmp/cmd-only"],
      stacks: ["main"],
      updatedAt: "",
    };

    const report = await findStaleProjects({
      commandRunner: emptyRunner,
      pathChecker: () => false,
      records: [commandOnlyRecord],
      holds: () => false,
    });

    expect(report.totalProjects).toBe(1);
    expect(report.totalContainers).toBe(0);
    expect(report.totalVolumes).toBe(0);
    expect(report.totalNetworks).toBe(0);
    expect(report.totalImages).toBe(0);
    expect(report.staleProjects).toEqual([
      {
        name: "cmd-only",
        recordedPath: "/tmp/cmd-only",
        containers: [],
        volumes: [],
        networks: [],
        images: [],
        recorded: true,
        containerCount: 0,
        volumeCount: 0,
        networkCount: 0,
        imageCount: 0,
        estimatedSizeBytes: 0,
        estimatedSize: "0 B",
        cleanupCommand: "flisk projects --stale --prune",
      },
    ]);
  });
});

describe("pruneStaleProjects", () => {
  const stale = {
    name: "hpc52513",
    recordedPath: "/tmp/hpc52513",
    containers: [],
    volumes: ["hpc52513-database-management_hpc52513_postgres_data"],
    networks: ["hpc52513_backend"],
    images: ["hpc52513-l1:latest"],
    recorded: true,
    containerCount: 0,
    volumeCount: 1,
    networkCount: 1,
    imageCount: 1,
    estimatedSizeBytes: 0,
    estimatedSize: "0 B",
    cleanupCommand: "flisk projects --stale --prune",
  };

  it("removes what the report listed and forgets the project", () => {
    const calls: string[][] = [];
    const forgotten: string[] = [];
    const result = pruneStaleProjects([stale], {
      docker: (args) => {
        calls.push(args);
        return "";
      },
      forget: (name) => forgotten.push(name),
    });

    expect(calls).toEqual([
      ["volume", "rm", "hpc52513-database-management_hpc52513_postgres_data"],
      ["network", "rm", "hpc52513_backend"],
      ["image", "rm", "hpc52513-l1:latest"],
    ]);
    expect(result.projects[0]?.kept).toEqual([]);
    expect(forgotten).toEqual(["hpc52513"]);
  });

  it("never touches a Compose project flisk up did not record, which may not be Flisk's", () => {
    // Regression: --prune force-removed every project the report listed, and the report lists any Compose project
    // whose folder is gone.
    const foreign = {
      ...stale,
      name: "someone-elses-app",
      containers: ["someone-elses-app-web-1"],
      volumes: ["someone-elses-app_data"],
      networks: [],
      images: [],
      recorded: false,
    };
    const calls: string[][] = [];
    const forgotten: string[] = [];

    const result = pruneStaleProjects([foreign], {
      docker: (args) => {
        calls.push(args);
        return "";
      },
      forget: (name) => forgotten.push(name),
    });

    expect(calls).toEqual([]);
    expect(forgotten).toEqual([]);
    expect(result).toEqual({ projects: [], skipped: ["someone-elses-app"] });
  });

  it("keeps the record while Docker still holds something of the project", () => {
    const forgotten: string[] = [];
    const result = pruneStaleProjects([stale], {
      docker: (args) => {
        if (args[0] === "volume")
          throw Object.assign(new Error("x"), { stderr: "volume is in use" });
        return "";
      },
      forget: (name) => forgotten.push(name),
    });

    expect(result.projects[0]?.kept).toEqual([
      {
        kind: "volumes",
        name: "hpc52513-database-management_hpc52513_postgres_data",
        reason: "volume is in use",
      },
    ]);
    expect(forgotten).toEqual([]);
  });

  it("does not offer to forget a recorded project when Docker could not be listed", async () => {
    const report = await findStaleProjects({
      commandRunner: () => {
        throw new Error("Cannot connect to the Docker daemon");
      },
      pathChecker: () => false,
      records: [{ name: "cmd-only", roots: ["/tmp/cmd-only"], stacks: ["main"], updatedAt: "" }],
      holds: () => false,
    });

    expect(report.staleProjects).toEqual([]);
    expect(report.totalProjects).toBe(0);
  });

  it("reports a registry record it could not delete instead of calling it removed", () => {
    const registryOnly = {
      ...stale,
      name: "cmd-only",
      recordedPath: "/tmp/cmd-only",
      containers: [],
      volumes: [],
      networks: [],
      images: [],
      containerCount: 0,
      volumeCount: 0,
      networkCount: 0,
      imageCount: 0,
    };

    const result = pruneStaleProjects([registryOnly], {
      docker: () => "",
      forget: () => {
        throw new Error("EACCES: permission denied");
      },
    });

    expect(result.projects).toEqual([
      {
        name: "cmd-only",
        removed: { containers: [], volumes: [], networks: [], images: [] },
        kept: [],
        recordError: "EACCES: permission denied",
      },
    ]);
  });

  it("forgets registry-only stale recorded projects without calling Docker", () => {
    const registryOnly = {
      ...stale,
      name: "cmd-only",
      recordedPath: "/tmp/cmd-only",
      volumes: [],
      networks: [],
      images: [],
      volumeCount: 0,
      networkCount: 0,
      imageCount: 0,
    };
    const calls: string[][] = [];
    const forgotten: string[] = [];

    const result = pruneStaleProjects([registryOnly], {
      docker: (args) => {
        calls.push(args);
        return "";
      },
      forget: (name) => forgotten.push(name),
    });

    expect(calls).toEqual([]);
    expect(forgotten).toEqual(["cmd-only"]);
    expect(result).toEqual({
      projects: [
        {
          name: "cmd-only",
          removed: { containers: [], volumes: [], networks: [], images: [] },
          kept: [],
        },
      ],
      skipped: [],
    });
  });
});
