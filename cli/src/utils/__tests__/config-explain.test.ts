import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { explainConfigFile } from "../config-explain.js";
import { FliskError } from "../errors.js";

let dir: string;
beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), "flisk-explain-"));
});
afterEach(() => {
  rmSync(dir, { recursive: true, force: true });
});

/** Writes `content` at the project-relative path `rel`, creating parent folders. */
function writeProjectFile(rel: string, content: string): void {
  const target = join(dir, rel);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
}

const SERVICE_JSON = '{"appName":"api","appType":"backend"}\n';
const COMPOSE_YML = "services: {}\n";

const explain = (rel: string) => explainConfigFile(dir, join(dir, rel));

/** Asserts the explanation's shape (plus a fragment of its reason when given). */
function expectShape(rel: string, shape: Record<string, unknown>, reason?: string): void {
  const result = explain(rel);
  expect(result).toMatchObject({ file: rel, isEditedNow: false, ...shape });
  if (reason !== undefined) {
    expect(result.reason).toContain(reason);
  }
}

describe("explainConfigFile", () => {
  it.each<[label: string, target: () => string, message: string]>([
    ["a path outside the project", () => join(dir, "..", "outside.txt"), "is outside the project"],
    ["the project root itself", () => dir, "is outside the project"],
    ["a missing file", () => join(dir, "missing.txt"), "File not found: missing.txt"],
    [
      "a directory",
      () => {
        const subdir = join(dir, "subdir");
        mkdirSync(subdir);
        return subdir;
      },
      "Not a file: subdir",
    ],
  ])("throws a FliskError for %s", (_label, target, message) => {
    const resolved = target();
    expect(() => explainConfigFile(dir, resolved)).toThrow(FliskError);
    expect(() => explainConfigFile(dir, resolved)).toThrow(message);
  });

  it("reports a plain file like README.md as user-owned", () => {
    writeProjectFile("README.md", "# Notes\n");
    expectShape("README.md", {
      ownership: "user-owned",
      source: null,
      driftOnUp: "none",
      next: ["Edit it directly."],
    });
  });

  it("reports the root package.json as user-owned because Flisk never overwrites it", () => {
    writeProjectFile("package.json", "{}\n");
    expectShape(
      "package.json",
      { ownership: "user-owned", source: null, driftOnUp: "none" },
      "never overwrites",
    );
  });

  describe("service outputs under .autogenerated", () => {
    it("reports unknown ownership when no service.json sits beside .autogenerated", () => {
      writeProjectFile("api/.autogenerated/docker-compose.yml", COMPOSE_YML);
      expectShape(
        "api/.autogenerated/docker-compose.yml",
        { ownership: "unknown", source: null, driftOnUp: "unknown" },
        "service.json",
      );
    });

    it("reports driftOnUp unknown when Flisk has no snapshot of the file yet", () => {
      writeProjectFile("api/service.json", SERVICE_JSON);
      writeProjectFile("api/.autogenerated/docker-compose.yml", COMPOSE_YML);
      expectShape("api/.autogenerated/docker-compose.yml", {
        ownership: "generated",
        source: "api/service.json",
        driftOnUp: "unknown",
      });
    });

    it("reports driftOnUp blocks-up when a snapshot exists for the file", () => {
      writeProjectFile("api/service.json", SERVICE_JSON);
      writeProjectFile("api/.autogenerated/docker-compose.yml", COMPOSE_YML);
      writeProjectFile("api/.autogenerated/.flisk-contract/docker-compose.yml", COMPOSE_YML);
      expectShape("api/.autogenerated/docker-compose.yml", {
        ownership: "generated",
        source: "api/service.json",
        driftOnUp: "blocks-up",
      });
    });

    it("reports the .flisk-contract snapshot itself as generated without drift", () => {
      writeProjectFile("api/service.json", SERVICE_JSON);
      writeProjectFile("api/.autogenerated/.flisk-contract/docker-compose.yml", COMPOSE_YML);
      expectShape(
        "api/.autogenerated/.flisk-contract/docker-compose.yml",
        { ownership: "generated", source: "api/service.json", driftOnUp: "none" },
        "snapshot",
      );
    });

    it("reports .autogenerated/service.yaml as a generated file exempt from the edit check", () => {
      writeProjectFile("api/service.json", SERVICE_JSON);
      writeProjectFile("api/.autogenerated/service.yaml", "resources: {}\n");
      expectShape(
        "api/.autogenerated/service.yaml",
        { ownership: "generated", source: "api/service.json", driftOnUp: "none" },
        "exempt",
      );
    });
  });
});
