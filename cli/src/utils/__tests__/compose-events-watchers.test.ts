import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import {
  type ComposeEventsWatcher,
  eventsTiltPids,
  findOrphanedComposeEventsWatchers,
  findProjectComposeEventsWatchers,
  listComposeEventsWatchers,
  stillComposeEventsWatcher,
  stopComposeEventsWatchers,
  watcherIdentity,
} from "../compose-events-watchers.js";

const dirs: string[] = [];

afterEach(() => {
  for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true });
});

function tempDir(prefix: string): string {
  const dir = realpathSync(mkdtempSync(join(tmpdir(), prefix)));
  dirs.push(dir);
  return dir;
}

/** A scratch Flisk project root: `.flisk/project.json` plus the folders Compose files are generated into. */
function makeProject(name: string): string {
  const root = tempDir(`flisk-watchers-${name}-`);
  mkdirSync(join(root, ".flisk", ".flisk-out"), { recursive: true });
  writeFileSync(join(root, ".flisk", "project.json"), JSON.stringify({ project: { name } }));
  return root;
}

function watcher(
  pid: number,
  projectName: string,
  projectDir: string,
  exe = "/usr/local/bin/docker",
): ComposeEventsWatcher {
  return {
    pid,
    command: `${exe} compose --project-name ${projectName} --project-directory ${projectDir} events --json`,
    projectName,
    projectDir,
  };
}

describe("listComposeEventsWatchers", () => {
  const shop = "/work/shop";
  const ps = [
    // The docker CLI and its compose plugin child are one watcher pair and both match.
    `  700 /usr/local/bin/docker compose --project-name shop-web-autogenerated --project-directory ${shop}/services/web/.autogenerated events --json`,
    `  701 /usr/local/lib/docker/cli-plugins/docker-compose compose --project-name shop-web-autogenerated --project-directory ${shop}/services/web/.autogenerated events --json`,
    `  702 /usr/bin/com.docker.cli compose --project-name shop-traefik --project-directory=${shop}/.flisk/.flisk-out events --json`,
    "  703 docker compose -p shop-database-management --project-directory /work/shop/services/platform/database-management events --json",
    // Not event streams: the daemon's own events, other compose subcommands, other binaries.
    "  704 /usr/local/bin/docker events",
    "  705 /usr/local/bin/docker compose logs -f shop",
    "  706 /usr/local/bin/docker compose --project-name x ps --format json",
    "  707 /opt/homebrew/bin/tilt up -f /work/shop/.flisk/.flisk-out/Tiltfile",
    // `events` is a positional argument here (a service/exec target), not the subcommand.
    "  708 /usr/local/bin/docker compose exec web events --json",
    `  709 /usr/local/bin/docker compose --project-directory ${shop} config events --json`,
    "  invalid line without a pid",
  ].join("\n");

  it("finds docker CLI and plugin `events --json` processes with their project name and directory", () => {
    const found = listComposeEventsWatchers("darwin", () => ps);
    expect(found).toEqual([
      {
        pid: 700,
        command: expect.stringContaining("--project-name shop-web-autogenerated"),
        projectName: "shop-web-autogenerated",
        projectDir: `${shop}/services/web/.autogenerated`,
      },
      {
        pid: 701,
        command: expect.stringContaining("docker-compose compose"),
        projectName: "shop-web-autogenerated",
        projectDir: `${shop}/services/web/.autogenerated`,
      },
      {
        pid: 702,
        command: expect.stringContaining("com.docker.cli"),
        projectName: "shop-traefik",
        projectDir: `${shop}/.flisk/.flisk-out`,
      },
      {
        pid: 703,
        command: expect.stringContaining("-p shop-database-management"),
        projectName: "shop-database-management",
        projectDir: "/work/shop/services/platform/database-management",
      },
    ]);
  });

  it("reads the subcommand past Compose's global options and their values", () => {
    const tricky = [
      // `events` here is the value of --env-file: the subcommand is `run`, and `--json` belongs to it.
      "  800 docker compose --project-name shop-dev --project-directory /work/shop --env-file events run --rm worker task --json",
      // `config` is the value of --env-file, so the subcommand really is `events`.
      "  801 docker compose --project-name shop-dev --project-directory /work/shop --env-file config events --json",
    ].join("\n");
    expect(listComposeEventsWatchers("darwin", () => tricky)?.map((w) => w.pid)).toEqual([801]);
  });

  it("reports null on Windows and when ps fails, never an empty list pretending success", () => {
    expect(listComposeEventsWatchers("win32", () => ps)).toBeNull();
    expect(
      listComposeEventsWatchers("linux", () => {
        throw new Error("no ps");
      }),
    ).toBeNull();
  });
});

describe("findProjectComposeEventsWatchers", () => {
  it("matches only this project's watchers: project directory inside the root AND its compose naming", () => {
    const root = makeProject("shop");
    const other = makeProject("shop-admin");
    const nested = join(root, "worktree");
    mkdirSync(join(nested, ".flisk", ".flisk-out"), { recursive: true });
    mkdirSync(join(nested, "services", "app", ".autogenerated"), { recursive: true });
    writeFileSync(join(nested, ".flisk", "project.json"), "{}");
    const ps = [
      `  700 docker compose --project-name shop-web-autogenerated --project-directory ${root}/services/web/.autogenerated events --json`,
      `  701 docker compose --project-name shop-traefik --project-directory ${root}/.flisk/.flisk-out events --json`,
      `  702 docker compose --project-name shop-database-management --project-directory ${root}/services/platform/database-management events --json`,
      // `shop-admin` names start with `shop-`, but its watchers point into its own root.
      `  703 docker compose --project-name shop-admin-web-autogenerated --project-directory ${other}/services/web/.autogenerated events --json`,
      // Same name, but the directory lies outside the project: not this project's stream.
      `  704 docker compose --project-name shop-web-autogenerated --project-directory ${other}/copy/.autogenerated events --json`,
      // A nested Flisk project's watcher lives inside the root but is not this project's.
      `  705 docker compose --project-name nested-app-autogenerated --project-directory ${nested}/.flisk/.flisk-out events --json`,
      // Inside the root without this project's name: a hand-run Compose session is left alone.
      `  706 docker compose --project-name dev-env --project-directory ${root}/tools/dev-env events --json`,
      // A worktree of this repo keeps the same project name and sits inside the root: its live watcher must
      // survive `flisk down` here because it belongs to the nested project, not this one (#4854).
      `  707 docker compose --project-name shop-app-autogenerated --project-directory ${nested}/services/app/.autogenerated events --json`,
      `  708 docker compose --project-name shop-web-autogenerated --project-directory ${nested}/.flisk/.flisk-out events --json`,
    ].join("\n");
    expect(
      findProjectComposeEventsWatchers(root, "shop", "darwin", () => ps).map((w) => w.pid),
    ).toEqual([700, 701, 702]);
  });

  it("leaves a nested project's watcher alone even when its generated directory was deleted", () => {
    const root = makeProject("shop");
    const nested = join(root, "worktree");
    mkdirSync(join(nested, ".flisk"), { recursive: true });
    writeFileSync(join(nested, ".flisk", "project.json"), "{}");
    const ps = [
      // The nested worktree's own generated folder no longer exists, but its nearest Flisk project is the worktree.
      `  700 docker compose --project-name shop-app-autogenerated --project-directory ${nested}/services/gone/.autogenerated events --json`,
      // This project's own deleted generated folder is still this project's.
      `  701 docker compose --project-name shop-app-autogenerated --project-directory ${root}/services/gone/.autogenerated events --json`,
    ].join("\n");
    expect(
      findProjectComposeEventsWatchers(root, "shop", "darwin", () => ps).map((w) => w.pid),
    ).toEqual([701]);
  });

  it("finds nothing on Windows, when ps fails, or when the project has no watchers", () => {
    const root = makeProject("shop");
    expect(findProjectComposeEventsWatchers(root, "shop", "win32", () => "")).toEqual([]);
    expect(
      findProjectComposeEventsWatchers(root, "shop", "linux", () => {
        throw new Error("no ps");
      }),
    ).toEqual([]);
    expect(findProjectComposeEventsWatchers(root, "shop", "darwin", () => "  1 launchd")).toEqual(
      [],
    );
  });
});

describe("stopComposeEventsWatchers", () => {
  it("TERMs every watcher pid and skips the ones already gone", () => {
    const sent: string[][] = [];
    const watchers = [
      watcher(10, "shop-web-autogenerated", "/work/shop/x"),
      watcher(
        11,
        "shop-web-autogenerated",
        "/work/shop/x",
        "/usr/local/lib/docker/cli-plugins/docker-compose",
      ),
      watcher(12, "shop-traefik", "/work/shop/.flisk/.flisk-out"),
    ];
    const runner = (_command: string, args: string[]): string => {
      if (args[1] === "11") throw new Error("ESRCH: no such process");
      sent.push(args);
      return "";
    };
    expect(stopComposeEventsWatchers(watchers, runner)).toEqual([10, 12]);
    expect(sent).toEqual([
      ["-TERM", "10"],
      ["-TERM", "12"],
    ]);
  });
});

describe("findOrphanedComposeEventsWatchers", () => {
  it("is an orphan when its project directory was deleted and nothing of the stack survives", () => {
    const gone = join(tmpdir(), "flisk-watchers-deleted-dir");
    const found = findOrphanedComposeEventsWatchers({
      watchers: [
        watcher(1, "shop-app-autogenerated", join(gone, "services/app/.autogenerated")),
        // A container of a different project does not keep this stream needed.
        watcher(2, "shop-traefik", join(gone, ".flisk", ".flisk-out")),
      ],
      runningProjects: new Set(["other-project-autogenerated"]),
      fliskRoots: [],
      tiltPids: () => [],
    });
    expect(found?.map((orphan) => orphan.pid).sort()).toEqual([1, 2]);
    expect(found?.[0]?.gone).toContain("deleted");
  });

  it("keeps a deleted-dir watcher while its stack still runs: ps truncates a --project-directory with spaces", () => {
    // `docker compose --project-directory /Users/Aariv Patel/proj/x` reports back as `/Users/Aariv`,
    // which merely looks deleted; the running container of the same project proves the stack lives.
    const found = findOrphanedComposeEventsWatchers({
      watchers: [watcher(1, "shop-app-autogenerated", "/Users/Aariv")],
      runningProjects: new Set(["shop-app-autogenerated"]),
      fliskRoots: [],
      tiltPids: () => [],
    });
    expect(found).toEqual([]);
  });

  it("is an orphan when its compose project has no running containers and its Tilt is gone", () => {
    const root = makeProject("shop");
    mkdirSync(join(root, "services", "app", ".autogenerated"), { recursive: true });
    const found = findOrphanedComposeEventsWatchers({
      watchers: [
        watcher(1, "shop-app-autogenerated", join(root, "services", "app", ".autogenerated")),
        watcher(2, "shop-traefik", join(root, ".flisk", ".flisk-out")),
      ],
      runningProjects: new Set(),
      fliskRoots: [],
      tiltPids: () => [],
    });
    expect(found?.map((orphan) => orphan.pid).sort()).toEqual([1, 2]);
    expect(found?.find((orphan) => orphan.pid === 1)?.owningRoot).toBe(root);
  });

  it("is an orphan when the stack's containers all exited", () => {
    const root = makeProject("shop");
    mkdirSync(join(root, "x", ".autogenerated"), { recursive: true });
    const found = findOrphanedComposeEventsWatchers({
      // A running container of ANOTHER project does not keep this stream needed.
      watchers: [watcher(1, "shop-app-autogenerated", join(root, "x", ".autogenerated"))],
      runningProjects: new Set(["other-project-autogenerated"]),
      fliskRoots: [],
      tiltPids: () => [],
    });
    expect(found?.map((orphan) => orphan.pid)).toEqual([1]);
  });

  it("keeps a stream whose project still runs containers, or whose Tilt is still up", () => {
    const root = makeProject("shop");
    mkdirSync(join(root, "x", ".autogenerated"), { recursive: true });
    const running = findOrphanedComposeEventsWatchers({
      watchers: [
        watcher(1, "shop-app-autogenerated", join(root, "x", ".autogenerated")),
        watcher(2, "shop-traefik", join(root, ".flisk", ".flisk-out")),
      ],
      runningProjects: new Set(["shop-app-autogenerated"]),
      fliskRoots: [],
      tiltPids: () => [900],
    });
    expect(running).toEqual([]);
  });

  it("finds infra watchers under services/platform through the .flisk ancestor, never a user-run compose session", () => {
    const root = makeProject("shop");
    mkdirSync(join(root, "services", "platform", "database-management"), { recursive: true });
    const plain = tempDir("flisk-watchers-user-");
    mkdirSync(join(plain, "deploy"), { recursive: true });
    const found = findOrphanedComposeEventsWatchers({
      watchers: [
        watcher(
          1,
          "shop-database-management",
          join(root, "services", "platform", "database-management"),
        ),
        // A user's own compose project named *-traefik outside any Flisk layout is not touched.
        watcher(2, "myapp-traefik", join(plain, "deploy")),
      ],
      runningProjects: new Set(),
      fliskRoots: [],
      tiltPids: () => [],
    });
    expect(found?.map((orphan) => orphan.pid)).toEqual([1]);
    expect(found?.[0]?.owningRoot).toBe(root);
  });

  it("claims a watcher inside a recorded root even when the .flisk marker is gone", () => {
    const root = tempDir("flisk-watchers-recorded-");
    mkdirSync(join(root, "services", "platform", "database-management"), { recursive: true });
    const found = findOrphanedComposeEventsWatchers({
      watchers: [
        watcher(
          1,
          "shop-database-management",
          join(root, "services", "platform", "database-management"),
        ),
      ],
      runningProjects: new Set(),
      fliskRoots: [root],
      projectNameOf: () => "shop",
      tiltPids: () => [],
    });
    expect(found?.map((orphan) => orphan.pid)).toEqual([1]);
    expect(found?.[0]?.owningRoot).toBe(root);
  });

  it("does not claim a hand-run session by directory alone: its project name must carry the project's", () => {
    const root = makeProject("shop");
    mkdirSync(join(root, "tools", "dev-env"), { recursive: true });
    const found = findOrphanedComposeEventsWatchers({
      watchers: [watcher(1, "dev-env", join(root, "tools", "dev-env"))],
      runningProjects: new Set(),
      fliskRoots: [root],
      tiltPids: () => [],
    });
    expect(found).toEqual([]);
  });

  it("does not call a watcher orphaned when the process table cannot say whether Tilt is up", () => {
    const root = makeProject("shop");
    mkdirSync(join(root, "services", "app", ".autogenerated"), { recursive: true });
    const found = findOrphanedComposeEventsWatchers({
      watchers: [
        watcher(1, "shop-app-autogenerated", join(root, "services", "app", ".autogenerated")),
      ],
      runningProjects: new Set(),
      fliskRoots: [],
      tiltPids: () => null,
    });
    expect(found).toEqual([]);
  });

  it("leaves a stream alone when ps clipped its directory at a space and no owner can be resolved", () => {
    // `--project-directory "/work/My Projects/shop/services/app/.autogenerated"` reads back as `/work/My`: nothing proves
    // the project's Tilt is down, so the stream is not offered for repair even with no running container yet.
    const found = findOrphanedComposeEventsWatchers({
      watchers: [watcher(1, "shop-app-autogenerated", "/work/My")],
      runningProjects: new Set(),
      fliskRoots: [],
      tiltPids: () => [],
    });
    expect(found).toEqual([]);
  });

  it("proves nothing while Docker cannot be asked, not even a deleted directory", () => {
    const root = makeProject("shop");
    mkdirSync(join(root, "x", ".autogenerated"), { recursive: true });
    // `ps` clips `--project-directory` at a space, so a live stack's stream can read as "deleted";
    // without Docker there is no running-container check to catch that.
    const found = findOrphanedComposeEventsWatchers({
      watchers: [
        watcher(1, "shop-app-autogenerated", join(root, "x", ".autogenerated")),
        watcher(2, "shop-app-autogenerated", join(tmpdir(), "flisk-watchers-really-gone")),
      ],
      runningProjects: null,
      fliskRoots: [],
      tiltPids: () => [],
    });
    expect(found).toBeNull();
  });

  it("skips a watcher with no --project-directory: nothing proves its owner or that it is orphaned", () => {
    const noDir: ComposeEventsWatcher = {
      pid: 1,
      command: "docker compose --project-name shop-app-autogenerated events --json",
      projectName: "shop-app-autogenerated",
      projectDir: undefined,
    };
    const found = findOrphanedComposeEventsWatchers({
      watchers: [noDir],
      runningProjects: new Set(),
      fliskRoots: [],
      tiltPids: () => [],
    });
    expect(found).toEqual([]);
  });

  it("passes null through when the process table cannot be read", () => {
    expect(
      findOrphanedComposeEventsWatchers({ watchers: null, runningProjects: new Set() }),
    ).toBeNull();
  });
});

describe("stillComposeEventsWatcher", () => {
  it("confirms a pid still runs a compose events stream, and rejects anything else", () => {
    const shop = "/work/shop";
    const ps = `docker compose --project-name shop-app-autogenerated --project-directory ${shop}/services/app/.autogenerated events --json\n`;
    expect(stillComposeEventsWatcher(700, "darwin", () => ps)).toBe(true);
    expect(stillComposeEventsWatcher(700, "darwin", () => "/usr/bin/vim x\n")).toBe(false);
    expect(
      stillComposeEventsWatcher(700, "darwin", () => {
        throw new Error("ESRCH");
      }),
    ).toBe(false);
    expect(stillComposeEventsWatcher(700, "win32", () => ps)).toBe(false);
  });
});

describe("watcherIdentity", () => {
  it("tells one stream from another and is stable for the same stream", () => {
    const a = watcher(1, "shop-app-autogenerated", "/x/.autogenerated");
    expect(watcherIdentity(a)).toMatch(/^[0-9a-f]{8}$/);
    expect(watcherIdentity({ ...a, pid: 99 })).toBe(watcherIdentity(a));
    expect(watcherIdentity(watcher(1, "other-app-autogenerated", "/y/.autogenerated"))).not.toBe(
      watcherIdentity(a),
    );
  });
});

describe("eventsTiltPids", () => {
  it("finds a live tilt up under the .flisk layout", () => {
    const root = makeProject("shop");
    const ps = [
      `  900 /opt/homebrew/bin/tilt up -f ${join(root, ".flisk", ".flisk-out", "Tiltfile")}`,
      "  902 /opt/homebrew/bin/tilt up -f /elsewhere/Tiltfile",
    ].join("\n");
    expect(eventsTiltPids(root, "darwin", () => ps)?.sort()).toEqual([900]);
  });

  it("is null, not empty, when the process table cannot be read", () => {
    expect(
      eventsTiltPids(makeProject("shop"), "darwin", () => {
        throw new Error("ps failed");
      }),
    ).toBeNull();
  });
});
