import { afterEach, describe, expect, it, vi } from "vitest";
import {
  checkoutDatabaseDropPlan,
  dropCheckoutDatabases,
  isSharedPostgresVolume,
  sharedPostgresContainer,
} from "../checkout-database-purge.js";
import type { DockerRun } from "../project-purge.js";

function fakeDocker(databases: string[], calls: string[][]): DockerRun {
  return (args) => {
    calls.push(args);
    if (args[0] === "ps") return "shop_postgres\n";
    if (args[2] === "psql" && args.includes("-Atc")) return `${databases.join("\n")}\n`;
    return "";
  };
}

afterEach(() => {
  vi.unstubAllEnvs();
});

describe("checkoutDatabaseDropPlan (#4698)", () => {
  const databases = [
    "postgres",
    "template0",
    "shop_api",
    "shop_orders",
    "shop_api_deadbee5",
    "shop_orders_deadbee5",
    "shop_api_cafebabe",
  ];

  it("drops only suffixed databases for a linked worktree", () => {
    expect(checkoutDatabaseDropPlan(databases, "_deadbee5")).toEqual([
      "shop_api_deadbee5",
      "shop_orders_deadbee5",
    ]);
  });

  it("drops only unsuffixed databases for the main checkout", () => {
    expect(checkoutDatabaseDropPlan(databases, "")).toEqual(["shop_api", "shop_orders"]);
  });
});

describe("dropCheckoutDatabases", () => {
  it("quotes and drops each database of the current checkout", () => {
    const calls: string[][] = [];
    const result = dropCheckoutDatabases(
      "shop",
      "_deadbee5",
      fakeDocker(["postgres", "shop_api", "shop_api_deadbee5", "shop_orders_cafebabe"], calls),
    );

    expect(result.dropped).toEqual(["shop_api_deadbee5"]);
    expect(calls).toContainEqual([
      "exec",
      "shop_postgres",
      "psql",
      "-U",
      "shop",
      "-d",
      "postgres",
      "-c",
      'DROP DATABASE IF EXISTS "shop_api_deadbee5" WITH (FORCE)',
    ]);
  });

  it("never touches a database that does not belong to this checkout", () => {
    const calls: string[][] = [];
    const result = dropCheckoutDatabases(
      "shop",
      "_deadbee5",
      fakeDocker(["postgres", "shop_api", "shop_orders_cafebabe"], calls),
    );

    expect(result.dropped).toEqual([]);
    expect(calls.filter((args) => args.includes("DROP DATABASE"))).toEqual([]);
  });

  it("is a no-op when the shared Postgres container does not exist", () => {
    const docker: DockerRun = () => "";
    const result = dropCheckoutDatabases("shop", "_deadbee5", docker);

    expect(result.skipped).toMatch(/does not exist/);
    expect(result.dropped).toEqual([]);
  });

  it("starts a stopped container, drops this checkout's databases, and stops it again", () => {
    const calls: string[][] = [];
    const docker: DockerRun = (args) => {
      calls.push(args);
      if (args[0] === "ps" && args.includes("-a")) return "shop_postgres\n";
      if (args[0] === "ps") return "";
      if (args.includes("-Atc")) return "postgres\nshop_api\nshop_api_deadbee5\n";
      return "";
    };
    const result = dropCheckoutDatabases("shop", "_deadbee5", docker);

    expect(result.dropped).toEqual(["shop_api_deadbee5"]);
    expect(calls).toContainEqual(["start", "shop_postgres"]);
    expect(calls.at(-1)).toEqual(["stop", "shop_postgres"]);
    expect(calls.filter((args) => args.includes("-c")).map((args) => args.at(-1))).toEqual([
      'DROP DATABASE IF EXISTS "shop_api_deadbee5" WITH (FORCE)',
    ]);
  });

  it("does not stop a container that was already running", () => {
    const calls: string[][] = [];
    dropCheckoutDatabases("shop", "_deadbee5", fakeDocker(["shop_api_deadbee5"], calls));
    expect(calls.some((args) => args[0] === "stop" || args[0] === "start")).toBe(false);
  });

  it("reports an actionable skip when the Docker CLI is not on PATH", () => {
    vi.stubEnv("PATH", "");
    const result = dropCheckoutDatabases("shop", "_deadbee5");

    expect(result.skipped).toMatch(/Docker CLI not found on PATH/);
    expect(result.skipped).toMatch(/flisk down --purge/);
    expect(result.dropped).toEqual([]);
  });
});

describe("shared Postgres naming", () => {
  it("finds the volume under Compose's generated name", () => {
    expect(sharedPostgresContainer("acme-shop")).toBe("acme_shop_postgres");
    expect(
      isSharedPostgresVolume("acme-shop-database-management_acme_shop_postgres_data", "acme-shop"),
    ).toBe(true);
    expect(isSharedPostgresVolume("shop_autogenerated_uploads", "shop")).toBe(false);
  });
});
