import { spawnSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { writeTextFileAtomic } from "./atomic-write.js";
import { byCodeUnit } from "./compare.js";
import { PROJECT_JSON } from "./constants.js";
import { isInsideGitWorkTree } from "./file-helpers.js";
import { findOnPath } from "./which.js";

/** The first line of the block `flisk up` writes. A .gitignore that has it is never touched again, so a team can edit it. */
export const GENERATED_ROOT_BLOCK_START =
  "# >>> Flisk generated files in the repository root (#3030)";
const BLOCK_END = "# <<< Flisk generated files";
const GENERATED_HEADER = "SYSTEM-GENERATED BY Flisk CLI";
/** The header `generateDatabaseManagementCompose` writes; it differs from GENERATED_HEADER, so the compose file needs its own check. */
const DATABASE_COMPOSE_HEADER = "SYSTEM-GENERATED - DO NOT EDIT";
const LOCKFILES = ["bun.lock", "bun.lockb", "package-lock.json", "pnpm-lock.yaml", "yarn.lock"];

/**
 * Runs one git query in the project root so every candidate path is answered by a single process (#3866).
 * Null when git could not run or never exited.
 */
function gitQuery(
  projectRoot: string,
  args: string[],
  input?: string,
): { status: number; stdout: string } | null {
  const git = findOnPath("git");
  if (git === null) return null;
  const result = spawnSync(git, args, {
    cwd: projectRoot,
    encoding: "utf-8",
    timeout: 5000,
    input,
    stdio: ["pipe", "pipe", "ignore"],
  });
  if (result.error !== undefined || result.status === null) return null;
  return { status: result.status, stdout: result.stdout };
}

/**
 * The paths among `paths` git tracks, from one `git ls-files`: a directory counts as tracked when anything
 * under it is listed. Null when git cannot answer: unknown counts as tracked, so nothing is hidden by mistake.
 */
function trackedPaths(projectRoot: string, paths: string[]): Set<string> | null {
  const result = gitQuery(projectRoot, ["ls-files", "-z", "--", ...paths]);
  if (result === null || result.status !== 0) return null;
  const listed = result.stdout.split("\0").filter((entry) => entry !== "");
  return new Set(
    paths.filter((path) => listed.some((entry) => entry === path || entry.startsWith(`${path}/`))),
  );
}

/**
 * The paths among `paths` git ignores, from one `git check-ignore --stdin` (exit 1 means none of them are
 * ignored, not an error; `-z` pairs the NUL-separated answers with the NUL-separated input). Empty when git
 * cannot answer: unknown counts as not ignored, as the per-path checks did.
 */
function ignoredPaths(projectRoot: string, paths: string[]): Set<string> {
  const result = gitQuery(projectRoot, ["check-ignore", "--stdin", "-z"], `${paths.join("\0")}\0`);
  if (result === null || result.status > 1) return new Set();
  return new Set(result.stdout.split("\0").filter((entry) => entry !== ""));
}

function discoveryPathsOf(projectRoot: string): string[] | null {
  try {
    const config = JSON.parse(readFileSync(resolve(projectRoot, ".flisk", PROJECT_JSON), "utf-8"));
    const paths = config?.discovery?.paths;
    return Array.isArray(paths) ? paths : null;
  } catch {
    return null;
  }
}

/** The root package.json Flisk generates (`ensureRootWorkspaceManifest`): exactly its keys, workspaces = discovery paths. */
function isGeneratedWorkspaceManifest(projectRoot: string): boolean {
  const file = resolve(projectRoot, "package.json");
  if (!existsSync(file)) return false;
  try {
    const manifest = JSON.parse(readFileSync(file, "utf-8"));
    const keys = Object.keys(manifest).sort(byCodeUnit).join(",");
    const paths = discoveryPathsOf(projectRoot);
    return (
      keys === "name,private,type,version,workspaces" &&
      manifest.private === true &&
      manifest.type === "module" &&
      paths !== null &&
      JSON.stringify(manifest.workspaces) === JSON.stringify(paths)
    );
  } catch {
    return false;
  }
}

function fileHasGeneratedHeader(file: string, headers: string[] = [GENERATED_HEADER]): boolean {
  try {
    const text = readFileSync(file, "utf-8");
    return headers.some((header) => text.includes(header));
  } catch {
    return false;
  }
}

/**
 * Adds the files Flisk generates in the repository root to the project's .gitignore, in one marked block, once (#3030):
 * the workspace `package.json` and the lockfiles beside it, `.tiltignore`, `shared-platform-engineering/` and the generated
 * `services/platform/database-management/docker-compose.yml`. Only inside a git work tree, and never for a path git already
 * tracks (a team's own `package.json` or `.tiltignore` stays as it is). An existing block is left alone, so deleting a
 * line is how a team keeps committing that file. Returns the entries it wrote.
 */
export function ensureGeneratedRootIgnored(projectRoot: string): string[] {
  if (!isInsideGitWorkTree(projectRoot)) return [];
  const gitignorePath = resolve(projectRoot, ".gitignore");
  const existing = existsSync(gitignorePath) ? readFileSync(gitignorePath, "utf-8") : "";
  if (existing.includes(GENERATED_ROOT_BLOCK_START)) return [];

  const candidates: string[] = [];
  if (isGeneratedWorkspaceManifest(projectRoot)) {
    candidates.push("package.json", ...LOCKFILES);
  }
  if (fileHasGeneratedHeader(resolve(projectRoot, ".tiltignore"))) candidates.push(".tiltignore");
  if (existsSync(resolve(projectRoot, "shared-platform-engineering"))) {
    candidates.push("shared-platform-engineering/");
  }
  const databaseCompose = "services/platform/database-management/docker-compose.yml";
  if (
    fileHasGeneratedHeader(resolve(projectRoot, databaseCompose), [
      GENERATED_HEADER,
      DATABASE_COMPOSE_HEADER,
    ])
  ) {
    candidates.push(databaseCompose);
  }

  if (candidates.length === 0) return [];

  // Two git processes answer for every candidate at once (#3866): one ls-files for the tracked
  // paths, one check-ignore for the already-ignored ones. When ls-files cannot answer, every path
  // counts as tracked and nothing is hidden by mistake.
  const stripped = candidates.map((path) => path.replace(/\/$/, ""));
  const tracked = trackedPaths(projectRoot, stripped);
  if (tracked === null) return [];
  const ignored = ignoredPaths(projectRoot, stripped);
  const entries = candidates
    .filter((_, index) => !tracked.has(stripped[index]) && !ignored.has(stripped[index]))
    .map((path) => `/${path}`);
  if (entries.length === 0) return [];

  // Re-read immediately before writing so a concurrent caller that wrote the block while
  // git ls-files / check-ignore ran does not duplicate it.
  const latest = existsSync(gitignorePath) ? readFileSync(gitignorePath, "utf-8") : "";
  if (latest.includes(GENERATED_ROOT_BLOCK_START)) return [];

  const prefix = latest === "" ? "" : latest.endsWith("\n") ? "\n" : "\n\n";
  const lines = [
    GENERATED_ROOT_BLOCK_START,
    "# Written by flisk once. Delete a line to commit that file; flisk will not add it again.",
    ...entries,
    BLOCK_END,
  ];
  writeTextFileAtomic(gitignorePath, `${latest}${prefix}${lines.join("\n")}\n`);
  return entries.map((entry) => entry.slice(1));
}
