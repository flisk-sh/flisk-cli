import { rmSync } from "node:fs";
import { join, normalize } from "node:path";
import { describe, expect, it, vi } from "vitest";
import { checkFrontendDockerPreflight } from "../docker-preflight.js";
import { type DoctorTestProject, useTempProject } from "./fixtures.js";

describe("checkFrontendDockerPreflight", () => {
  const tempProject = useTempProject();
  let project: DoctorTestProject;

  function writeFrontendProject(options: {
    composePort: number;
    dockerTsconfig: Record<string, unknown>;
    mainTsx: string;
  }) {
    project.writeService(
      "app/dashboard-app",
      {
        appType: "frontend",
        stack: "app",
        port: 3200,
        basePath: "/dashboard-app",
      },
      {
        ".autogenerated/Dockerfile.app.autogenerated":
          "FROM nginx:alpine\nCOPY dist /usr/share/nginx/html\nEXPOSE 80\n",
        ".autogenerated/tsconfig.docker.autogenerated.json": JSON.stringify(
          options.dockerTsconfig,
          null,
          2,
        ),
        "src/main.tsx": options.mainTsx,
      },
    );
    project.mkdir("services/app/dashboard-app/public");
    project.writeFile(
      "services/app/.autogenerated/docker-compose.app.autogenerated.yml",
      [
        "services:",
        "  dashboard-app:",
        "    labels:",
        `      - "traefik.http.services.dashboard-app.loadbalancer.server.port=${options.composePort}"`,
      ].join("\n"),
    );
  }

  it("fails when generated Traefik routes an nginx frontend to the Vite dev port", () => {
    project = tempProject();
    writeFrontendProject({
      composePort: 3200,
      dockerTsconfig: { compilerOptions: { allowSyntheticDefaultImports: true } },
      mainTsx: 'import { StrictMode } from "react";\n',
    });

    const result = checkFrontendDockerPreflight();

    expect(result.didPass).toBe(false);
    expect(result.message).toContain("nginx runtime exposes 80");
    expect(result.message).toContain("routes to 3200");
  });

  it("fails when Docker tsconfig rejects default React imports used by the entrypoint", () => {
    project = tempProject();
    writeFrontendProject({
      composePort: 80,
      dockerTsconfig: { compilerOptions: { strict: true } },
      mainTsx: ['import React from "react";', 'import ReactDOM from "react-dom/client";', ""].join(
        "\n",
      ),
    });

    const result = checkFrontendDockerPreflight();

    expect(result.didPass).toBe(false);
    expect(result.message).toContain("does not allow synthetic default imports");
    expect(result.message).toContain("react-dom/client");
  });

  function writeFrontendWithoutPublic(platform: "linux" | "win32") {
    project = tempProject();
    writeFrontendProject({
      composePort: 80,
      dockerTsconfig: { compilerOptions: { strict: true } },
      mainTsx: "",
    });
    rmSync(join(project.root, "services", "app", "dashboard-app", "public"), { recursive: true });
    return vi.spyOn(process, "platform", "get").mockReturnValue(platform);
  }

  it("fails when a frontend has no public/ folder for the Docker build to copy", () => {
    const platform = writeFrontendWithoutPublic("linux");

    try {
      const result = checkFrontendDockerPreflight();

      expect(result.didPass).toBe(false);
      expect(result.message).toContain("dashboard-app: no public/ folder");
      expect(result.message).toContain(
        `mkdir -p ${normalize("services/app/dashboard-app/public")}`,
      );
    } finally {
      platform.mockRestore();
    }
  });

  it("prints PowerShell creation steps on Windows when a frontend has no public/ folder", () => {
    const platform = writeFrontendWithoutPublic("win32");

    try {
      const result = checkFrontendDockerPreflight();

      expect(result.didPass).toBe(false);
      expect(result.message).toContain("dashboard-app: no public/ folder");
      expect(result.message).toContain("Create it: New-Item -ItemType Directory -Force");
      expect(result.message).toContain("New-Item -ItemType File -Force");
      expect(result.message).toContain(".gitkeep'");
      expect(result.message).not.toContain("mkdir -p");
      expect(result.message).not.toContain(" && touch ");
    } finally {
      platform.mockRestore();
    }
  });

  it("passes when generated frontend Docker metadata is internally consistent", () => {
    project = tempProject();
    writeFrontendProject({
      composePort: 80,
      dockerTsconfig: { compilerOptions: { strict: true } },
      mainTsx: [
        'import { StrictMode } from "react";',
        'import { createRoot } from "react-dom/client";',
        "",
      ].join("\n"),
    });

    const result = checkFrontendDockerPreflight();

    expect(result.didPass).toBe(true);
  });

  it("skips when the project has no frontend services", () => {
    project = tempProject();
    project.writeService("app/api", { appType: "backend", stack: "app" });

    const result = checkFrontendDockerPreflight();

    expect(result.didPass).toBe(true);
    expect(result.isSkipped).toBe(true);
    expect(result.message).toBe("No frontend services to check");
  });

  it("skips the public/ check for a frontend that declares its own top-level dockerfile", () => {
    project = tempProject();
    // The service owns its image: no .autogenerated Dockerfile is generated, so nothing copies public/.
    project.writeService(
      "app/dashboard-app",
      { appType: "frontend", stack: "app", port: 3200, dockerfile: "Dockerfile" },
      { Dockerfile: "FROM nginx:alpine\nCOPY dist /usr/share/nginx/html\n" },
    );

    const result = checkFrontendDockerPreflight();

    expect(result.didPass).toBe(true);
    expect(result.message ?? "").not.toContain("no public/ folder");
  });

  it("skips the public/ check for a frontend that declares build.dockerfile, the nested spelling", () => {
    project = tempProject();
    project.writeService(
      "app/dashboard-app",
      {
        appType: "frontend",
        stack: "app",
        port: 3200,
        build: { dockerfile: "Dockerfile", context: "." },
      },
      { Dockerfile: "FROM nginx:alpine\nCOPY dist /usr/share/nginx/html\n" },
    );

    const result = checkFrontendDockerPreflight();

    expect(result.didPass).toBe(true);
    expect(result.message ?? "").not.toContain("no public/ folder");
  });

  it("skips only the own-Dockerfile frontends and still checks the generated ones", () => {
    project = tempProject();
    project.writeService(
      "app/landing",
      { appType: "frontend", stack: "app", port: 3100, dockerfile: "Dockerfile" },
      { Dockerfile: "FROM nginx:alpine\nCOPY dist /usr/share/nginx/html\n" },
    );
    writeFrontendProject({
      composePort: 80,
      dockerTsconfig: { compilerOptions: { strict: true } },
      mainTsx: "",
    });
    rmSync(join(project.root, "services", "app", "dashboard-app", "public"), { recursive: true });

    const result = checkFrontendDockerPreflight();

    expect(result.didPass).toBe(false);
    expect(result.message).toContain("dashboard-app: no public/ folder");
  });
});
