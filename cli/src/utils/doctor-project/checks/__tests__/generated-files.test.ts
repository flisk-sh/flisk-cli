import { chmodSync, existsSync, mkdirSync, readFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { checkGeneratedFiles, checkGeneratedProjectRuntimeAssets } from "../generated-files.js";
import { type DoctorTestProject, useTempProject } from "./fixtures.js";

describe("checkGeneratedFiles", () => {
  const tempProject = useTempProject();
  let project: DoctorTestProject;

  function writeService(name: string, appType: string, generated: string[]) {
    project.writeService(
      `shop/${name}`,
      { appType, stack: "shop", port: 4000 },
      Object.fromEntries(generated.map((file) => [`.autogenerated/${file}`, ""])),
    );
  }

  it("lists the generated files of every resource", () => {
    project = tempProject();
    writeService("orders-api", "backend", ["Dockerfile.app", "env.ts"]);

    const result = checkGeneratedFiles();

    expect(result.didPass).toBe(true);
    expect(result.message).toContain("services/shop/orders-api: Dockerfile.app, env.ts");
  });

  it("warns, without failing, for a resource that has not been generated yet", () => {
    project = tempProject();
    writeService("orders-api", "backend", []);

    const result = checkGeneratedFiles();

    expect(result.didPass).toBe(false);
    expect(result.isWarning).toBe(true);
    expect(result.message).toContain("services/shop/orders-api: no .autogenerated/ files");
    expect(result.fix).toContain("flisk up");
  });

  it("fails instead of warning in strict mode", () => {
    project = tempProject();
    writeService("orders-api", "backend", []);

    const result = checkGeneratedFiles(true);

    expect(result.didPass).toBe(false);
    expect(result.isWarning).toBe(false);
  });

  it("counts nested files and ignores the .flisk-contract directory", () => {
    project = tempProject();
    writeService("orders-api", "backend", []);
    const generated = "services/shop/orders-api/.autogenerated";
    project.mkdir(`${generated}/.flisk-contract`);
    project.writeFile(`${generated}/.flisk-contract/manifest.json`, "");

    expect(checkGeneratedFiles().didPass).toBe(false);

    project.writeFile(`${generated}/nested/env.ts`, "");
    const result = checkGeneratedFiles();

    expect(result.didPass).toBe(true);
    expect(result.message).toContain("nested/env.ts");
    expect(result.message).not.toContain("manifest.json");
  });

  it("ignores library resources", () => {
    project = tempProject();
    writeService("shared-sdk", "library", []);

    expect(checkGeneratedFiles().isSkipped).toBe(true);
  });
});

describe("checkGeneratedProjectRuntimeAssets", () => {
  const tempProject = useTempProject();
  let project: DoctorTestProject;

  function writeRequiredRuntimeAssets() {
    for (const file of [
      "install-deps.sh",
      "bun-hoisted-symlink-fix.sh",
      "prisma-bun-client-link-fix.sh",
      "prisma-normalize-client.sh",
      "infisical-entrypoint.sh",
    ]) {
      project.writeFile(`shared-platform-engineering/docker-templates/${file}`, "#!/bin/sh\n");
    }
  }

  function writeWorkspaceManifest() {
    project.writeFile(
      "package.json",
      JSON.stringify({ name: "asset-check", private: true, workspaces: ["services/*/*"] }),
    );
  }

  function writeDockerfileService(dockerfile: string | string[]) {
    project.writeService(
      "shop/orders-api",
      { appType: "backend", stack: "shop", port: 4000 },
      {
        ".autogenerated/Dockerfile.app.autogenerated": Array.isArray(dockerfile)
          ? dockerfile.join("\n")
          : dockerfile,
      },
    );
  }

  function setupDockerfileProject() {
    project = tempProject();
    writeWorkspaceManifest();
  }

  it("fails when the root workspace package.json is missing", () => {
    project = tempProject();

    const result = checkGeneratedProjectRuntimeAssets();

    expect(result.didPass).toBe(false);
    expect(result.message).toContain("package.json");
    // No generated Dockerfile references the templates, so they are not required (#4583).
    expect(result.message).not.toContain("install-deps.sh");
    expect(result.fix).toContain("flisk project");
  });

  it("passes on a fresh starter with no generated Dockerfiles and no docker-templates directory (#4583)", () => {
    project = tempProject();
    project.writeFile(
      "package.json",
      JSON.stringify({ name: "portal-starter", private: true, workspaces: ["services/*/*"] }),
    );
    project.writeService("main/api", { appType: "backend", stack: "main", port: 4000 });
    // The starter's own production Dockerfile never copies shared-platform-engineering.
    project.writeFile(
      "services/main/api/Dockerfile",
      "FROM node:20\nCOPY package.json ./\nCOPY src ./src\nCOPY public ./public\n",
    );

    const result = checkGeneratedProjectRuntimeAssets();

    expect(result.didPass).toBe(true);
    expect(result.message).toContain("runtime assets are present");
  });

  it("passes when generated Docker runtime assets are present", () => {
    setupDockerfileProject();
    writeRequiredRuntimeAssets();

    const result = checkGeneratedProjectRuntimeAssets();

    expect(result.didPass).toBe(true);
    expect(result.message).toContain("runtime assets are present");
  });

  it("fails when a copied Docker script has a CR in its first line", () => {
    setupDockerfileProject();
    writeRequiredRuntimeAssets();
    writeDockerfileService(
      "COPY shared-platform-engineering/docker-templates/install-deps.sh /usr/local/bin/install-deps.sh\n",
    );
    project.writeFile(
      "shared-platform-engineering/docker-templates/install-deps.sh",
      "#!/bin/sh\r\necho install-deps.sh\n",
    );

    const result = checkGeneratedProjectRuntimeAssets();

    expect(result.didPass).toBe(false);
    expect(result.message).toContain("install-deps.sh");
    expect(result.message).toContain("CRLF");
    expect(result.fix).toContain("flisk config regenerate");
  });

  it("flags a script a generated Dockerfile copies but the project lacks", () => {
    setupDockerfileProject();
    writeRequiredRuntimeAssets();
    writeDockerfileService(
      "COPY shared-platform-engineering/docker-templates/migrate.sh /usr/local/bin/migrate.sh\n",
    );

    const result = checkGeneratedProjectRuntimeAssets();

    expect(result.didPass).toBe(false);
    expect(result.message).toContain("migrate.sh");
  });

  it("ignores template paths in Dockerfile comments, RUN commands, and COPY --from stages", () => {
    setupDockerfileProject();
    writeDockerfileService([
      "FROM node:20",
      "# Previously used: shared-platform-engineering/docker-templates/legacy.sh",
      'RUN echo "shared-platform-engineering/docker-templates/debug.sh"',
      "COPY --from=builder shared-platform-engineering/docker-templates/from-stage.sh /usr/local/bin/from-stage.sh",
      "COPY package.json /app/shared-platform-engineering/docker-templates/dest-only.sh",
      "",
    ]);

    const result = checkGeneratedProjectRuntimeAssets();

    expect(result.didPass).toBe(true);
    expect(result.message).toContain("runtime assets are present");
  });

  it("detects missing template files in COPY with flags, line continuations, and JSON form", () => {
    setupDockerfileProject();
    writeDockerfileService([
      "FROM node:20",
      "COPY --chmod=0755 --chown=1000:1000 \\",
      "  shared-platform-engineering/docker-templates/flagged.sh \\",
      "  /usr/local/bin/flagged.sh",
      'COPY --chmod=0755 ["shared-platform-engineering/docker-templates/json-form.sh", "/usr/local/bin/json-form.sh"]',
      "",
    ]);

    const result = checkGeneratedProjectRuntimeAssets();

    expect(result.didPass).toBe(false);
    expect(result.message).toContain("flagged.sh");
    expect(result.message).toContain("json-form.sh");
  });

  it("ignores an escape directive that follows an ordinary comment or blank line", () => {
    setupDockerfileProject();
    // Docker stops looking for parser directives after an ordinary comment or blank line, so the `# escape=`` directive
    // below is inert and backslash still continues lines: the COPY source must be read as one instruction.
    writeDockerfileService([
      "# An ordinary comment",
      "# escape=`",
      "FROM node:20",
      "COPY shared-platform-engineering/docker-templates/inert-escape.sh \\",
      "  /usr/local/bin/inert-escape.sh",
      "",
    ]);

    const result = checkGeneratedProjectRuntimeAssets();

    expect(result.didPass).toBe(false);
    expect(result.message).toContain("inert-escape.sh");
  });

  it("rejoins a source path split by a backslash continuation without inserting whitespace", () => {
    setupDockerfileProject();
    writeDockerfileService([
      "FROM node:20",
      "COPY shared-platform-engineering/docker-tem\\",
      "plates/split-path.sh /usr/local/bin/split-path.sh",
      "",
    ]);

    const result = checkGeneratedProjectRuntimeAssets();

    expect(result.didPass).toBe(false);
    expect(result.message).toContain("split-path.sh");
  });

  it("ignores COPY-like text inside a heredoc body and still checks the COPY after it", () => {
    setupDockerfileProject();
    writeDockerfileService([
      "FROM node:20",
      "COPY <<EOF /tmp/example",
      "COPY shared-platform-engineering/docker-templates/inside-heredoc.sh /tmp/",
      "EOF",
      "COPY shared-platform-engineering/docker-templates/after-heredoc.sh /tmp/",
      "",
    ]);

    const result = checkGeneratedProjectRuntimeAssets();

    expect(result.didPass).toBe(false);
    expect(result.message).toContain("after-heredoc.sh");
    expect(result.message).not.toContain("inside-heredoc.sh");
  });

  it("checks the templates the golden layers Dockerfile copies", () => {
    setupDockerfileProject();
    project.writeFile(
      ".flisk/.flisk-out/golden-layers.Dockerfile",
      "FROM oven/bun\nCOPY shared-platform-engineering/docker-templates/golden-only.sh /usr/local/bin/golden-only.sh\n",
    );

    const result = checkGeneratedProjectRuntimeAssets();

    expect(result.didPass).toBe(false);
    expect(result.message).toContain("golden-only.sh");
  });

  it("normalizes a leading slash on COPY sources", () => {
    setupDockerfileProject();
    // Docker resolves an absolute source against the build context root, so the leading slash must not hide the
    // referenced template file.
    writeDockerfileService([
      "FROM node:20",
      "COPY /shared-platform-engineering/docker-templates/absolute.sh /usr/local/bin/absolute.sh",
      "",
    ]);

    const result = checkGeneratedProjectRuntimeAssets();

    expect(result.didPass).toBe(false);
    expect(result.message).toContain("absolute.sh");
  });

  it("fails instead of silently passing when a generated Dockerfile cannot be read", () => {
    setupDockerfileProject();
    writeDockerfileService(
      "COPY shared-platform-engineering/docker-templates/migrate.sh /usr/local/bin/migrate.sh\n",
    );
    const dockerfilePath = join(
      project.root,
      "services",
      "shop",
      "orders-api",
      ".autogenerated",
      "Dockerfile.app.autogenerated",
    );

    chmodSync(dockerfilePath, 0o000);
    let readable = false;
    try {
      readFileSync(dockerfilePath, "utf-8");
      readable = true;
    } catch {
      readable = false;
    }

    try {
      if (readable) {
        // Fallback when running as root or on a filesystem ignoring chmod 0o000:
        // a directory at a Dockerfile path guarantees readFileSync fails with EISDIR.
        rmSync(dockerfilePath, { force: true });
        mkdirSync(dockerfilePath);
      }

      const result = checkGeneratedProjectRuntimeAssets();

      expect(result.didPass).toBe(false);
      expect(result.message).toContain("Failed to inspect generated Dockerfiles");
      expect(result.message).toContain("Dockerfile.app.autogenerated");
    } finally {
      if (!readable && existsSync(dockerfilePath)) {
        chmodSync(dockerfilePath, 0o644);
      }
    }
  });
});
