import type { ResourceType } from "./app-types.js";
import type { AutogeneratedFile } from "./files.js";
import type { TiltRuntimeStatus } from "./tilt.js";

export type ResourceStatus = "ready" | "pending" | "error" | "unhealthy" | "stopped" | "unknown";

export interface ResourceMetadata {
  name: string;
  stack?: string;
  type: ResourceType;
  port?: number;
  createdAt: string;
  lastModified: string;
  dependencies: string[];
  hasDockerfile: boolean;
  hasTiltfile: boolean;
  hasDockerCompose: boolean;
  autogeneratedFiles: AutogeneratedFile[];
  status: ResourceStatus;
  /** Why the service is not ready, from the running Tilt (for example "db failed"). */
  statusReason?: string;
}

export type StackHealthStatus = "healthy" | "degraded" | "error" | "unknown";

export interface StackMetadata {
  name: string;
  resourceCount: number;
  createdAt: string;
  lastModified: string;
  resources: ResourceMetadata[];
  overallStatus: StackHealthStatus;
}

export interface ServiceUrl {
  name: string;
  stack?: string;
  /** Resource folder relative to the project root (POSIX-style separators). */
  path?: string;
  basePath: string;
  url: string;
  loopbackUrl?: string;
  port?: number;
  status: "running" | "stopped" | "unknown";
}

export type StatusValue =
  | ResourceStatus
  | StackHealthStatus
  | TiltRuntimeStatus
  | ServiceUrl["status"]
  | "active"
  | "failed"
  | "critical"
  | "stopped"
  | "starting"
  | "building"
  | undefined;

export type StatusCategory = "success" | "error" | "warning" | "unknown";

export interface ServiceRuntimeState {
  status: ResourceStatus;
  /** Why the service is not ready: its own error, or the dependency that failed or is still starting. */
  reason?: string;
  /** Failed services this one depends on, directly or through others. */
  blockedBy?: string[];
  /** The exit code of the process that ran most recently, when one is on record. */
  exitCode?: number | null;
}
