import { describe, expect, it } from "vitest";
import type {
  ResourceMetadata,
  ResourceStatus,
  ServiceRuntimeState,
  ServiceUrl,
  StackHealthStatus,
  StackMetadata,
  StatusCategory,
  StatusValue,
} from "../status.js";

describe("status vocabulary", () => {
  it("types resource and stack metadata with their health fields", () => {
    const status: ResourceStatus = "error";
    const resource: ResourceMetadata = {
      name: "api",
      stack: "core",
      type: "backend",
      port: 4100,
      createdAt: "2026-01-01T00:00:00Z",
      lastModified: "2026-01-02T00:00:00Z",
      dependencies: ["db"],
      hasDockerfile: true,
      hasTiltfile: false,
      hasDockerCompose: true,
      autogeneratedFiles: [],
      status,
      statusReason: "db failed",
    };
    const stack: StackMetadata = {
      name: "core",
      resourceCount: 1,
      createdAt: resource.createdAt,
      lastModified: resource.lastModified,
      resources: [resource],
      overallStatus: "degraded" satisfies StackHealthStatus,
    };
    expect(stack.resources[0]?.statusReason).toBe("db failed");
    expect(stack.overallStatus).toBe("degraded");
  });

  it("types a printed service URL", () => {
    const url: ServiceUrl = {
      name: "api",
      stack: "core",
      path: "services/core/api",
      basePath: "/api/api",
      url: "http://api.demo.localhost/api/api",
      loopbackUrl: "http://127.0.0.1:4100",
      port: 4100,
      status: "running",
    };
    expect(url.status).toBe("running");
    expect(url.loopbackUrl).toContain("4100");
  });

  it("widens StatusValue over every status spelling the UI maps", () => {
    const values: StatusValue[] = [
      "ready",
      "pending",
      "error",
      "unknown",
      "healthy",
      "degraded",
      "running",
      "stopped",
      "active",
      "failed",
      "critical",
      "starting",
      "building",
      undefined,
    ];
    const categories: StatusCategory[] = ["success", "error", "warning", "unknown"];
    expect(values).toHaveLength(14);
    expect(categories).toHaveLength(4);
  });

  it("carries why a service is not ready and what blocks it", () => {
    const state: ServiceRuntimeState = {
      status: "pending",
      reason: "db failed",
      blockedBy: ["db"],
    };
    expect(state.blockedBy).toEqual(["db"]);
  });
});
