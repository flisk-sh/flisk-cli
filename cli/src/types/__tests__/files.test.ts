import { describe, expect, it } from "vitest";
import type {
  AutogeneratedFile,
  FileGenerationTask,
  FileNode,
  FileType,
  ResourceFileType,
} from "../files.js";

describe("file inventory and generation types", () => {
  it("classifies an autogenerated file by FileType", () => {
    const type: FileType = "docker";
    const file: AutogeneratedFile = {
      name: "Dockerfile",
      path: "/svc/Dockerfile",
      type,
      size: 128,
      lastModified: "2026-01-01T00:00:00Z",
    };
    expect(file.type).toBe("docker");
  });

  it("builds a generation task with JSON or text content", () => {
    const json: FileGenerationTask = {
      type: "json" satisfies ResourceFileType,
      filename: "tsconfig.json",
      content: { compilerOptions: { strict: true } },
      description: "TS config",
      emoji: "🔧",
    };
    const text: FileGenerationTask = {
      type: "text",
      filename: "Dockerfile",
      content: "FROM oven/bun",
      description: "Image recipe",
      emoji: "🐳",
    };
    expect(json.content).toEqual({ compilerOptions: { strict: true } });
    expect(text.content).toBe("FROM oven/bun");
  });

  it("nests file nodes for the file tree", () => {
    const leaf: FileNode = {
      name: "service.json",
      path: "/svc/service.json",
      type: "file",
      fileType: "config",
    };
    const tree: FileNode = {
      name: "svc",
      path: "/svc",
      type: "directory",
      children: [leaf],
    };
    expect(tree.children?.[0]?.fileType).toBe("config");
  });
});
