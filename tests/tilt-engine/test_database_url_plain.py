"""
The generated DATABASE_URL is a plain PostgreSQL URL with no query parameters (#3659).

It used to end in `?schema=public`, a Prisma-only parameter that Bun's SQL client, libpq and
other drivers forward to Postgres as a startup parameter: every query then failed with
`unrecognized configuration parameter "schema"`. Prisma selects the `public` schema when the
parameter is absent, so dropping it loses nothing.

Every surface that hands a service a database URL is covered: the backend Compose
`environment:` lines (`DATABASE_URL` and `TILT_DATABASE_URL`), the migrator's fallback
`DATABASE_URL`, the generated `.env.backend.autogenerated` for the `prisma` and `drizzle`
features, and the SDK helpers (`Database.get_url`, `manifest.get_database_url`,
`PlatformDockerConstants`).

Runs the real generators through Tilt's interpreter (`tilt alpha tiltfile-result`), via the shared
run_project_tilt helper in tilt_project.py. The asserts are on what a service receives, not on the
Starlark text.
"""

from __future__ import annotations

import shutil

import pytest

from tilt_project import run_project_tilt

pytestmark = [pytest.mark.generator]
TILT_REQUIRED = pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")

COMPOSE_BODY = """
load('@ENGINE/topologies/platform/docker/compose/compose.star', 'generate_backend_compose_entry')
load('@ENGINE/topologies/tilt/resources/orchestrator/generators/env.star', 'EnvGenerators')
load('@ENGINE/topologies/tilt/resources/databases.star', 'Database')
load('@ENGINE/topologies/platform/docker/constants.star', 'PlatformDockerConstants')
load('@DISCOVERY/manifest/normalize.star', 'get_database_url')

api_manifest = {'appType': 'backend', 'stack': 'shop', 'port': 4000, 'healthCheckPath': '/health', 'dependsOn': ['postgres']}
prisma_manifest = {'appType': 'backend', 'stack': 'shop', 'port': 4001, 'featuresEnabled': ['prisma'], 'dependsOn': ['postgres']}
drizzle_manifest = {'appType': 'backend', 'stack': 'shop', 'port': 4002, 'featuresEnabled': ['drizzle'], 'dependsOn': ['postgres']}
migrator_manifest = {'appType': 'migrator', 'stack': 'shop', 'featuresEnabled': ['prisma'], 'dependsOn': ['postgres']}

r = {
    'api': generate_backend_compose_entry('services/shop', 'shop', {'name': 'api'}, api_manifest),
    'migrator': generate_backend_compose_entry('services/shop', 'shop', {'name': 'migrations'}, migrator_manifest),
    'env_prisma': EnvGenerators.generate_params_env(prisma_manifest),
    'env_drizzle': EnvGenerators.generate_params_env(drizzle_manifest),
    'db_url': Database.get_url('api'),
    'tilt_url': get_database_url({'stack': 'shop'}),
    'env_url': PlatformDockerConstants.get_database_url_for_env('url_project_shop'),
    'shell_url': PlatformDockerConstants.get_database_url_for_shell('url_project_shop'),
}
"""


@pytest.fixture(scope="module")
def result(tmp_path_factory) -> dict:
    if shutil.which("tilt") is None:
        pytest.skip("tilt CLI not installed")
    return run_project_tilt(tmp_path_factory.mktemp("database-url"), "url-project", COMPOSE_BODY)


def _database_url_lines(text: str) -> list[str]:
    return [line for line in text.splitlines() if "DATABASE_URL" in line]


def _assert_plain_urls(text: str) -> None:
    """Every line that mentions DATABASE_URL carries a URL with no query string."""
    lines = _database_url_lines(text)
    assert lines, "expected at least one DATABASE_URL line"
    for line in lines:
        assert "?" not in line, line
        assert "schema=" not in line, line


@TILT_REQUIRED
def test_backend_compose_database_url_has_no_query_parameters(result):
    entry = result["api"]

    _assert_plain_urls(entry)
    assert "      - DATABASE_URL=postgresql://url_project:${DB_PASSWORD}@url_project_postgres:5432/url_project_shop\n" in entry
    assert "      - TILT_DATABASE_URL=postgresql://url_project:${DB_PASSWORD}@url_project_postgres:5432/url_project_shop\n" in entry


@TILT_REQUIRED
def test_migrator_compose_database_url_has_no_query_parameters(result):
    entry = result["migrator"]

    _assert_plain_urls(entry)
    assert "/url_project_shop" in entry


@TILT_REQUIRED
def test_prisma_env_file_database_url_has_no_query_parameters(result):
    content = result["env_prisma"]

    _assert_plain_urls(content)
    assert "DATABASE_URL=postgresql://url_project:${DB_PASSWORD}@url_project_postgres:5432/url_project_shop\n" in content


@TILT_REQUIRED
def test_drizzle_env_file_database_url_has_no_query_parameters(result):
    content = result["env_drizzle"]

    _assert_plain_urls(content)
    assert "DATABASE_URL=postgresql://url_project:${DB_PASSWORD}@url_project_postgres:5432/url_project_shop\n" in content


@TILT_REQUIRED
def test_sdk_database_url_helpers_have_no_query_parameters(result):
    expected = {
        "db_url": "/url_project_api",
        "tilt_url": "/url_project_shop",
        "env_url": "/url_project_shop",
        "shell_url": "/url_project_shop",
    }
    for key, suffix in expected.items():
        url = result[key]
        assert url.startswith("postgresql://"), (key, url)
        assert "?" not in url, (key, url)
        assert url.endswith(suffix), (key, url)
