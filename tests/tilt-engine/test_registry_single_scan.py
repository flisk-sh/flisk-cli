"""registry.star runs the multi-root discovery scan once per Tiltfile load.

The registry used to call initialize_discovery twice: the second call re-ran the whole
multi-root scan only to print "  1.2 Preparing Tilt resources...". These tests pin the
single-scan behavior and the shape _run_discovery exports.
"""

import json
import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
REGISTRY = REPO_ROOT / "runtime" / "discovery" / "registry.star"
ORCHESTRATOR = REPO_ROOT / "runtime" / "discovery" / "discovery_orchestrator.star"
RESULT_MARKER = "Error in fail: RESULT"

needs_tilt = pytest.mark.skipif(
    shutil.which("tilt") is None, reason="tilt CLI not installed"
)


def test_run_discovery_calls_initialize_discovery_once():
    body = re.search(
        r"def _run_discovery\(\):\n(.*?)\n +return working_cache",
        REGISTRY.read_text(),
        re.DOTALL,
    )
    assert body, "_run_discovery not found in registry.star"
    assert body.group(1).count("initialize_discovery(") == 1


def test_second_pass_is_gone_and_both_log_lines_remain():
    orchestrator = ORCHESTRATOR.read_text()
    assert "second_pass" not in orchestrator
    assert "  1.1 Scanning service manifests" in orchestrator
    registry = REGISTRY.read_text()
    assert "second_pass" not in registry
    assert "  1.2 Preparing Tilt resources" in registry


def _write_project(project: Path) -> Path:
    (project / ".flisk").mkdir(parents=True)
    (project / ".flisk" / "project.json").write_text(
        json.dumps({"project": {"name": "proj"}})
    )
    manifest_dir = project / "services" / "product" / "order" / "order-api"
    manifest_dir.mkdir(parents=True)
    (manifest_dir / "service.json").write_text(
        json.dumps(
            {
                "appName": "order-api",
                "appType": "backend",
                "stack": "order",
                "port": 4100,
                "homepage": "https://a.example/order",
            }
        )
    )
    return manifest_dir


def _run_registry(project: Path, portable: bool):
    exported = (
        "'APP_RESOURCES', 'RESOURCE_DEPENDENCIES', 'RESOURCE_ALIASES', "
        + "'RESOURCE_PATH_MAP', 'Registry'"
    )
    result = (
        "{'app_resources': APP_RESOURCES, 'deps': RESOURCE_DEPENDENCIES, "
        + "'aliases': RESOURCE_ALIASES, 'paths': RESOURCE_PATH_MAP, 'stats': Registry.stats()}"
    )
    (project / "Tiltfile").write_text(
        "load('"
        + str(REGISTRY)
        + "', "
        + exported
        + ")\n"
        + "fail('RESULT' + encode_json("
        + result
        + "))\n"
    )
    env = {**os.environ, "FLISK_PROJECT_ROOT": str(project)}
    if portable:
        env["FLISK_DISCOVERY_PORTABLE"] = "1"
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(project / "Tiltfile")],
        capture_output=True,
        text=True,
        timeout=180,
        cwd=project,
        env=env,
    )
    out = proc.stdout + proc.stderr
    assert RESULT_MARKER in out, out[-3000:]
    result = json.loads(out.split(RESULT_MARKER, 1)[1].strip())
    return out, result


def _assert_single_scan_output(out, result):
    # Both phase lines print exactly once each.
    assert out.count("1.1 Scanning service manifests") == 1
    assert out.count("1.2 Preparing Tilt resources") == 1
    # One scan, not two: the per-scan summary line prints once per
    # initialize_discovery call, so it is the real scan-count discriminator.
    assert out.count("resources loaded") == 1
    assert isinstance(result["app_resources"], list)
    assert isinstance(result["deps"], dict)
    assert isinstance(result["aliases"], dict)
    assert isinstance(result["paths"], dict)
    assert result["stats"]["app_resources_count"] == len(result["app_resources"])
    service = next(
        (s for s in result["app_resources"] if s.get("name") == "order"), None
    )
    assert service is not None, result["app_resources"]
    assert [r["name"] for r in service["resources"]] == ["order-api"]
    assert result["aliases"]["order"] == "services/product/order"
    assert result["paths"]["services/product/order"] == "order"


def _assert_yaml_shadow(manifest_dir: Path):
    yaml = pytest.importorskip("yaml")
    shadow = manifest_dir / ".autogenerated" / "service.yaml"
    parsed = yaml.safe_load(shadow.read_text())
    assert parsed["appName"] == "order-api"
    assert parsed["homepage"] == "https://a.example/order"


@needs_tilt
def test_single_scan_and_exported_shape_posix(tmp_path):
    pytest.importorskip("yaml")
    project = tmp_path / "proj"
    project.mkdir()
    manifest_dir = _write_project(project)
    out, result = _run_registry(project, portable=False)
    _assert_single_scan_output(out, result)
    _assert_yaml_shadow(manifest_dir)


@needs_tilt
def test_single_scan_and_exported_shape_portable(tmp_path):
    pytest.importorskip("yaml")
    project = tmp_path / "proj"
    project.mkdir()
    manifest_dir = _write_project(project)
    out, result = _run_registry(project, portable=True)
    _assert_single_scan_output(out, result)
    _assert_yaml_shadow(manifest_dir)


def test_generated_tiltfiles_set_the_project_root_before_the_registry_loads():
    """Discovery populates APP_RESOURCES at registry load, and only when FLISK_PROJECT_ROOT is set.

    The generated Tiltfile must set it before it loads the extension that pulls the registry in,
    so consumers reading the module variables (or the lazy getters) see the discovered services.
    """
    for rel, root_marker, load_marker in (
        ("cli/templates/Tiltfile.hbs", "os.environ['FLISK_PROJECT_ROOT']", "load('ext://flisk-cli'"),
    ):
        text = (REPO_ROOT / rel).read_text()
        assert root_marker in text, f"{rel} no longer sets FLISK_PROJECT_ROOT"
        assert load_marker in text, f"{rel} no longer loads the extension"
        assert text.index(root_marker) < text.index(load_marker), (
            f"{rel} loads the extension before setting FLISK_PROJECT_ROOT, so discovery would run empty"
        )
