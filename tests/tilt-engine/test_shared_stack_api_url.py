"""Two backends in one stack get distinct API_URLs and distinct default Traefik paths (#392).

`orders-api` and `billing-api` in stack `shop` used to share `/api/shop-management`: the generated
`.env.backend.autogenerated` wrote the same `API_URL` for both, and `compose.star` defaulted both
`traefik.pathPrefix` values to the same stack path. The route and the env URL are now keyed off the
resource name -- the same path the `<name>-project` router serves and `flisk up` prints -- and the
stack path stays only as the fallback for manifests without `appName`.

The executed cases run the real Starlark through Tilt's interpreter (`tilt alpha tiltfile-result`);
the source cases keep checking the contract when the tilt CLI is not installed.

Spec / Issue: https://github.com/flisk-sh/flisk/issues/392
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
GENERATORS = (
    REPO_ROOT
    / "runtime"
    / "engine"
    / "topologies"
    / "tilt"
    / "resources"
    / "orchestrator"
    / "generators"
)
ENV_STAR = GENERATORS / "env.star"
COMPOSE_STAR = (
    REPO_ROOT
    / "runtime"
    / "engine"
    / "topologies"
    / "platform"
    / "docker"
    / "compose"
    / "compose.star"
)

RESULT_MARKER = "Error in fail: RESULT"
TILT_REQUIRED = pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")
pytestmark = [pytest.mark.generator]


def run_tilt(project_root: Path, body: str, project_name: str = "shop") -> str:
    """Evaluate `body` in a minimal Flisk project and return stdout+stderr (the body calls fail('RESULT'...))."""
    (project_root / ".flisk").mkdir(parents=True, exist_ok=True)
    (project_root / ".flisk" / "project.json").write_text(json.dumps({"project": {"name": project_name}}))
    tiltfile = project_root / "Tiltfile"
    tiltfile.write_text(body.replace("@ENV_STAR", str(ENV_STAR)).replace("@COMPOSE_STAR", str(COMPOSE_STAR)))
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tiltfile)],
        capture_output=True,
        text=True,
        timeout=180,
        cwd=project_root,
        env={**os.environ, "FLISK_PROJECT_ROOT": str(project_root)},
    )
    return proc.stdout + proc.stderr


def result_json(output: str) -> dict:
    assert RESULT_MARKER in output, output[-3000:]
    return json.loads(output.split(RESULT_MARKER, 1)[1].strip())


def env_line(env_text: str, name: str) -> str:
    return next(line.split("=", 1)[1] for line in env_text.splitlines() if line.startswith(name + "="))


ENV_BODY = """load('@ENV_STAR', 'EnvGenerators')
def gen(**extra):
    manifest = {'appType': 'backend', 'stack': 'shop', '_resource_path': 'services/product/shop/x'}
    manifest.update(extra)
    return EnvGenerators.generate_env_file(manifest, None, None)
r = {
    'orders': gen(appName='orders-api', port=4001),
    'billing': gen(appName='billing-api', port=4002),
    'no_name': gen(port=4003),
    'explicit': gen(appName='ledger-api', apiPath='/api/v2/ledger', port=4004),
}
fail('RESULT' + encode_json(r))
"""

COMPOSE_BODY = """load('@COMPOSE_STAR', 'generate_backend_compose_entry')
def gen(name, **extra):
    manifest = {'appType': 'backend', 'stack': 'shop', 'port': 4001}
    manifest.update(extra)
    res = {'name': name, '_resource_path': 'services/product/shop/' + name}
    return generate_backend_compose_entry('services/product/shop', 'shop', res, manifest)
r = {
    'orders': gen('orders-api', appName='orders-api'),
    'billing': gen('billing-api', appName='billing-api'),
    'no_name': gen('legacy-backend'),
    'prefixed': gen('webhook-api', appName='webhook-api', traefik={'pathPrefix': '/api/custom-hook'}),
}
fail('RESULT' + encode_json(r))
"""


def _primary_router_rule(entry: str, project: str, name: str) -> str:
    """The Host+path rule of the service's own router (not the -project or -management compat routers)."""
    prefix = f'traefik.http.routers.{project}-{name}.rule='
    matches = [line.split("=", 1)[1].strip('"') for line in entry.splitlines() if line.strip().startswith('- "' + prefix)]
    assert len(matches) == 1, f"expected one primary router rule for {name}, got {matches}"
    return matches[0]


@TILT_REQUIRED
def test_two_backends_one_stack_get_distinct_api_urls(tmp_path):
    env_files = result_json(run_tilt(tmp_path / "proj", ENV_BODY))
    orders_url = env_line(env_files["orders"], "API_URL")
    billing_url = env_line(env_files["billing"], "API_URL")
    assert orders_url != billing_url
    # The same /api/<name> route the <name>-project router serves and `flisk up` prints (-api stripped).
    assert orders_url.endswith("/api/orders")
    assert billing_url.endswith("/api/billing")


@TILT_REQUIRED
def test_backend_without_app_name_keeps_the_stack_api_url(tmp_path):
    env_files = result_json(run_tilt(tmp_path / "proj", ENV_BODY))
    assert env_line(env_files["no_name"], "API_URL").endswith("/api/shop-management")


@TILT_REQUIRED
def test_backend_api_url_honours_an_explicit_api_path(tmp_path):
    env_files = result_json(run_tilt(tmp_path / "proj", ENV_BODY))
    assert env_line(env_files["explicit"], "API_URL").endswith("/api/v2/ledger")


@TILT_REQUIRED
def test_two_backends_one_stack_get_distinct_traefik_paths(tmp_path):
    entries = result_json(run_tilt(tmp_path / "proj", COMPOSE_BODY, project_name="testproj"))
    orders_rule = _primary_router_rule(entries["orders"], "testproj", "orders-api")
    billing_rule = _primary_router_rule(entries["billing"], "testproj", "billing-api")
    assert orders_rule != billing_rule
    assert "/api/orders" in orders_rule
    assert "/api/billing" in billing_rule
    assert "/api/shop-management" not in orders_rule


@TILT_REQUIRED
def test_compose_path_falls_back_to_the_stack_route_without_app_name(tmp_path):
    entries = result_json(run_tilt(tmp_path / "proj", COMPOSE_BODY, project_name="testproj"))
    rule = _primary_router_rule(entries["no_name"], "testproj", "legacy-backend")
    assert "/api/shop-management" in rule


@TILT_REQUIRED
def test_an_explicit_path_prefix_still_wins(tmp_path):
    entries = result_json(run_tilt(tmp_path / "proj", COMPOSE_BODY, project_name="testproj"))
    rule = _primary_router_rule(entries["prefixed"], "testproj", "webhook-api")
    assert "/api/custom-hook" in rule
    assert "/api/webhook" not in rule


