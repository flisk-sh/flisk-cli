def test_env_star_keys_the_backend_url_off_the_resource_name():
    source = ENV_STAR.read_text()
    assert "cli_api_path" in source
    assert "own_api_path" in source


@pytest.mark.fast
def test_compose_star_defaults_the_path_off_the_resource_name():
    source = COMPOSE_STAR.read_text()
    assert "cli_api_path" in source
    assert "default_traefik_path" in source
