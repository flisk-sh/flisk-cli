"""
A scaffolded migrator used to hold 570-960 MB of layers the service image already had (flisk#4070):
its own l3_migration_build stage installed the same dependencies a second time, and its runtime
copied them onto a separate l4-migrator base.

The migrator Dockerfile now emits the service's own l3_production_purger stage (same instructions,
same inputs, so BuildKit builds the install once) and the service's l4-backend base, and the
dependency COPYs are byte-identical to the backend runtime's. What is left unique to the migrator
is the few MB of migrate.sh, the prisma schema and the Alpine tools the entrypoint needs.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = [pytest.mark.generator]
TILT_REQUIRED = pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")

REPO_ROOT = Path(__file__).resolve().parents[2]
PRISMA_DIR = REPO_ROOT / "runtime" / "engine" / "topologies" / "platform" / "docker" / "layers" / "prisma"
GENERATOR = REPO_ROOT / "runtime" / "engine" / "topologies" / "platform" / "docker" / "generators" / "golden_docker_generator_v2.star"
RESULT_MARKER = "Error in fail: RESULT"


def run_starlark(tmp_path: Path, body: str) -> dict:
    tiltfile = tmp_path / "Tiltfile"
    # Starlark string literals reject Windows backslashes (\\g in C:\\github-...), so pass a POSIX-style path to load().
    tiltfile.write_text(body.replace("@PRISMA", PRISMA_DIR.as_posix()) + "\nfail('RESULT' + encode_json(r))\n")
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tiltfile)],
        capture_output=True,
        text=True,
        timeout=180,
        cwd=tmp_path,
        env={**os.environ, "FLISK_PROJECT_ROOT": str(tmp_path)},
    )
    output = proc.stdout + proc.stderr
    assert RESULT_MARKER in output, output[-3000:]
    return json.loads(output.split(RESULT_MARKER, 1)[1].strip())


def generate(tmp_path: Path, res_type: str, resource_name: str, res_path: str | None = None) -> str:
    """The Dockerfile the orchestrator emits for a resource, with its service dir scaffolded."""
    res_path = res_path or f"services/main/{resource_name}"
    (tmp_path / res_path / ".autogenerated").mkdir(parents=True, exist_ok=True)
    result = run_starlark(
        tmp_path,
        f"load({json.dumps(str(GENERATOR))}, 'L4_generate_orchestrator')\n"
        f"r = {{'df': L4_generate_orchestrator('{res_path}', res_type='{res_type}', resource_name='{resource_name}', "
        "use_prisma=True, use_golden=True)}\n",
    )
    return result["df"]


def stage(dockerfile: str, name: str) -> str:
    """The instructions of one `FROM ... AS <name>` stage, up to the next FROM or end of file."""
    marker = f"AS {name}"
    start = dockerfile.index("FROM ", dockerfile.index(marker) - 60)
    rest = dockerfile[start:]
    nxt = rest.find("\nFROM ", 1)
    block = rest[:nxt] if nxt != -1 else rest
    # The next stage's `# ---- ... ----` comment line sits between the boundary FROM and this
    # stage's last instruction; it is not part of the stage being compared.
    lines = block.splitlines()
    while lines and (lines[-1].startswith("#") or not lines[-1].strip()):
        lines.pop()
    return "\n".join(lines) + "\n"


@TILT_REQUIRED
def test_migrator_emits_the_same_dependency_stage_as_the_service(tmp_path):
    # Identical instructions against identical inputs: BuildKit computes one snapshot for both
    # images, so the install runs once per service, not once per service plus once per migrator.
    backend = generate(tmp_path, "backend", "api")
    migrator = generate(tmp_path, "migrator", "api", res_path="services/main/api")
    assert stage(migrator, "l3_production_purger") == stage(backend, "l3_production_purger")
    assert "l3_migration_build" not in migrator


@TILT_REQUIRED
def test_migrator_runtime_reuses_the_services_dependency_layers(tmp_path):
    backend = generate(tmp_path, "backend", "api")
    migrator = generate(tmp_path, "migrator", "api", res_path="services/main/api")
    mig_stage = stage(migrator, "l4_migrator_runtime")
    back_stage = stage(backend, "l4_backend_runtime")

    def copy_lines(text: str) -> list[str]:
        return [
            line
            for line in text.splitlines()
            if line.startswith("COPY") and ("--from=l3_production_purger" in line or "package.json" in line)
        ]

    # Every dependency COPY the backend emits appears verbatim in the migrator stage.
    for line in copy_lines(back_stage):
        assert line in mig_stage, line
    # The base image is the service's: the whole prefix of the migrator image is shared.
    assert mig_stage.splitlines()[0] == back_stage.splitlines()[0].replace("l4_backend_runtime", "l4_migrator_runtime")
    assert "l4-migrator" not in mig_stage


@TILT_REQUIRED
def test_migrator_runtime_is_a_thin_delta_over_the_shared_layers(tmp_path):
    migrator = generate(tmp_path, "migrator", "api", res_path="services/main/api")
    mig_stage = stage(migrator, "l4_migrator_runtime")
    run_lines = [line for line in mig_stage.splitlines() if line.startswith("RUN")]
    # No install, add or generate of its own: the only RUNs are the small fixes and the
    # migrate.sh/tools setup every migrator needs.
    assert all("bun install" not in line and "bun add" not in line and "bunx" not in line for line in run_lines), run_lines
    assert all("prisma generate" not in line for line in run_lines), run_lines
    assert [line for line in run_lines if "apk add" in line] == ["RUN apk add --no-cache curl jq netcat-openbsd"]
    assert 'ENTRYPOINT ["/app/migrate.sh"]' in mig_stage
    assert "HEALTHCHECK NONE" in mig_stage
    assert "WORKDIR /app/services/main/api" in mig_stage
    assert "FROM l4_migrator_runtime AS migrator" in migrator


@TILT_REQUIRED
@pytest.mark.parametrize("use_golden,expected", [("True", "-l4-backend"), ("False", "oven/bun")])
def test_migrator_base_matches_the_service_base(tmp_path, use_golden, expected):
    result = run_starlark(
        tmp_path,
        "load('@PRISMA/prisma_runtime.star', 'L4_generate_migrator_runtime')\n"
        "r = {'runtime': L4_generate_migrator_runtime('services/main/mig', 'mig', " + use_golden + ")}\n",
    )
    from_line = [line for line in result["runtime"].splitlines() if line.startswith("FROM")][0]
    assert expected in from_line


@TILT_REQUIRED
def test_pin_step_skips_bun_add_when_the_cli_is_already_installed_and_never_installs_dev_dependencies(tmp_path):
    # `bun add` after `bun install --production` installs devDependencies too: biome, typescript, vitest, vite and their native
    # binaries (about 330 MB) ended up in the migrator and the backend (flisk#3709). The add now carries --production as well
    # (flisk#3832).
    result = run_starlark(
        tmp_path,
        "load('@PRISMA/prisma_build.star', 'prisma_cli_pin_step')\n"
        "r = {'pin': prisma_cli_pin_step()}\n",
    )
    run = [line for line in result["pin"].splitlines() if line.startswith("RUN")]
    assert len(run) == 1, run
    assert "node_modules/prisma/package.json" in run[0]
    assert "until grep -Eq" in run[0] and "node_modules/prisma/package.json" in run[0]
    assert "bun add --production --no-save --exact prisma@" in run[0]


@TILT_REQUIRED
def test_a_name_migrator_service_uses_the_sibling_services_path(tmp_path):
    # `flisk resource --feature prisma` scaffolds <service>-migrator next to <service>; resolving
    # the sibling makes its stages identical to the service's even though it lives in its own dir.
    (tmp_path / "services" / "main" / "api").mkdir(parents=True)
    migrator = generate(tmp_path, "backend", "api-migrator")
    mig_stage = stage(migrator, "l4_migrator_runtime")
    assert "WORKDIR /app/services/main/api\n" in mig_stage
    assert "COPY --from=l3_production_purger /app/services/main/api/node_modules ./node_modules" in mig_stage
    assert "api-migrator" not in stage(migrator, "l3_production_purger")


@TILT_REQUIRED
def test_a_migrator_without_a_sibling_service_keeps_its_own_path(tmp_path):
    # A standalone migrator (no services/main/solo dir) still builds on its own files.
    migrator = generate(tmp_path, "backend", "solo-migrator")
    assert "WORKDIR /app/services/main/solo-migrator" in stage(migrator, "l4_migrator_runtime")


@TILT_REQUIRED
def test_node_modules_is_not_rewritten_by_a_later_chown_r(tmp_path):
    # `chown -R` over a directory a COPY has just put in the image stores every file again in a
    # new layer; only node_modules/.prisma, the directory `prisma generate` writes to, is chowned.
    result = run_starlark(
        tmp_path,
        "load('@PRISMA/filesystem_setup.star', 'prisma_dir_and_permissions')\n"
        "load('@PRISMA/prisma_runtime.star', 'L4_generate_migrator_runtime')\n"
        "r = {'perm': prisma_dir_and_permissions('/app/services/main/mig'), "
        "'runtime': L4_generate_migrator_runtime('services/main/mig', 'mig', False)}\n",
    )
    chown_r = [line.split("chown -R", 1)[1] for line in result["perm"].splitlines() if "chown -R" in line]
    assert chown_r, "the prisma directory ownership fix is expected to remain"
    for part in chown_r:
        node_modules_mentions = [p for p in part.split() if "node_modules" in p]
        assert node_modules_mentions and all(p.endswith("/node_modules/.prisma") for p in node_modules_mentions), part
    mig_stage = stage(result["runtime"], "l4_migrator_runtime")
    chown_lines = [line for line in mig_stage.splitlines() if "chown -R" in line]
    for line in chown_lines:
        after = line.split("chown -R", 1)[1].replace("/node_modules/.prisma", "")
        assert "node_modules" not in after, line


@TILT_REQUIRED
def test_migrator_runtime_does_not_copy_prisma_packages_a_second_time(tmp_path):
    # The relink step replaced the @prisma/client, adapter-pg and engines symlinks with `cp -R` copies in a RUN of their own, so
    # 98 MB were stored twice in a scaffolded migrator (flisk#4070). The symlinks that arrive with the node_modules COPY resolve
    # as they are, and a migration still completes.
    result = run_starlark(
        tmp_path,
        "load('@PRISMA/prisma_runtime.star', 'L4_generate_migrator_runtime')\n"
        "r = {'runtime': L4_generate_migrator_runtime('services/main/mig', 'mig', False)}\n",
    )
    assert "prisma-runtime-relink" not in result["runtime"]
    assert "cp -R" not in result["runtime"]


@TILT_REQUIRED
def test_prisma_config_is_copied_when_the_generated_file_exists_and_inlined_otherwise(tmp_path):
    # The backend COPYs prisma.config.autogenerated.ts; the migrator does the same when the file
    # is already generated (one more shared layer), and falls back to the inline heredoc otherwise.
    cfg = tmp_path / "services" / "main" / "api" / ".autogenerated" / "prisma.config.autogenerated.ts"
    cfg.parent.mkdir(parents=True, exist_ok=True)
    cfg.write_text("export default {};\n")
    with_copy = generate(tmp_path, "migrator", "api", res_path="services/main/api")
    assert "COPY services/main/api/.autogenerated/prisma.config.autogenerated.ts ./prisma.config.ts" in with_copy
    cfg.unlink()
    without = generate(tmp_path, "migrator", "api", res_path="services/main/api")
    assert "RUN cat > /app/services/main/api/prisma.config.ts" in without
    assert "process.env.DATABASE_URL" in without


@TILT_REQUIRED
def test_migrate_sh_runs_the_pinned_cli_from_the_service_tree(tmp_path):
    # migrate.sh cds into /app/<res_path> and calls node_modules/.bin/prisma there: the pinned CLI
    # the shared purger stage left in node_modules, not a bunx fetch of prisma@latest.
    result = run_starlark(
        tmp_path,
        "load('@PRISMA/migrate_script.star', 'migrate_sh_content')\n"
        "r = {'sh': migrate_sh_content('mig', '/app/services/main/mig')}\n",
    )
    assert 'PRISMA_BIN="/app/services/main/mig/node_modules/.bin/prisma"' in result["sh"]
    assert 'cd /app/services/main/mig && "$PRISMA_BIN" migrate deploy' in result["sh"]
    assert '"$PRISMA_BIN" generate' in result["sh"]
