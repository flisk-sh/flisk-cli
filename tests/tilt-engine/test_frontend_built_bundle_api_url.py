def test_the_env_file_name_agrees_between_the_writer_and_the_build_stage():
    """env.star writes the file under one literal name and the build stage COPYs it under another;
    if either spelling drifts the Vite build silently loses VITE_API_URL again."""
    env_star = ENV_STAR.read_text()
    written = re.search(r"OUTPUT\.AUTOGENERATED_FOLDER \+ '/([^']*\.env\.frontend[^']*)'", env_star)
    assert written, "env.star no longer writes a .env.frontend* file under .autogenerated"
    builder = L3_STAR.read_text().split("def L3_generate_frontend_builder", 1)[1]
    assert "/" + written.group(1) + " ./.env" in builder.split('"RUN ', 1)[0]


def _match_segments(pattern: list[str], path: list[str]) -> bool:
    """Go filepath.Match per segment: `*` and `?` never cross `/`, `**` spans zero or more whole segments."""
    while pattern:
        head = pattern[0]
        if head == "**":
            return any(_match_segments(pattern[1:], path[index:]) for index in range(len(path) + 1))
        if not path or not fnmatchcase(path[0], head):
            return False
        pattern = pattern[1:]
        path = path[1:]
    return not path


def _dockerignore_excludes(dockerignore: str, path: str) -> bool:
    """True when `path` stays out of the build context under Docker .dockerignore semantics.

    Patterns are anchored at the context root; `!` re-includes what an earlier pattern excluded,
    and a pattern matching a directory decides its whole subtree, so the deepest matching
    ancestor-or-self wins (the last rule wins inside one level).
    """
    rules = []
    for raw in dockerignore.splitlines():
        pattern = raw.strip()
        if not pattern or pattern.startswith("#"):
            continue
        negated = pattern.startswith("!")
        if negated:
            pattern = pattern[1:].strip()
        pattern = pattern.strip("/")
        if pattern:
            rules.append((pattern, negated))

    segments = path.split("/")
    excluded = False
    for end in range(1, len(segments) + 1):
        candidate = segments[:end]
        hit = False
        verdict = False
        for pattern, negated in rules:
            if _match_segments(pattern.split("/"), candidate):
                hit = True
                verdict = not negated
        if hit:
            excluded = verdict
    return excluded


def test_dockerignore_rule_evaluation():
    rules = "*\n!keep/me\nkeep/me/.env.*\n**/*.tmp\n"
    assert _dockerignore_excludes(rules, "drop/this.txt")  # `*` hides a root dir nothing re-includes
    assert not _dockerignore_excludes(rules, "keep/me/src/app.ts")  # `!` re-includes a subtree under `*`
    assert _dockerignore_excludes(rules, "keep/me/.env.local")
    assert not _dockerignore_excludes(rules, "keep/me/.autogenerated/.env.frontend.autogenerated")
    assert _dockerignore_excludes(rules, "deep/down/out.tmp")  # `**` spans directories


@needs_tilt
def test_the_frontend_dockerignore_keeps_the_env_file_in_the_build_context(tmp_path):
    """The `.env` and `.env.*` rules in the generated .dockerignore are anchored at the context root, so they
    cannot hide the nested env file the build stage COPYs. A `**/.env*` variant would; evaluate the real rules."""
    dockerignore = _run(
        tmp_path,
        f"load('{DOCKERIGNORE_STAR}', 'generate_dockerignore')\n"
        + "fail('RESULT' + encode_json({'dockerignore': generate_dockerignore('services/main/web', 'frontend')}))\n",
    )["dockerignore"]
    # Sanity-check the evaluator on the real rules: root .env files stay ignored, the exception still works.
    assert _dockerignore_excludes(dockerignore, ".env.local")
    assert not _dockerignore_excludes(dockerignore, ".env.example")
    assert _dockerignore_excludes(dockerignore, "node_modules/leftpad/index.js")
    assert not _dockerignore_excludes(dockerignore, ENV_FILE_PATH)


@needs_tilt
def test_the_image_prebuild_dockerignore_keeps_the_env_file_in_the_build_context(tmp_path):
    """The `<name>-image` step builds with its own allowlist .dockerignore (`*` + `!dir`, see
    TypescriptBuilders.prebuild_dockerignore); the env file rides along under the service dir."""
    dockerignore = _run(
        tmp_path,
        f"load('{DOCKERIGNORE_STAR}', 'generate_dockerignore')\n"
        + "fail('RESULT' + encode_json({'dockerignore': generate_dockerignore('services/main/web', 'frontend')}))\n",
    )["dockerignore"]
    dockerfile = "services/main/web/.autogenerated/Dockerfile.app.autogenerated"
    ignore_file = tmp_path / (dockerfile + ".dockerignore")
    ignore_file.parent.mkdir(parents=True, exist_ok=True)
    ignore_file.write_text(dockerignore)
    prebuild = _run(
        tmp_path,
        f"load('{TYPESCRIPT_STAR}', 'TypescriptBuilders')\n"
        + "fail('RESULT' + encode_json({'ignore': TypescriptBuilders.prebuild_dockerignore("
        + "'" + dockerfile + "', '', 'services/main/web')}))\n",
    )["ignore"]
    assert _dockerignore_excludes(prebuild, "cli/package.json")  # `*` drops everything not allow-listed
    assert _dockerignore_excludes(prebuild, "services/main/web/node_modules/leftpad/index.js")
    assert _dockerignore_excludes(prebuild, "services/main/web/.env.local")
    assert not _dockerignore_excludes(prebuild, "services/main/web/package.json")
    assert not _dockerignore_excludes(prebuild, ENV_FILE_PATH)
