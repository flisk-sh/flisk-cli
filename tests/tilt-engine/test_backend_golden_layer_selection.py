"""
flisk#3833 option 1: the L3 base image is chosen from the service folder.

A backend with no `prisma/` directory starts from the Prisma-free `l3-backend`; a backend that
has one starts from `l3-backend-prisma`. Migrators share the L2-based production-purger
stage and its pinned Prisma CLI with the backend runtime.

The generator tests execute the real Starlark through Tilt's interpreter. Source-level tests
below also run when Tilt is not installed locally.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = [pytest.mark.generator]
TILT_REQUIRED = pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")

REPO_ROOT = Path(__file__).resolve().parents[2]
DOCKER_DIR = REPO_ROOT / "runtime" / "engine" / "topologies" / "platform" / "docker"
GENERATOR = DOCKER_DIR / "generators" / "golden_docker_generator_v2.star"
BUILDERS = DOCKER_DIR / "layers" / "l3_builder_layers.star"
PRISMA_CONSTANTS = DOCKER_DIR / "layers" / "prisma" / "constants.star"
RESULT_MARKER = "Error in fail: RESULT"


def generate(tmp_path: Path, res_type: str, resource_name: str, prisma_dir: bool = False) -> str:
    """Render a Dockerfile with the real generator; optionally give the service a prisma/ folder."""
    svc = tmp_path / "services" / "main" / resource_name
    (svc / ".autogenerated").mkdir(parents=True)
    if prisma_dir:
        (svc / "prisma").mkdir()

    tiltfile = tmp_path / "Tiltfile"
    tiltfile.write_text(
        f"load({json.dumps(str(GENERATOR))}, 'L4_generate_orchestrator')\n"
        f"r = L4_generate_orchestrator('services/main/{resource_name}', res_type={res_type!r}, "
        f"resource_name={resource_name!r}, use_prisma=True, use_golden=True)\n"
        "fail('RESULT' + encode_json(r))\n"
    )
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tiltfile)],
        capture_output=True,
        text=True,
        cwd=tmp_path,
        env={**os.environ, "FLISK_PROJECT_ROOT": str(tmp_path)},
        timeout=180,
    )
    output = proc.stdout + proc.stderr
    assert RESULT_MARKER in output, output[-3000:]
    return json.loads(output.split(RESULT_MARKER, 1)[1].strip())


@TILT_REQUIRED
def test_plain_backend_uses_the_prisma_free_layer(tmp_path):
    dockerfile = generate(tmp_path, "backend", "plain-api")
    assert "FROM flisk-project-l3-backend:latest AS l3_backend_build" in dockerfile
    assert "-l3-backend-prisma" not in dockerfile


@TILT_REQUIRED
def test_backend_with_prisma_folder_uses_the_prisma_layer(tmp_path):
    dockerfile = generate(tmp_path, "backend", "orders-api", prisma_dir=True)
    assert "FROM flisk-project-l3-backend-prisma:latest AS l3_backend_build" in dockerfile
    assert "FROM flisk-project-l3-backend:latest" not in dockerfile


@TILT_REQUIRED
def test_migrator_uses_the_shared_l2_purger_and_pinned_prisma(tmp_path):
    dockerfile = generate(tmp_path, "migrator", "orders-migrator", prisma_dir=True)
    assert "FROM flisk-project-l2:latest AS l3_production_purger" in dockerfile
    assert "-l3-backend-prisma" not in dockerfile
    assert "bun install --production" in dockerfile
    assert 'bun add --production --no-save --exact prisma@"$PRISMA_VERSION"' in dockerfile
    assert "node_modules/@prisma/client/package.json" in dockerfile
    assert "COPY --from=l3_production_purger" in dockerfile


def test_selection_uses_the_service_folder_check():
    """Keep the runtime choice tied to the same `dir_exists(.../prisma)` check the migrator uses."""
    constants = PRISMA_CONSTANTS.read_text(encoding="utf-8")
    assert "load('../../../../../../discovery/native_windows.star', 'dir_exists')" in constants
    assert "def service_has_prisma_dir(res_path):" in constants
    assert "return dir_exists(res_path + '/' + PRISMA_DIR_NAME)" in constants

    builders = BUILDERS.read_text(encoding="utf-8")
    assert "GOLDEN_L3_BACKEND_PRISMA_IMAGE" in builders
    assert "def backend_golden_image(res_path, use_golden = True):" in builders
    assert "if service_has_prisma_dir(res_path):" in builders

    generator = GENERATOR.read_text(encoding="utf-8")
    assert "base_image=backend_golden_image(res_path, use_golden)" in generator
