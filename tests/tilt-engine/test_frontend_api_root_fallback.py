"""A frontend with no backend of its own gets a route that exists (#3648).

`flisk resource web --type frontend --stack shop` writes no `backendName` and no API `dependsOn`, so the generated
`VITE_API_URL` fell back to `/api/<stack>-management`. With two or more APIs in the stack the engine drops that route
(Traefik could not tell the APIs apart), so the address answered 404. Such a frontend now gets the API root (`/api`),
under which every API answers at `/<name>`; a one-API stack keeps its stack route and `backendName` keeps the
backend's own path.

Runs the real resolver and generators through Tilt's interpreter (`tilt alpha tiltfile-result`) against a project the
test lays out, so discovery returns the same resources `flisk up` sees.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = [pytest.mark.fast, pytest.mark.generator]
TILT_REQUIRED = pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")

REPO_ROOT = Path(__file__).resolve().parents[2]
TOPOLOGIES = REPO_ROOT / "runtime" / "engine" / "topologies"
GENERATORS = TOPOLOGIES / "tilt" / "resources" / "orchestrator" / "generators"
RESOLVER_STAR = GENERATORS / "dependencies" / "resolver.star"
ENV_STAR = GENERATORS / "env.star"
FRONTEND_STAR = GENERATORS / "frontend.star"
TRAEFIK_HELPERS_STAR = TOPOLOGIES / "platform" / "docker" / "networking" / "traefik_helpers.star"
RESULT_MARKER = "Error in fail: RESULT"

WEB = "services/product/shop/web"

SERVICE_JSONS = {
    # stack `shop`: one backend-less frontend and two APIs, the issue's reproduction.
    f"{WEB}/service.json": {"appName": "web", "appType": "frontend", "stack": "shop", "port": 3000},
    "services/product/shop/catalog-api/service.json": {
        "appName": "catalog-api",
        "appType": "backend",
        "stack": "shop",
        "port": 4001,
    },
    "services/product/shop/orders-api/service.json": {
        "appName": "orders-api",
        "appType": "backend",
        "stack": "shop",
        "port": 4002,
    },
    # stack `solo`: the one-API case keeps the stack route.
    "services/product/solo/web/service.json": {"appName": "web", "appType": "frontend", "stack": "solo", "port": 3010},
    "services/product/solo/api/service.json": {"appName": "api", "appType": "backend", "stack": "solo", "port": 4010},
}

# as_posix: a Windows path's backslashes would be invalid escape sequences in the Starlark strings below.
BODY = f"""
load('{RESOLVER_STAR.as_posix()}', 'resolve_frontend_api_path')
load('{ENV_STAR.as_posix()}', 'EnvGenerators')
load('{FRONTEND_STAR.as_posix()}', 'FrontendGenerators')
load('{TRAEFIK_HELPERS_STAR.as_posix()}', 'get_api_path')

# The manifest the generators see: normalized, so `stack` is present and no backendName was derived (`web` does not
# end in -frontend). `_resource_path` is what manifest_resource.star stamps on it before calling the generators.
web = {{'appType': 'frontend', 'stack': 'shop', 'appName': 'web', 'port': 3000, '_resource_path': '{WEB}'}}
web_named = dict(web, backendName='orders-api')
web_dep = dict(web, dependsOn=['catalog-api'])
solo_web = {{'appType': 'frontend', 'stack': 'solo', 'appName': 'web', 'port': 3010, '_resource_path': 'services/product/solo/web'}}

out = {{}}
def write(path, content):
    out[path] = content

EnvGenerators.generate_env_file(web, None, write)
FrontendGenerators.generate_all(web, write)

r = {{
    'paths': {{
        'multi': resolve_frontend_api_path(web, get_api_path('shop')),
        'backend_name': resolve_frontend_api_path(web_named, get_api_path('shop')),
        'depends_on': resolve_frontend_api_path(web_dep, get_api_path('shop')),
        'solo': resolve_frontend_api_path(solo_web, get_api_path('solo')),
    }},
    'env_file': out['{WEB}/.autogenerated/.env.frontend.autogenerated'],
    'env_ts': out['{WEB}/.autogenerated/env.ts'],
    'api_client': out['{WEB}/.autogenerated/api-client.ts'],
}}

# With the gateway moved off port 80 the generated .ts fallbacks and the env file carry FLISK_HTTP_PORT like the
# running stack does (#3647). Generated after the portless outputs above, in the same run, so both cases see the
# same discovered resources.
os.environ['FLISK_HTTP_PORT'] = '8084'
dep_moved = FrontendGenerators.generate_all(web_dep)
web_moved = FrontendGenerators.generate_all(web)
r['moved_port'] = {{
    'dep_env_file': EnvGenerators.generate_env_file(web_dep, None, None),
    'dep_env_ts': dep_moved['env.ts'],
    'dep_api_client': dep_moved['api-client.ts'],
    'web_env_ts': web_moved['env.ts'],
    'web_api_client': web_moved['api-client.ts'],
}}
os.environ.pop('FLISK_HTTP_PORT', None)

fail('RESULT' + encode_json(r))
"""


@pytest.fixture(scope="module")
def result(tmp_path_factory) -> dict:
    if shutil.which("tilt") is None:
        pytest.skip("tilt CLI not installed")
    project_root = tmp_path_factory.mktemp("shop")
    (project_root / ".flisk").mkdir(parents=True)
    (project_root / ".flisk" / "project.json").write_text(json.dumps({"project": {"name": "shop"}}))
    for rel_path, manifest in SERVICE_JSONS.items():
        manifest_path = project_root / rel_path
        manifest_path.parent.mkdir(parents=True, exist_ok=True)
        manifest_path.write_text(json.dumps(manifest))
    (project_root / "Tiltfile").write_text(BODY)
    # The registry runs discovery while its modules load, so FLISK_PROJECT_ROOT has to be in the process environment.
    env = {**os.environ, "FLISK_PROJECT_ROOT": project_root.as_posix()}
    env.pop("FLISK_HTTP_PORT", None)
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(project_root / "Tiltfile")],
        capture_output=True,
        text=True,
        timeout=180,
        cwd=project_root,
        env=env,
    )
    output = proc.stdout + proc.stderr
    assert RESULT_MARKER in output, output[-4000:]
    return json.loads(output.split(RESULT_MARKER, 1)[1].strip())


@TILT_REQUIRED
def test_frontend_with_two_apis_and_no_backend_gets_the_api_root(result):
    # The reproduction: /api/shop-management has no route, /api is the root every API answers under.
    assert result["paths"]["multi"] == "/api"


@TILT_REQUIRED
def test_frontend_with_one_api_keeps_the_stack_route(result):
    assert result["paths"]["solo"] == "/api/solo-management"


@TILT_REQUIRED
def test_backend_name_keeps_that_backends_route_even_in_a_shared_stack(result):
    assert result["paths"]["backend_name"] == "/api/orders"


@TILT_REQUIRED
def test_depends_on_api_keeps_that_backends_route_even_in_a_shared_stack(result):
    assert result["paths"]["depends_on"] == "/api/catalog"


@TILT_REQUIRED
def test_env_file_vite_api_url_is_the_api_root_not_a_dead_route(result):
    assert "VITE_API_URL=http://api.shop.localhost/api\n" in result["env_file"]
    assert "shop-management" not in result["env_file"]


@TILT_REQUIRED
def test_env_ts_and_api_client_fallbacks_are_the_api_root(result):
    assert "shop-management" not in result["env_ts"]
    assert "shop-management" not in result["api_client"]
    assert "|| 'http://api.shop.localhost/api'" in result["env_ts"]
    assert "|| 'http://api.shop.localhost/api'" in result["api_client"]


@TILT_REQUIRED
def test_ts_fallbacks_carry_a_moved_router_port(result):
    # #3647: with the gateway on :8084 the generated .ts fallbacks keep the port, the env file's rule.
    moved = result["moved_port"]
    assert "|| 'http://api.shop.localhost:8084/api'" in moved["web_env_ts"]
    assert "|| 'http://api.shop.localhost:8084/api'" in moved["web_api_client"]


@TILT_REQUIRED
def test_depends_on_fallbacks_carry_the_backend_route_and_moved_port(result):
    # The issue's reproduction: a frontend whose backend is catalog-api falls back to that backend's route on
    # api.<project>.localhost with the router port, not a portless URL another project's router would own.
    moved = result["moved_port"]
    assert "VITE_API_URL=http://api.shop.localhost:8084/api/catalog\n" in moved["dep_env_file"]
    assert "|| 'http://api.shop.localhost:8084/api/catalog'" in moved["dep_env_ts"]
    assert "|| 'http://api.shop.localhost:8084/api/catalog'" in moved["dep_api_client"]
